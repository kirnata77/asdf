영입_비용 = 100


숙소_최대인원 = lodge_system.숙소_최대인원


def 숙소_목록(게임상태):
    return 게임상태.setdefault("모험단숙소", [])


def 주점_현황(게임상태):
    return {
        "파티인원": len(게임상태["파티"]["파티원"]),
        "파티최대": party_system.파티_최대인원,
        "숙소인원": len(숙소_목록(게임상태)),
        "숙소최대": 숙소_최대인원,
        "골드": 게임상태["소지품"].get("골드", 0),
    }


def _영입_이름(게임상태, 입력이름, 직업):
    """새 동료 이름. 입력은 _새_게임_이름목록과 같은 규칙으로 자른다. 비우면
    직업명, 이미 있으면 직업명+A~D 중 빈 것. 파티+숙소 이름과 겹치면 ValueError
    (장비/전투가 이름으로 캐릭터를 구분한다)."""
    있는이름 = {c["캐릭터명"] for c in 게임상태["파티"]["파티원"] + 숙소_목록(게임상태)}
    이름 = 이름_자르기((입력이름 or "").strip())
    if not 이름:
        후보 = [직업] + [f"{직업}{글자}" for 글자 in "ABCD"]
        이름 = next((n for n in 후보 if n not in 있는이름), None)
        if 이름 is None:
            raise ValueError(
                f"'{직업}' 이름이 모두 쓰이고 있습니다. 이름을 입력해 주세요."
            )
    if 이름 in 있는이름:
        raise ValueError(f"이름 '{이름}'이(가) 겹칩니다. 다른 이름을 입력해 주세요.")
    return 이름


def 파티원_영입(게임상태, 입력이름, 직업):
    """영입_비용 골드를 내고 레벨 1 동료를 만든다. 파티에 빈자리가 있으면
    파티로, 없으면 모험단 숙소로. (캐릭터, "파티"|"숙소")를 반환한다.
    골드 부족/이름 겹침/숙소 가득이면 ValueError(아무것도 바뀌지 않는다)."""
    if 직업 not in 직업_레지스트리:
        raise ValueError(f"'{직업}'은(는) 없는 직업이다.")
    if lodge_system.영입_자리(게임상태["파티"], 숙소_목록(게임상태)) is None:
        raise ValueError(f"모험단 숙소가 가득 찼다(최대 {숙소_최대인원}명).")
    if 게임상태["소지품"].get("골드", 0) < 영입_비용:
        raise ValueError(f"골드가 모자란다({영입_비용}골드 필요).")
    캐릭터 = 캐릭터_생성(_영입_이름(게임상태, 입력이름, 직업), 직업)
    자리 = lodge_system.영입(게임상태["파티"], 숙소_목록(게임상태), 캐릭터)
    게임상태["소지품"]["골드"] -= 영입_비용
    # 시작 장비를 소지품 개수에 넣고(장착품_소지품_동기화), 장비 반영 최대치로 채운다.
    equipment_system.장착품_소지품_동기화(플레이어뷰(게임상태))
    장비변경_후처리(게임상태)
    캐릭터["현재HP"] = 캐릭터_최대HP(게임상태, 캐릭터)
    캐릭터["현재MP"] = 캐릭터_최대MP(게임상태, 캐릭터)
    return 캐릭터, 자리


def 파티원_대기(게임상태, 캐릭터):
    """파티원을 모험단 숙소로(파티에는 최소 1명). 실패하면 ValueError."""
    lodge_system.대기(게임상태["파티"], 숙소_목록(게임상태), 캐릭터)
    장비변경_후처리(게임상태)


def 파티원_합류(게임상태, 캐릭터):
    """숙소 동료를 파티로. 실패하면 ValueError."""
    lodge_system.합류(게임상태["파티"], 숙소_목록(게임상태), 캐릭터)
    장비변경_후처리(게임상태)


def 파티원_추방(게임상태, 캐릭터):
    """파티원/숙소 동료를 지운다. 끼고 있던 장비는 소지품에 남는다(파티에는 최소 1명)."""
    lodge_system.추방(게임상태["파티"], 숙소_목록(게임상태), 캐릭터)
    장비변경_후처리(게임상태)
