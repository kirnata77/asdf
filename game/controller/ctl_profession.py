# 봉인해제/봉인변환 규칙은 magic_seal_system.py. 장비해체는 상점에 있던 것을 옮겨 온 것이라
# 함수는 ctl_shop의 상점_해체*를 그대로 쓴다. 장비강화/마법부여는 아직 미구현.

from game.system import magic_seal_system
from game.controller.ctl_party import 플레이어뷰
from game.controller.ctl_equip import 장비변경_후처리

__all__ = [
    "전문직업_메뉴",
    "전문직업_구현됨",
    "전문직업_비용글",
    "전문직업_봉인목록",
    "전문직업_봉인해제",
    "전문직업_봉인변환",
    "_실행",
]

전문직업_메뉴 = ["장비강화", "장비해체", "마법부여", "봉인해제", "봉인변환"]
전문직업_구현됨 = {"장비해체", "봉인해제", "봉인변환"}
전문직업_비용글 = f"{magic_seal_system.비용['골드']}G + 레어 소울 {magic_seal_system.비용['레어 소울']}개"


def 전문직업_봉인목록(게임상태, 모드):
    """[{"이름", "아이템", "탭", "캐릭터", "슬롯", "수량"}] - "봉인해제"는 봉인 장비, "봉인변환"은
    봉인을 푼 마법의 장비. 장착 중인 것(파티원/숙소 동료)은 캐릭터마다 한 줄."""
    return magic_seal_system.대상목록(
        플레이어뷰(게임상태),
        게임상태["상점카탈로그"]["장비"],
        모드,
        숙소=게임상태.get("모험단숙소", []),
    )


def _실행(게임상태, 항목, 처리):
    새이름 = 처리(플레이어뷰(게임상태), 항목)
    if 항목["캐릭터"] is not None:
        장비변경_후처리(게임상태)
    return 새이름


def 전문직업_봉인해제(게임상태, 항목):
    """봉인 장비 하나를 푼다(100G + 레어 소울 1). 새 이름. 모자라면 ValueError."""
    return _실행(게임상태, 항목, magic_seal_system.봉인해제)


def 전문직업_봉인변환(게임상태, 항목):
    """마법의 장비의 마봉능력을 다른 것으로(100G + 레어 소울 1). 새 이름."""
    return _실행(게임상태, 항목, magic_seal_system.봉인변환)
