#
# 실제 구매/판매 로직은 전부 shop_system.py가 갖고 있다. 이 절의 함수들은
# 게임상태(카탈로그/소지품 위치)를 shop_system.py가 기대하는 인자 모양으로
# 맞춰 대신 호출해주는 얇은 어댑터일 뿐이다 - screens_town.py의 상점화면은
# shop_system.py를 직접 부르지 않고 이 함수들만 쓴다.

from game.system import dismantle_system, shop_system
from game.controller.ctl_party import 플레이어뷰

__all__ = [
    "상점_탭목록",
    "상점_보유골드",
    "상점_구매목록",
    "상점_판매목록",
    "상점_구매",
    "상점_해체_탭목록",
    "상점_해체_등급목록",
    "상점_해체목록",
    "상점_해체",
    "상점_일괄해체_대상",
    "상점_일괄해체",
    "상점_판매",
    "상점_대분류목록",
    "상점_최대구매수량",
    "상점_판매가",
]


def 상점_탭목록(대분류):
    return shop_system.탭_목록(대분류)


def 상점_보유골드(게임상태):
    return shop_system.보유_골드(플레이어뷰(게임상태))


def 상점_구매목록(게임상태, 대분류, 탭, 상점판매목록=None):
    return shop_system.구매목록(게임상태["상점카탈로그"], 대분류, 탭, 상점판매목록)


def 상점_판매목록(게임상태, 대분류, 탭):
    return shop_system.판매목록(
        플레이어뷰(게임상태),
        게임상태["상점카탈로그"],
        대분류,
        탭,
    )


def 상점_구매(게임상태, 대분류, 탭, 이름, 수량, 상점판매목록=None):
    """성공하면 지불한 총 골드를 반환한다. 실패(품절/수량 오류/골드
    부족)하면 shop_system.구매_처리()와 동일하게 ValueError를 낸다."""
    return shop_system.구매_처리(
        플레이어뷰(게임상태),
        게임상태["상점카탈로그"],
        대분류,
        탭,
        이름,
        수량,
        상점판매목록=상점판매목록,
    )


상점_해체_탭목록 = dismantle_system.해체_탭목록()


상점_해체_등급목록 = list(dismantle_system.소울_레어도)


def 상점_해체목록(게임상태, 탭):
    """[(장비데이터, 해체가능수량, 부위탭)] - 장착 중이 아닌 보유 장비(dismantle_system).
    탭이 "전체"면 모든 부위."""
    return dismantle_system.해체목록(플레이어뷰(게임상태), 게임상태["상점카탈로그"], 탭)


def 상점_해체(게임상태, 탭, 이름, 수량):
    """장비를 해체해 소울/큐브 조각을 소지품 "재료"에 넣는다. 얻은 {재료: 개수}를
    반환한다. 실패하면 ValueError."""
    return dismantle_system.해체_처리(
        플레이어뷰(게임상태), 게임상태["상점카탈로그"], 탭, 이름, 수량
    )


def 상점_일괄해체_대상(게임상태, 레어도, 탭):
    """[(이름, 수량, 부위탭)] - 일괄해체 확인 팝업용."""
    return dismantle_system.일괄해체_대상(
        플레이어뷰(게임상태), 게임상태["상점카탈로그"], 레어도, 탭
    )


def 상점_일괄해체(게임상태, 레어도, 탭):
    """그 레어도 + 부위(또는 "전체")의 해체 가능한 장비를 전부 해체한다.
    (해체한 수, {재료: 개수}). 대상이 없으면 ValueError."""
    return dismantle_system.일괄해체(
        플레이어뷰(게임상태), 게임상태["상점카탈로그"], 레어도, 탭
    )


def 상점_판매(게임상태, 대분류, 탭, 이름, 수량):
    """성공하면 받은 총 골드를 반환한다. 실패하면 ValueError."""
    return shop_system.판매_처리(
        플레이어뷰(게임상태),
        게임상태["상점카탈로그"],
        대분류,
        탭,
        이름,
        수량,
    )


상점_대분류목록 = shop_system.대분류_목록


상점_최대구매수량 = shop_system.최대_구매수량


def 상점_판매가(아이템):
    return shop_system.판매가(아이템)
