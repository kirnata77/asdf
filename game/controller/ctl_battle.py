def _몬스터항목_정규화(항목):
    """인카운트 결과("출현몬스터" 이름 문자열)와 오브젝트의
    "전투몬스터"({"이름":..,"칭호":..} 딕셔너리) 두 형태를 하나로
    맞춘다."""
    if isinstance(항목, str):
        return {"이름": 항목}
    return 항목


def _몬스터원본목록_생성(몬스터항목목록, 레벨=None, 차수=None):
    """레벨/차수를 주면 몬스터 원본 데이터 사본에 덮어쓴다 - 몬스터
    데이터(monster_race_*.py) 자신은 "레벨"/"차수"가 항상 None이고,
    실제 값은 던전 맵의 인카운트/오브젝트 데이터가 갖고 있다
    (monster_format.py 설명 참고). combat.participants.적_참가자_생성()이
    "최대HP"/"AC" 수식(예: "레벨×(6+건강보정치)")을 평가할 때 이 값을
    읽는다."""
    몬스터원본목록 = []
    for 원항목 in 몬스터항목목록:
        항목 = _몬스터항목_정규화(원항목)
        원본 = 몬스터목록.get(항목["이름"])
        if 원본 is None:
            # 종족별 몬스터 파일(monster_race_*.py)에 없는 몬스터
            # (원본에도 "미정" 상태인 몬스터일 수 있다) - 조용히 건너뛴다.
            continue
        덮어쓰기 = {}
        칭호 = 항목.get("칭호")
        if 칭호 is not None:
            덮어쓰기["칭호"] = 칭호
        if 레벨 is not None:
            덮어쓰기["레벨"] = 레벨
        if 차수 is not None:
            덮어쓰기["차수"] = 차수
        if 덮어쓰기:
            원본 = dict(원본, **덮어쓰기)
        몬스터원본목록.append(원본)
    return 몬스터원본목록


# 반응 자동 사용 옵션: False(기본)면 반응행동을 쓰는 반응을 화면이
# 팝업으로 묻는다(전투상태["반응선택"] 콜백). True면 묻지 않고 자동으로 쓴다.
# 값은 화면(옵션화면)이 기기 설정 파일에서 읽어 반응_자동_설정()으로 넣는다.
_반응_자동 = False


def 반응_자동_여부():
    return _반응_자동


def 반응_자동_설정(값):
    global _반응_자동
    _반응_자동 = bool(값)


def 전투시작_반응_대기중(게임상태):
    전투상태 = 게임상태.get("전투상태")
    return bool(전투상태) and reactions.전투시작_반응_대기중(전투상태)


def 전투시작_반응_처리(게임상태):
    """전투 화면에 들어온 뒤 미뤄 둔 전투시작 반응(패스티스트 건)을 처리한다."""
    reactions.전투시작_반응_처리(게임상태["전투상태"])


def 전투_시작(게임상태, 몬스터항목목록, 클리어위치=None, 레벨=None, 차수=None):
    몬스터원본목록 = _몬스터원본목록_생성(몬스터항목목록, 레벨=레벨, 차수=차수)
    if not 몬스터원본목록:
        return None

    # 캐릭터명이 키라 전직으로 이름이 바뀌었을 수 있다 - 전투 전에 새로 만든다.
    게임상태["장비데이터모음"] = 장비데이터모음_생성(
        게임상태["파티"], 게임상태["상점카탈로그"]
    )
    게임상태["전투상태"] = flow.전투_시작(
        게임상태["파티"],
        몬스터원본목록,
        게임상태["장비데이터모음"],
        버프정의모음=버프목록,
        디버프정의모음=디버프목록,
        상태이상정의모음=상태이상목록,
        특성정의모음=전투용_몬스터특성정의,
        캐릭터특성정의모음=전투용_캐릭터특성정의,
        칭호정의모음=칭호목록,
        세트정의모음=방어구세트목록,
        시작반응_보류=not _반응_자동,
        스킬정의모음=게임상태["스킬데이터모음"],
    )
    게임상태["전투_클리어위치"] = 클리어위치
    게임상태["전투_로그커서"] = 0
    return 게임상태["전투상태"]


def 현재_턴_참가자(게임상태):
    return flow.현재_턴_참가자(게임상태["전투상태"])


def 아군_차례인가(게임상태):
    참가자 = 현재_턴_참가자(게임상태)
    return 참가자["진영"] == "아군" and 참가자["생존"]


def 적_목록(게임상태):
    return [p for p in 게임상태["전투상태"]["참가자"] if p["진영"] == "적"]


def 아군_목록(게임상태):
    return [p for p in 게임상태["전투상태"]["참가자"] if p["진영"] == "아군"]


def 새_로그_가져오기(게임상태):
    """마지막으로 조회한 뒤 새로 쌓인 전투 로그만 반환한다(화면이 매번
    로그 전체를 다시 그리지 않아도 되게)."""
    전투상태 = 게임상태["전투상태"]
    로그전체 = 전투상태["로그"]
    새로그 = 로그전체[게임상태["전투_로그커서"] :]
    게임상태["전투_로그커서"] = len(로그전체)
    return 새로그


def 아군_일반공격(게임상태, 대상참가자):
    """combat.attacks.일반공격_실행() 자체는 행동자원을 소모하지 않으므로(무기 명중/피해
    계산만 한다), 여기서 직접 일반행동 1개를 깎는다."""
    전투상태 = 게임상태["전투상태"]
    공격자 = 현재_턴_참가자(게임상태)
    if 공격자["행동자원"].get("일반행동", 0) <= 0:
        raise ValueError("일반행동이 남아있지 않다.")
    if not 대상참가자["생존"]:  # B12 - 부활 규칙이 없으므로 로직에서 거부한다
        raise ValueError(f"'{대상참가자['이름']}'은(는) 이미 쓰러져 지정할 수 없다.")
    공격자["행동자원"]["일반행동"] -= 1
    결과 = attacks.일반공격_실행(전투상태, 공격자, 대상참가자)
    core.종료판정_갱신(전투상태)  # 마지막 적을 쓰러뜨렸으면 바로 끝낸다(B9)
    return 결과


def 아군_스킬사용(게임상태, 스킬이름, 중심대상=None, 지정대상목록=None, 행동지불=None):
    """지정대상목록: "적반복지정" 스킬에서 타격 순서대로 고른 대상 리스트.
    행동지불: 행동 선택 팝업에서 고른 수단(스킬_행동선택지 참고), 없으면 기본 순서."""
    전투상태 = 게임상태["전투상태"]
    시전자 = 현재_턴_참가자(게임상태)
    스킬데이터모음 = 게임상태["스킬데이터모음"]
    스킬데이터 = 스킬데이터모음[스킬이름]
    결과 = skill_system.스킬_실행(
        전투상태,
        시전자,
        스킬이름,
        스킬데이터,
        중심대상=중심대상,
        지정대상목록=지정대상목록,
        행동지불=행동지불,
    )
    core.종료판정_갱신(전투상태)  # B9
    return 결과


def 파티_최고능력치_참가자(게임상태, 능력치이름):
    """생존한 아군 참가자 중 능력치이름(예: "민첩", "근력", "지능" 등)의
    유효 보정치(combat.stats.유효_능력치_보정치 - 버프/디버프까지 반영)가
    가장 높은 참가자를 반환한다. 동률이면 참가자 목록에서 먼저 나오는
    쪽을 쓴다. 생존한 아군이 없으면 None.

    "파티 대표 1명"이 필요한 판정에 어떤 능력치로든 재사용할 수 있게 능력치이름을 인자로 받는 범용 함수로
    만들었다."""
    전투상태 = 게임상태["전투상태"]
    후보 = [p for p in 아군_목록(게임상태) if p["생존"]]
    if not 후보:
        return None
    return max(
        후보,
        key=lambda p: stats.유효_능력치_보정치(전투상태, p, 능력치이름),
    )


def 도망_막는_상태이상(게임상태):
    """생존한 아군 중 도망을 막는 상태이상("도망불가" 효과, 예: 구속)에
    걸린 사람마다 (이름, [상태이상 이름...])을 돌려준다. 한 명이라도
    있으면 파티 전체가 도망칠 수 없다. 빈 리스트면 도망칠 수 있다."""
    전투상태 = 게임상태["전투상태"]
    결과 = []
    for p in 아군_목록(게임상태):
        if not p["생존"]:
            continue
        이름들 = status.상태이상_플래그_이름들(전투상태, p, "도망불가")
        if 이름들:
            결과.append((p["이름"], 이름들))
    return 결과


def 아군_도망시도(게임상태):
    """현재 턴의 아군이 파티를 대표해 전투이탈(도망)을 시도한다. 판정식
    (DC = 10 + 생존한 적 중 가장 민첩한 개체의 민첩보정치)은
    combat.flow.전투이탈_시도()를 그대로 쓴다. 반환값도 그 함수와 동일 -
    (성공여부, 최종굴림값, 난이도).

    파티 중 한 명이라도 도망을 막는 상태이상이면 시도 자체를 거부한다
    (ValueError, 턴은 그대로). 판정에 실패하면 현재 캐릭터의 턴을 끝낸다
    (턴_넘기기 - 이어지는 몬스터 턴도 진행된다). 그래서 한 턴에 여러 번
    다시 시도할 수 없다(B1)."""
    전투상태 = 게임상태["전투상태"]
    현재 = 전투상태["참가자"][전투상태["현재턴"]]
    if 현재["진영"] != "아군" or not 현재["생존"]:
        raise ValueError("도망을 시도할 아군 차례가 아니다.")
    if 도망_막는_상태이상(게임상태):
        raise ValueError("도망 칠 수 없습니다.")
    결과 = flow.전투이탈_시도(전투상태, 현재)
    if not 결과[0]:
        턴_넘기기(게임상태)
    return 결과


def 자동전투_한_턴(게임상태):
    """[자동전투] - 현재 턴의 아군이 일반행동이 남아 있는 동안 지정 가능한 적
    중 무작위 하나를 일반공격하고, 더 할 수 없으면 턴을 넘긴다(턴_넘기기 -
    이어지는 몬스터 턴도 진행). 전투가 끝나면 바로 멈춘다. 반응은
    전투상태["반응선택"] 콜백이 없으면 자동으로 쓴다(화면이 비워서 부른다).
    공격할 적이 없으면(모두 은신 등) 공격 없이 턴을 넘긴다."""
    전투상태 = 게임상태["전투상태"]
    if 전투상태["종료"] is not None:
        return
    현재 = 현재_턴_참가자(게임상태)
    if 현재["진영"] != "아군" or not 현재["생존"]:
        raise ValueError("자동전투는 아군 차례에만 진행한다.")
    while 전투상태["종료"] is None and 현재["행동자원"].get("일반행동", 0) > 0:
        후보 = [
            p
            for p in 적_목록(게임상태)
            if p["생존"] and not 지정불가_상태인가(게임상태, p)
        ]
        if not 후보:
            break
        아군_일반공격(게임상태, random.choice(후보))
    if 전투상태["종료"] is None:
        턴_넘기기(게임상태)


def 턴_넘기기(게임상태):
    """현재 참가자의 턴을 끝낸다. 다음이 몬스터면 자동으로 행동시키고
    계속 넘겨서, 다시 아군 차례가 되거나 전투가 끝나면 멈춘다(화면 갱신
    타이밍 없이 한 번에 끝까지 진행한다).

    현재 참가자가 아직 행동하지 않은 몬스터면(선공 몬스터의 첫 턴) 먼저
    행동시킨 뒤 넘긴다 - 그러지 않으면 그 턴이 행동 없이 끝난다(B2)."""
    전투상태 = 게임상태["전투상태"]

    현재 = 전투상태["참가자"][전투상태["현재턴"]]
    if (
        전투상태["종료"] is None
        and 현재["진영"] == "적"
        and 현재["생존"]
        and not 전투상태.get("현재턴_행동완료", True)
    ):
        monster_actions.몬스터_턴_실행(전투상태, 현재)
        if core.종료판정_갱신(전투상태) is not None:
            return

    while True:
        참가자 = skill_system.다음_턴(전투상태)
        if 전투상태["종료"] is not None:
            return
        if 참가자["진영"] == "아군":
            return
        monster_actions.몬스터_턴_실행(전투상태, 참가자)
        if core.종료판정_갱신(전투상태) is not None:
            return


def _검사용_스킬데이터(게임상태, 스킬이름):
    # 사용 횟수 기록 키("_이름")를 붙인 사본 - skill_system.스킬_실행과 같은 모양.
    return dict(게임상태["스킬데이터모음"][스킬이름], _이름=스킬이름)


def 스킬_사용_가능여부(게임상태, 참가자, 스킬이름):
    """(가능여부, 사유) - 행동자원/MP/자원/횟수 제한/상태이상을 본다."""
    return skill_system.사용_가능여부(
        게임상태["전투상태"], 참가자, _검사용_스킬데이터(게임상태, 스킬이름)
    )


def 스킬_행동선택지(게임상태, 참가자, 스킬이름):
    """스킬의 일반행동을 낼 수 있는 수단 목록("쇼타임행동"/"일반행동"/"보조행동").
    둘 이상이면 화면이 행동 선택 팝업을 띄운다."""
    return skill_system.일반행동_지불수단_목록(
        게임상태["전투상태"], 참가자, _검사용_스킬데이터(게임상태, 스킬이름)
    )


def 스킬_휴식_남은횟수(게임상태, 참가자, 스킬이름):
    """ "휴식당횟수"가 있는 스킬이면 (남은횟수, 최대횟수), 아니면 None."""
    return skill_system.휴식_남은횟수(
        게임상태["전투상태"], 참가자, _검사용_스킬데이터(게임상태, 스킬이름)
    )


def 스킬_실제_타겟(게임상태, 스킬데이터):
    """스킬의 실제 타겟 종류. 분할공격은 1단계, 지속공격은 그 상세의 "타겟"을
    보고, 조건부효과의 "타겟" 오버라이드(은탄 등)가 지금 현재 턴 참가자에게
    충족되면 그 값을 쓴다 - skill_system.스킬_실행과 같은 판정."""
    타겟 = (
        스킬데이터.get("타겟")
        or (스킬데이터.get("공격단계1") or {}).get("타겟")
        or (스킬데이터.get("지속공격") or {}).get("타겟")
    )
    오버라이드 = skill_system.조건부효과_평가(
        게임상태["전투상태"],
        현재_턴_참가자(게임상태),
        None,
        스킬데이터.get("조건부효과", []),
    )
    return 오버라이드.get("타겟") or 타겟


def 현재참가자_수치(게임상태, 값, 기본값=1):
    """ "공격횟수"/"대상당피격제한" 같은 정수 수식(예: "3+추가공격")을 현재 턴
    참가자 기준으로 계산한다. None이면 기본값."""
    return skill_system.정수_평가(
        값, 게임상태["전투상태"], 현재_턴_참가자(게임상태), 기본값
    )


# 전투화면 적 그림 배율 - 칸에 맞춘 크기(중형, 아군 캐릭터와 같은 1배)에 곱한다.
몬스터_크기_배율 = {"소형": 0.75, "중형": 1.0, "대형": 1.25}


def 적_크기(참가자):
    """몬스터 데이터의 "크기"(없으면 "중형"). 모르는 값이면 ValueError."""
    크기 = 참가자["원본"].get("크기") or "중형"
    if 크기 not in 몬스터_크기_배율:
        raise ValueError(
            f"'{참가자['이름']}'의 크기 '{크기}'는 {list(몬스터_크기_배율)} 중 하나여야 한다."
        )
    return 크기


def 적_표시_배율(참가자):
    return 몬스터_크기_배율[적_크기(참가자)]


def 적_그리기_순서(적목록):
    """겹칠 때의 그리기 순서(먼저 그린 것이 뒤) - 대형을 먼저(뒤로), 같은 크기끼리는
    오른쪽부터 그려 왼쪽이 앞에 오게 한다. 적목록의 순서(화면 왼쪽부터)로 받은
    (번호, 참가자)를 그릴 순서로 돌려준다."""
    return sorted(
        enumerate(적목록),
        key=lambda 항목: (-적_표시_배율(항목[1]), -항목[0]),
    )


def 지정불가_상태인가(게임상태, 참가자):
    """은신 등 "지정불가" 상태이상이 있어 단일 대상으로 고를 수 없으면 True."""
    return bool(status.상태이상_플래그(게임상태["전투상태"], 참가자, "지정불가"))


def 전투_종료됨(게임상태):
    전투상태 = 게임상태["전투상태"]
    return 전투상태 is not None and 전투상태["종료"] is not None
