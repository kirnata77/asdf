def _항아리(이름):
    항아리 = 소모품_데이터["항아리"].get(이름)
    if 항아리 is None:
        raise ValueError(f"'{이름}'은(는) 항아리가 아니다.")
    return 항아리


def 항아리_열기(게임상태, 이름):
    """항아리 1개를 열어 그 레어도 장비 하나를 소지품에 넣고 그 장비 데이터를 돌려준다.
    그 레어도 장비가 없으면 ValueError("데이터 없음") - 항아리는 소모하지 않는다."""
    항아리 = _항아리(이름)
    if 게임상태["소지품"].get("소모품", {}).get(이름, 0) <= 0:
        raise ValueError(f"'{이름}'이(가) 소지품에 없다.")
    장비카탈로그 = 게임상태["상점카탈로그"]["장비"]
    장비이름 = loot_system.레어도_장비_뽑기(장비카탈로그, 항아리["장비레어도"])
    if 장비이름 is None:
        raise ValueError("데이터 없음")
    potion_system.소지품_차감_카테고리(게임상태["소지품"], "소모품", 이름)
    player_system.아이템_추가(플레이어뷰(게임상태), "장비", 장비이름)
    collection_system.아이템_등록(게임상태["진행도"], "장비", 장비이름)
    return next(탭[장비이름] for 탭 in 장비카탈로그.values() if 장비이름 in 탭)


# -------------------------------------------------------------- 소지품 화면 - 목록/상세보기


def _사용종류(대분류, 탭, 아이템):
    """소지품 화면에서 [사용]할 수 있으면 그 종류("항아리"/"회복포션"/"음식"/"주류"), 아니면 None.
    버프포션/투척/소환 아이템은 전투 중에만 쓴다."""
    if 대분류 != "소모품":
        return None
    if 탭 == "포션":
        return "회복포션" if 아이템.get("분류") == "회복포션" else None
    return 탭 if 탭 in ("항아리", "음식", "주류") else None


def 소지품_탭줄(게임상태, 대분류):
    """소지품 화면의 탭 줄 - 장비/소모품은 상점과 같고, 재료는 재료 묶음(큐브 조각/소울 ...)."""
    if 대분류 == "재료":
        return [list(게임상태["상점카탈로그"]["재료"])]
    if 대분류 == "장비":
        return 상점_탭줄("판매", 대분류)
    return [상점_탭목록(대분류)]


def 소지품_목록(게임상태, 대분류, 탭):
    """[(아이템데이터, 보유수량, 사용종류 또는 None)] - 장비는 장착 중인 것도 센다."""
    return [
        (아이템, 개수, _사용종류(대분류, 탭, 아이템))
        for 아이템, 개수 in shop_system.보유목록(
            플레이어뷰(게임상태), 게임상태["상점카탈로그"], 대분류, 탭
        )
    ]


def 소지품_상세(아이템):
    """[상세보기]에 쓸 효과 설명 줄들 - 회복포션/음식/주류는 회복량, 항아리는 나오는 등급.
    그 밖의 아이템은 None(화면이 데이터 항목을 그대로 보여준다)."""
    분류 = 아이템.get("분류")
    if 분류 == "항아리":
        return [f"열면 {아이템['장비레어도']} 등급 장비 1개가 나온다."]
    if 분류 == "회복포션":
        식 = 아이템["회복값"].replace("(차수)", str(아이템["티어"]))
        return [
            f"{아이템['회복대상']} 회복: {식} (최소 {아이템.get('최소회복값', 0)})",
            f"레벨 {아이템.get('레벨제한', 1)} 이상",
        ]
    if 아이템.get("타입") == "음식":
        비율 = potion_system.음식_회복비율(아이템)
        if 비율 is None:
            return ["회복: 데이터 없음"]
        return [f"{종류} 최대치의 {비율}% 회복" for 종류 in 아이템["회복대상"]]
    if 아이템.get("타입") == "주류":
        회복값 = 아이템.get("회복값")
        if not isinstance(회복값, dict):
            return ["회복: 데이터 없음"]
        return [f"{종류} 회복: {식}" for 종류, 식 in 회복값.items()] + [
            "차수 = 마시는 캐릭터의 전직 차수",
            f"상태이상: {아이템.get('상태이상', '없음')}",
        ]
    return None
