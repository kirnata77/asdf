# 컨트롤러 - 회복포션 사용 - 전투 중엔 보조행동 1개로 자기 자신만, 파티원 화면에선 아무 파티원
# (gameflow.py에서 분리 - N5. 화면은 gameflow.py 창구만 부른다. 설명은 gameflow.py 머리말)

from game.data.item.item_potion import 포션_데이터
from game.system import (
    character_data_system as 캐릭터데이터,
    equipment_system,
    potion_system,
)
from game.system.combat import core, stats
from game.controller.ctl_battle import 현재_턴_참가자
from game.controller.ctl_party import 캐릭터_능력치_보정치, 캐릭터_최대HP, 캐릭터_최대MP

__all__ = [
    "_회복포션",
    "_회복포션_목록",
    "_캐릭터_포션값",
    "_캐릭터_포션_사유",
    "캐릭터_회복포션_목록",
    "캐릭터_포션사용",
    "_참가자_포션값",
    "_참가자_포션_사유",
    "아군_회복포션_목록",
    "아군_포션사용",
]


def _회복포션(포션이름):
    포션 = 포션_데이터["회복포션"].get(포션이름)
    if 포션 is None:
        raise ValueError(f"'{포션이름}'은(는) 회복포션이 아니다.")
    return 포션


def _회복포션_목록(게임상태, 사유함수):
    """소지품의 회복포션을 [(이름, 개수, 사유 또는 None)]로. 데이터 순서대로."""
    보유 = 게임상태["소지품"].get(potion_system.소지품_카테고리, {})
    return [
        (이름, 보유[이름], 사유함수(포션, 보유[이름]))
        for 이름, 포션 in 포션_데이터["회복포션"].items()
        if 보유.get(이름, 0) > 0
    ]


def _캐릭터_포션값(게임상태, 캐릭터, 포션):
    """전투 밖 (보정치, 현재값, 최대값) - 장비 반영."""
    if 포션["회복대상"] == "HP":
        보정치 = 캐릭터_능력치_보정치(게임상태, 캐릭터, "건강")
        return 보정치, 캐릭터["현재HP"], 캐릭터_최대HP(게임상태, 캐릭터)
    스탯 = 캐릭터데이터.주문시전능력치(캐릭터)
    보정치 = 캐릭터_능력치_보정치(게임상태, 캐릭터, 스탯)
    return 보정치, 캐릭터["현재MP"], 캐릭터_최대MP(게임상태, 캐릭터)


def _캐릭터_포션_사유(게임상태, 캐릭터, 포션, 보유수):
    _, 현재값, 최대값 = _캐릭터_포션값(게임상태, 캐릭터, 포션)
    return potion_system.사용불가_사유(
        포션, 캐릭터["레벨"], 캐릭터["현재HP"], 현재값, 최대값, 보유수
    )


def 캐릭터_회복포션_목록(게임상태, 캐릭터):
    """전투 밖 파티원 화면용 - [(이름, 개수, 사유 또는 None)]."""
    return _회복포션_목록(
        게임상태, lambda 포션, 수: _캐릭터_포션_사유(게임상태, 캐릭터, 포션, 수)
    )


def 캐릭터_포션사용(게임상태, 캐릭터, 포션이름):
    """전투 밖에서 캐릭터에게 회복포션 1개를 쓴다. (회복대상 "HP"/"MP", 실제
    회복량)을 돌려준다."""
    포션 = _회복포션(포션이름)
    보유수 = 게임상태["소지품"].get(potion_system.소지품_카테고리, {}).get(포션이름, 0)
    사유 = _캐릭터_포션_사유(게임상태, 캐릭터, 포션, 보유수)
    if 사유:
        raise ValueError(사유)
    보정치, _, 최대값 = _캐릭터_포션값(게임상태, 캐릭터, 포션)
    회복 = potion_system.포션_적용(캐릭터, 포션, 보정치, 최대값)
    potion_system.소지품_차감(게임상태["소지품"], 포션이름)
    return 포션["회복대상"], 회복


def _참가자_포션값(전투상태, 참가자, 포션):
    """전투 중 (보정치, 현재값, 최대값) - 버프/디버프/장비 반영."""
    if 포션["회복대상"] == "HP":
        보정치 = stats.유효_능력치_보정치(전투상태, 참가자, "건강")
        return 보정치, 참가자["현재HP"], stats.유효_최대HP(전투상태, 참가자)
    최대값 = equipment_system.장비반영_최대MP(
        참가자["원본"], 참가자.get("장비데이터", {}), 전투상태.get("세트정의")
    )
    return stats.주문시전_보정치(전투상태, 참가자), 참가자["현재MP"], 최대값


def _참가자_포션_사유(전투상태, 참가자, 포션, 보유수):
    if 참가자["행동자원"].get("보조행동", 0) <= 0:
        return "보조행동이 남아있지 않다."
    _, 현재값, 최대값 = _참가자_포션값(전투상태, 참가자, 포션)
    return potion_system.사용불가_사유(
        포션,
        참가자["원본"]["레벨"],
        참가자["현재HP"] if 참가자["생존"] else 0,
        현재값,
        최대값,
        보유수,
    )


def 아군_회복포션_목록(게임상태):
    """전투 화면 [아이템]용 - 현재 턴 아군 기준 [(이름, 개수, 사유 또는 None)]."""
    전투상태 = 게임상태["전투상태"]
    참가자 = 현재_턴_참가자(게임상태)
    return _회복포션_목록(
        게임상태, lambda 포션, 수: _참가자_포션_사유(전투상태, 참가자, 포션, 수)
    )


def 아군_포션사용(게임상태, 포션이름):
    """현재 턴 아군이 회복포션 1개를 자신에게 쓴다(보조행동 1개). 실제 회복량을
    돌려주고 전투 로그에 남긴다."""
    전투상태 = 게임상태["전투상태"]
    참가자 = 현재_턴_참가자(게임상태)
    if 참가자["진영"] != "아군":
        raise ValueError("아군 차례가 아니다.")
    포션 = _회복포션(포션이름)
    보유수 = 게임상태["소지품"].get(potion_system.소지품_카테고리, {}).get(포션이름, 0)
    사유 = _참가자_포션_사유(전투상태, 참가자, 포션, 보유수)
    if 사유:
        raise ValueError(사유)
    보정치, _, 최대값 = _참가자_포션값(전투상태, 참가자, 포션)
    회복 = potion_system.포션_적용(참가자, 포션, 보정치, 최대값)
    potion_system.소지품_차감(게임상태["소지품"], 포션이름)
    참가자["행동자원"]["보조행동"] -= 1
    core.로그(
        전투상태,
        {
            "공격자": 참가자["이름"],
            "행동": f"{포션이름} 사용 - {포션['회복대상']} {회복} 회복",
        },
    )
    return 회복
