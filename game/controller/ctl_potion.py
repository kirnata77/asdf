def _주류(이름):
    주류 = 음식_데이터["주류"].get(이름)
    if 주류 is None:
        raise ValueError(f"'{이름}'은(는) 주류가 아니다.")
    return 주류


def _주류_목록(게임상태, 사유함수):
    """소지품의 주류를 [(이름, 개수, 사유 또는 None)]로. 데이터 순서대로."""
    보유 = 게임상태["소지품"].get(drink_system.소지품_카테고리, {})
    return [
        (이름, 보유[이름], 사유함수(보유[이름]))
        for 이름 in 음식_데이터["주류"]
        if 보유.get(이름, 0) > 0
    ]


def _캐릭터_주류값(게임상태, 캐릭터):
    """전투 밖 ({"HP": 보정치, "MP": 보정치}, {"HP": 최대, "MP": 최대}) - 장비와 캐릭터에
    남은 상태이상(취기의 매력 감소) 반영."""
    스탯 = 캐릭터데이터.주문시전능력치(캐릭터)
    보정치 = {
        "HP": 캐릭터_능력치_보정치(게임상태, 캐릭터, "건강"),
        "MP": 캐릭터_능력치_보정치(게임상태, 캐릭터, 스탯),
    }
    최대 = {
        "HP": 캐릭터_최대HP(게임상태, 캐릭터),
        "MP": 캐릭터_최대MP(게임상태, 캐릭터),
    }
    return 보정치, 최대


def 캐릭터_주류_목록(게임상태, 캐릭터):
    """전투 밖 파티원 화면용 - [(이름, 개수, 사유 또는 None)]."""
    return _주류_목록(
        게임상태, lambda 수: drink_system.사용불가_사유(캐릭터["현재HP"], 수)
    )


def 캐릭터_주류사용(게임상태, 캐릭터, 이름):
    """전투 밖에서 캐릭터가 주류 1개를 마신다. (회복 {"HP": n, ...}, 취기 결과 문구)."""
    주류 = _주류(이름)
    보유수 = 게임상태["소지품"].get(drink_system.소지품_카테고리, {}).get(이름, 0)
    사유 = drink_system.사용불가_사유(캐릭터["현재HP"], 보유수)
    if 사유:
        raise ValueError(사유)
    보정치, 최대 = _캐릭터_주류값(게임상태, 캐릭터)
    회복 = drink_system.회복_적용(
        캐릭터, 주류, 보정치, 최대, 캐릭터데이터.차수_계산(캐릭터)
    )
    결과 = drink_system.음주_상태이상_적용(
        캐릭터.setdefault("상태이상", []), 주류["상태이상"], 상태이상목록
    )
    potion_system.소지품_차감_카테고리(
        게임상태["소지품"], drink_system.소지품_카테고리, 이름
    )
    return 회복, 결과


def _참가자_주류값(전투상태, 참가자):
    """전투 중 보정치/최대치 - 버프/디버프/상태이상/장비 반영."""
    보정치 = {
        "HP": stats.유효_능력치_보정치(전투상태, 참가자, "건강"),
        "MP": stats.주문시전_보정치(전투상태, 참가자),
    }
    최대 = {
        "HP": stats.유효_최대HP(전투상태, 참가자),
        "MP": equipment_system.장비반영_최대MP(
            참가자["원본"], 참가자.get("장비데이터", {}), 전투상태.get("세트정의")
        ),
    }
    return 보정치, 최대


def _참가자_주류_사유(참가자, 보유수):
    if 참가자["행동자원"].get("보조행동", 0) <= 0:
        return "보조행동이 남아있지 않다."
    return drink_system.사용불가_사유(참가자["현재HP"] if 참가자["생존"] else 0, 보유수)


def 아군_주류_목록(게임상태):
    """전투 화면 [아이템]용 - 현재 턴 아군 기준 [(이름, 개수, 사유 또는 None)]."""
    참가자 = 현재_턴_참가자(게임상태)
    return _주류_목록(게임상태, lambda 수: _참가자_주류_사유(참가자, 수))


def 아군_주류사용(게임상태, 이름):
    """현재 턴 아군이 주류 1개를 마신다(보조행동 1개, 자기 자신만). 회복을 먼저 굴리고
    취기를 건다. (회복 {"HP": n, ...}, 취기 결과 문구)를 돌려주고 전투 로그에 남긴다."""
    전투상태 = 게임상태["전투상태"]
    참가자 = 현재_턴_참가자(게임상태)
    if 참가자["진영"] != "아군":
        raise ValueError("아군 차례가 아니다.")
    주류 = _주류(이름)
    보유수 = 게임상태["소지품"].get(drink_system.소지품_카테고리, {}).get(이름, 0)
    사유 = _참가자_주류_사유(참가자, 보유수)
    if 사유:
        raise ValueError(사유)
    보정치, 최대 = _참가자_주류값(전투상태, 참가자)
    회복 = drink_system.회복_적용(참가자, 주류, 보정치, 최대, core.차수(참가자))
    결과 = drink_system.음주_상태이상_적용(
        참가자["상태이상"], 주류["상태이상"], 상태이상목록
    )
    potion_system.소지품_차감_카테고리(
        게임상태["소지품"], drink_system.소지품_카테고리, 이름
    )
    참가자["행동자원"]["보조행동"] -= 1
    core.로그(
        전투상태,
        {
            "공격자": 참가자["이름"],
            "행동": f"{이름} 마심 - " + 주류_결과_문구(회복, 결과),
        },
    )
    return 회복, 결과


def 주류_결과_문구(회복, 결과):
    """ "HP 5 회복, MP 3 회복 / 취기 2" 같은 한 줄."""
    조각 = [f"{종류} {양} 회복" for 종류, 양 in 회복.items()]
    return ", ".join(조각 or ["회복 없음"]) + f" / {결과}"
