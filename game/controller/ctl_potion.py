def _음식(이름):
    음식 = 음식_데이터["음식"].get(이름)
    if 음식 is None:
        raise ValueError(f"'{이름}'은(는) 음식이 아니다.")
    return 음식


def 캐릭터_음식사용(게임상태, 캐릭터, 이름):
    """전투 밖에서 캐릭터가 음식 1개를 먹는다. 실제 회복량 {"HP": n, ...}을 돌려준다.
    회복값이 "미정"이면 ValueError("데이터 없음") - 소모하지 않는다."""
    음식 = _음식(이름)
    보유수 = 게임상태["소지품"].get(drink_system.소지품_카테고리, {}).get(이름, 0)
    최대 = {
        "HP": 캐릭터_최대HP(게임상태, 캐릭터),
        "MP": 캐릭터_최대MP(게임상태, 캐릭터),
    }
    현재 = {"HP": 캐릭터["현재HP"], "MP": 캐릭터["현재MP"]}
    사유 = potion_system.음식_사용불가_사유(음식, 캐릭터["현재HP"], 현재, 최대, 보유수)
    if 사유:
        raise ValueError(사유)
    회복 = potion_system.음식_적용(캐릭터, 음식, 최대)
    potion_system.소지품_차감_카테고리(
        게임상태["소지품"], drink_system.소지품_카테고리, 이름
    )
    return 회복


