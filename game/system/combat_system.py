def _턴_종료_처리(전투상태, 참가자):
    """턴 종료 시 발동하는 지속피해형("턴종료시" - 출혈/중독 등)을
    발동시킨다. 인스턴스별로 관리되므로(같은 이름도 병합하지 않음)
    여러 개면 각각 피해를 입힌다. "지속피해정지"(빙결/석화) 중이면
    아무것도 하지 않는다.

    이어서 job_skill_format.py "지속피해"(스킬에 곁들이는 커스텀 도트)도
    같은 시점(대상 본인 턴종료시)에 발동시킨다. 마지막으로 "발동조건":
    "턴종료시"인 몬스터특성(냉기방출 등)도 참가자 자신의 턴 종료
    시점에 발동시킨다(신규)."""
    if not 상태이상_플래그(전투상태, 참가자, "지속피해정지"):
        for 항목 in list(참가자.get("상태이상", [])):
            정의 = 전투상태["상태이상정의"].get(항목["이름"])
            if 정의 is None or 정의.get("분류") != "지속피해형":
                continue
            효과 = 정의.get("효과", {})
            if 효과.get("발동시점") == "턴종료시":
                _지속피해_적용(전투상태, 참가자, 항목, 정의)

        for 항목 in list(참가자.get("상태이상", [])):
            if 항목.get("종류") == "지속피해":
                _지속피해_스킬_적용(전투상태, 참가자, 항목)

    _특성_턴종료시_발동(전투상태, 참가자)

    # 몬스터 소환수는 소환한 몬스터의 턴 종료 시 행동한다.
    if 참가자["진영"] == "적" and 참가자["생존"]:
        _몬스터_소환수_행동_실행(전투상태, 참가자)
    반응대기_처리(전투상태)


