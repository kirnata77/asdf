#     "효과"의 공격을 한다. 반격은 그 적의 공격 로그 뒤에 나오도록 반응대기에
#     넣었다가 반응대기_처리()에서 실행한다.
#   - "피격시"(건가드 피해감소 / 위상 변화 피해무효): 적의 공격·능력으로
#     피해를 받을 때. 자동 사용이면 피해무효를 쓰러지지 않는 피해에도 바로 쓰고,
