def _특성_턴종료시_발동(전투상태, 참가자):
    """"발동조건":"턴종료시"인 몬스터특성(냉기방출 등)을 참가자 자신의
    턴이 끝날 때 발동시킨다. "효과"가 "종류":"데미지"이고 "타겟":
    "적전체"인 것만 다룬다(지금까지 나온 유일한 형태). "내성성공시":
    "데미지절반"이면 내성굴림 성공 시 피해를 절반으로 줄인다."""
    for 이름, 정의 in _특성_목록(전투상태, 참가자):
        if 정의.get("분류") != "몬스터특성" or 정의.get("발동조건") != "턴종료시":
            continue
        효과 = 정의.get("효과")
        if not isinstance(효과, dict) or 효과.get("종류") != "데미지":
            continue
        if 효과.get("타겟") != "적전체":
            continue
        상대진영 = "아군" if 참가자["진영"] == "적" else "적"
        for 대상 in [p for p in 전투상태["참가자"] if p["진영"] == 상대진영 and p["생존"]]:
            피해 = 수식_평가(str(효과.get("데미지", "0")), 기본_컨텍스트(전투상태, 참가자))
            내성스탯 = 효과.get("내성")
            내성성공 = False
            if 내성스탯:
                난이도 = 수식_평가(str(효과.get("난이도", "10")), 기본_컨텍스트(전투상태, 참가자))
