# 가드류 버프: skill_effects.py 기술효과 중 "효과"."반격"."발동조건"이 "피격시"인
# 것(가드, 무기막기). 스킬로 얻은 뒤 지속턴 안에 처음 받는 적의 공격 1회를 명중
# 굴림과 무관하게 빗나감(회피)으로 바꾸고 버프는 사라진다. 그 즉시 반응행동이
# 있으면 1개 소모해 "반격"(데미지, 기본 보정공격력 / 보정명중률)을 반응대기에 넣는다.
# 오토가드류: 강화특성 중 "효과"."타입"이 "자동발동"인 것(오토가드). 가드류 버프가
# 없을 때 적의 공격을 받을 때마다 "발동확률"로 굴려, 성공하면 "대상"(가드)의 효과를
# 그대로 발동한다 - 버프/행동/MP를 쓰지 않고 횟수 제한도 없다. 반격은 똑같이
# 반응행동으로 한다. 행동불가(기절 등) 상태면 둘 다 발동하지 않는다.
# 명중 판정을 거치지 않는 적의 능력(내성형 패턴/자폭/특성 데미지)에는 적용되지 않는다.

def _가드_반격정의(이름):
    """가드류 기술효과면 그 "반격" 정의, 아니면 None."""
    정의, _ = 효과정의_조회(이름)
    반격 = ((정의 or {}).get("효과") or {}).get("반격") if isinstance((정의 or {}).get("효과"), dict) else None
    if isinstance(반격, dict) and 반격.get("발동조건") == "피격시":
        return 반격
    return None


def _자동발동_특성목록(전투상태, 참가자):
    정의모음 = 전투상태.get("캐릭터특성정의", {})
    결과 = []
    for 이름 in (참가자["원본"].get("보유특성") or []):
        정의 = 정의모음.get(이름)
        효과 = (정의 or {}).get("효과")
        if 정의 and 정의.get("분류") == "강화특성" and isinstance(효과, dict) \
                and 효과.get("타입") == "자동발동":
            결과.append((이름, 정의))
    return 결과


def _가드_반응(전투상태, 공격자, 대상, 판정):
    """가드류 버프/오토가드의 회피는 자동이다(반응행동을 쓰지 않음). 반응행동을
    쓰는 반격은 _피격판정_반응에서 다른 반격 후보와 함께 고른다(판정["가드반격"])."""
    if not 대상["생존"] or 상태이상_플래그(전투상태, 대상, "행동불가"):
        return 판정
    발동이름, 반격 = None, None
    for 항목 in list(대상.get("버프", [])):
        반격 = _가드_반격정의(항목["이름"])
        if 반격:
            대상["버프"].remove(항목)
            발동이름 = 항목["이름"]
            break
    if 발동이름 is None:
        for 이름, 정의 in _자동발동_특성목록(전투상태, 대상):
            반격 = _가드_반격정의(정의.get("대상"))
            확률 = 정의["효과"].get("발동확률", 0) or 0
            if 반격 and random.random() < 확률:
                발동이름 = f"{이름}({정의.get('대상')})"
                break
    if 발동이름 is None:
        return 판정
    _반응_로그(전투상태, 대상, 발동이름, f"{공격자['이름']}의 공격을 막아냄")
    return dict(판정, 성공=False, 치명타=False, 반응회피=발동이름, 가드반격=(발동이름, 반격))

def 반응대기_처리(전투상태):
    """반응대기에 쌓인 반격을 순서대로 실행한다(적의 공격 로그 뒤에 나오게)."""
    대기 = 전투상태.pop("반응대기", [])
    for 시전자, 대상, 효과, 이름 in 대기:
        if 시전자["생존"]:
            _반응공격_실행(전투상태, 시전자, 대상, 효과, 이름)


def _피격피해_반응(전투상태, 공격자, 대상, 최종피해):
    """적에게 피해를 받기 직전: 피해무효형(위상 변화)/피해감소형(건가드) 중에서
    고른다. 피해무효는 쓰러지지 않는 피해에도 후보에 들어간다 -
    반응 자동 사용(콜백 없음)이면 첫 후보(피해무효가 있으면 피해무효, 없으면
    첫 피해감소)를 바로 쓴다. 반응 후 남은 피해를 반환."""
    반응들 = _반응특성_목록(전투상태, 대상)
    if not 반응들:
        return 최종피해
    치명적 = 최종피해 >= 대상["현재HP"] + 대상.get("임시생명력", 0)
    피격시 = [(n, d) for n, d in 반응들
           if d.get("발동조건") == "피격시" and isinstance(d.get("효과"), dict)]
    후보 = []
    for 이름, 정의 in 피격시:
        if 정의["효과"].get("피해무효") and _반응_사용가능(전투상태, 대상, 이름, 정의):
            후보.append((이름, 정의, f"받는 피해 {최종피해} 무효화", 0))
    for 이름, 정의 in 피격시:
        감소식 = 정의["효과"].get("피해감소")
        if 감소식 is None or not _반응_사용가능(전투상태, 대상, 이름, 정의):
            continue
        무기필요 = "보정공격력" in str(감소식) or "무기공격력" in str(감소식)
        if 무기필요 and not 대상.get("장비데이터", {}).get("무기"):
            continue
        감소 = max(0, int(수식_평가(str(감소식),
                               기본_컨텍스트(전투상태, 대상, 무기공격력필요=무기필요))))
        후보.append((이름, 정의, f"피해 {최종피해} → {max(0, 최종피해 - 감소)} ({감소} 감소)",
                   max(0, 최종피해 - 감소)))
    남은HP = 대상["현재HP"] + 대상.get("임시생명력", 0)
    선택 = _반응_선택(전투상태, 대상, 후보,
                  f"{공격자['이름']}의 공격으로 {대상['이름']}이(가) {최종피해}의 피해를 받습니다 "
                  f"(남은 체력 {남은HP}" + (", 쓰러짐" if 치명적 else "") + ").")
    if not 선택:
        return 최종피해
    이름, 정의, 설명, 남은 = 선택
    _반응_소모(전투상태, 대상, 이름, 정의)
    _반응_로그(전투상태, 대상, 이름, f"{공격자['이름']}의 {설명}")
    return 남은

def 상태이상_이름목록(참가자):
    return {i.get("이름") for i in 참가자.get("상태이상", [])}


def 공격후_반응(전투상태, 공격자, 대상, 공격전상태):
    """아군이 적을 공격한 뒤: 공격 시작 시점에 대상이 "조건값" 상태이상
    이었으면 "적상태" 반응특성(공중연속베기) 중에서 골라 추가 공격한다."""
    if 공격자.get("진영") != "아군" or not 대상["생존"]:
        return
    후보 = []
    for 이름, 정의 in _반응특성_목록(전투상태, 공격자):
        if 정의.get("발동조건") != "적상태" or 정의.get("조건값") not in 공격전상태:
            continue
        효과 = 정의.get("효과")
        if isinstance(효과, dict) and 효과.get("데미지") and _반응_사용가능(전투상태, 공격자, 이름, 정의):
            후보.append((이름, 정의, f"{대상['이름']}에게 추가 공격({효과.get('데미지')})", None))
    선택 = _반응_선택(전투상태, 공격자, 후보,
                  f"{대상['이름']}이(가) '{후보[0][1].get('조건값') if 후보 else ''}' 상태입니다. 추가 공격할까요?")
    if 선택:
        이름, 정의 = 선택[0], 선택[1]
        _반응_소모(전투상태, 공격자, 이름, 정의)
        _반응공격_실행(전투상태, 공격자, 대상, 정의["효과"], 이름)

def _집계_수(전투상태, 참가자, 집계조건):
    """몬스터특성 "집계조건"({"범위":"필드", "분류":..., "자신제외":...})에
    맞는 생존 참가자 수. "분류"는 몬스터 원본 "분류"와 비교한다."""
    수 = 0
    for p in 전투상태["참가자"]:
        if not p["생존"]:
            continue
        if 집계조건.get("자신제외") and p is 참가자:
            continue
        if 집계조건.get("분류") and p.get("원본", {}).get("분류") != 집계조건["분류"]:
            continue
        수 += 1
    return 수


def 전투시작_특성(전투상태):
    """"발동조건":"전투시작시" 몬스터특성을 전투 시작 때 한 번 발동한다
    지금은 "종류":"임시생명력", "타겟":"자신"만 처리한다(겁쟁이).
    "수치" 수식의 "고블린수"는 "집계조건"으로 센 값으로 바꿔 평가한다."""
    for 참가자 in [p for p in 전투상태["참가자"] if p["생존"]]:
        for 이름, 정의 in _특성_목록(전투상태, 참가자):
            if 정의.get("분류") != "몬스터특성" or 정의.get("발동조건") != "전투시작시":
                continue
            효과 = 정의.get("효과")
            if not isinstance(효과, dict) or 효과.get("종류") != "임시생명력":
                continue
            if 효과.get("타겟", "자신") != "자신":
                continue
            수식 = str(효과.get("수치", "0"))
            집계조건 = 효과.get("집계조건") or {}
            if 집계조건:
                집계명 = f"{집계조건.get('분류', '')}수"
                수식 = 수식.replace(집계명, str(_집계_수(전투상태, 참가자, 집계조건)))
            양 = max(0, int(_몬스터_수식값(전투상태, 참가자, 수식)))
            if 양 <= 0:
                continue
            참가자["임시생명력"] = 참가자.get("임시생명력", 0) + 양
            _로그(전투상태, {
                "대상": 참가자["이름"],
                "비고": f"'{이름}' 특성 - 임시생명력 {양} 획득",
            })


def 전투시작_반응(전투상태, 지연=False):
    """"발동조건":"전투시작시" 반응특성(패스티스트 건): 무작위 적(은신 제외)
    에게 공격하고, "디버프획득"을 "지속턴"만큼 자신에게 건다.
    "행동"이 비어 있으면 반응행동 1개를 소모값으로 본다(없으면 사용 불가).
    아군마다 쓸 수 있는 후보 중에서 고른다.
    지연=True(화면이 전투 화면에 들어온 뒤 처리 - 전투시작_반응_처리)이고 그 아군이
    이미 첫 턴을 시작한 참가자면 디버프는 걸지 않는다 - 첫 턴 반응행동은 방금 쓴
    것으로 이미 0이고, 디버프까지 걸면 두 번째 턴까지 0이 되기 때문."""
    for 아군 in [p for p in 전투상태["참가자"] if p["진영"] == "아군"]:
        적후보 = [p for p in 전투상태["참가자"] if p["진영"] == "적" and p["생존"]
               and not 상태이상_플래그(전투상태, p, "지정불가")]
        if not 적후보:
            return
        후보 = []
        for 이름, 정의 in _반응특성_목록(전투상태, 아군):
            if 정의.get("발동조건") != "전투시작시":
                continue
            정의 = {**정의, "행동": 정의.get("행동") or "반응행동"}
            if _반응_사용가능(전투상태, 아군, 이름, 정의):
                후보.append((이름, 정의, "무작위 적에게 선제 공격", None))
        선택 = _반응_선택(전투상태, 아군, 후보, "전투가 시작됐습니다. 선제 공격할까요?")
        if not 선택:
            continue
        이름, 정의 = 선택[0], 선택[1]
        _반응_소모(전투상태, 아군, 이름, 정의)
        _반응공격_실행(전투상태, 아군, random.choice(적후보), 정의.get("효과") or {}, 이름)
        이미시작 = 지연 and 전투상태["참가자"][전투상태["현재턴"]] is 아군
        if 정의.get("디버프획득") and not 이미시작:
            지속턴 = 정의.get("지속턴")
            _몬스터_버프_부여(전투상태, 아군, 정의["디버프획득"],
                         지속턴 if isinstance(지속턴, int) else None)
            _반응_로그(전투상태, 아군, 이름, f"자신에게 '{정의['디버프획득']}' 부여")


