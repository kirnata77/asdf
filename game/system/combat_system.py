def _지속피해_적용(전투상태, 대상, 항목, 정의):
    """지속피해형 상태이상(출혈/중독/화상/감전 등) 하나의 "턴시작시"/
    "턴종료시" 피해를 실제로 입힌다. "화상"의 "범위지속피해"(자신과
    주변2체)는 대상 진영과 무관하게 "대형위치" 기준 좌우 인접까지
    포함한다(아군도 몬스터처럼 전투_시작()에서 대형위치가 매겨진다).

    좌우 인접은 죽은 참가자를 빼고 당겨서 계산하지 않는다 - 같은 편
    전체(생존 무관)를 대형위치 순으로 늘어놓고 바로 옆 칸만 보며, 그
    칸이 죽은 참가자면 아무도 맞지 않는다(빈 칸 너머는 보지 않는다)."""
    효과 = 정의.get("효과", {})
    피해 = 수식_평가(효과.get("수식", "0"), {"차수": 차수(대상)})
