def 유효_이니셔티브(전투상태, 참가자):
    """매 라운드 재계산하는 이니셔티브. "기본이니셔티브"에 "속도"
    변동대상(속도증가/속도감소, 특성의 속도 변동 포함)과 상태이상
    "이니셔티브보너스"(둔화 등)를 반영한다. "구속"은 이니셔티브가
    아니라 유효_우선도()에서 페널티를 받는다. 수식형 보너스는 이
    함수가 불릴 때마다 다시 굴린다."""
    기본 = 참가자.get("기본이니셔티브", 참가자.get("이니셔티브", 0))
    보정 = 버프디버프_수치(전투상태, 참가자, "속도") + 특성_수치(전투상태, 참가자, "속도")
    for _, 정의 in _상태이상_정의_목록(전투상태, 참가자):
        효과 = 정의.get("효과", {})
        if "이니셔티브보너스" in 효과:
            보정 += 수식_평가(효과["이니셔티브보너스"], {"차수": 차수(참가자)})
    return 기본 + 보정


def 유효_우선도(전투상태, 참가자):
    """포켓몬류 "우선도" - 기본값에 "우선도" 변동대상과 상태이상
    "우선도보너스"(예: "구속"의 -3)를 더한다. 이니셔티브와 달리 랜덤
    굴림 요소는 없다."""
    기본 = 참가자.get("우선도", 0)
    보정 = 버프디버프_수치(전투상태, 참가자, "우선도")
    for _, 정의 in _상태이상_정의_목록(전투상태, 참가자):
        효과 = 정의.get("효과", {})
        if "우선도보너스" in 효과:
            보정 += 수식_평가(효과["우선도보너스"], {"차수": 차수(참가자)})
    return 기본 + 보정


def _턴순서_정렬(전투상태):
    """참가자 리스트를 (우선도, 이니셔티브) 순으로 내림차순 정렬한다 -
    우선도가 먼저고, 우선도가 같을 때만 이니셔티브로 가른다."""
    전투상태["참가자"].sort(key=lambda p: (p.get("우선도", 0), p["이니셔티브"]), reverse=True)


def _이니셔티브_재계산_및_정렬(전투상태):
    """라운드 전환 시 다음_턴()이 호출한다. 생존자만 "이니셔티브"/
    "우선도"를 재계산해 다시 정렬한다(사망자는 재계산하지 않는다)."""
    for 참가자 in 전투상태["참가자"]:
        if 참가자["생존"]:
            참가자["이니셔티브"] = 유효_이니셔티브(전투상태, 참가자)
            참가자["우선도"] = 유효_우선도(전투상태, 참가자)
    _턴순서_정렬(전투상태)


