def 버프디버프_수치(전투상태, 참가자, 변동대상, 행동종류=None):
    """버프/디버프의 "변동대상"에 해당하는 "변동값"을 전부 더한다
    (수식 문자열이면 그 자리에서 평가). 지속피해형의 "추가효과"도
    같은 변동대상으로 매핑해 함께 더한다(_추가효과_변동대상_매핑 참고).

    변동대상="행동보너스"로 호출할 때 "행동종류"(일반행동/보조행동/
    반응행동/쇼타임행동)를 같이 넘기면 그 종류만 필터링해서 더한다
    (넘기지 않으면 전부 더한다)."""
    합계 = 0
    목록들 = (
        (참가자["버프"], 전투상태["버프정의"]),
        (참가자["디버프"], 전투상태["디버프정의"]),
    )
    for 인스턴스목록, 정의모음 in 목록들:
        for 항목 in 인스턴스목록:
            정의 = 정의모음.get(항목["이름"])
            if 정의 is None:
                continue
            효과 = 정의.get("효과")
            if 효과 is None:
                continue
            효과리스트 = [효과] if isinstance(효과, dict) else 효과
            for 원소 in 효과리스트:
                if 원소.get("변동대상") != 변동대상:
                    continue
                if 행동종류 is not None and 원소.get("행동종류") != 행동종류:
                    continue
                변동값 = 원소.get("변동값", 0)
                중첩 = 항목.get("중첩", 1)
                if isinstance(변동값, str):
                    컨텍스트 = {
                        "차수": 차수(참가자),
                        "주문시전보정치": 주문시전_보정치(전투상태, 참가자),
                        "능력치": 참가자["원본"],
                    }
                    변동값 = 수식_평가(변동값, 컨텍스트)
                합계 += 변동값 * 중첩

    for 항목, 정의 in _상태이상_정의_목록(전투상태, 참가자):
        추가효과 = 정의.get("효과", {}).get("추가효과", {})
        for 키, 수식 in 추가효과.items():
            매핑된대상 = _추가효과_변동대상_매핑.get(키, 키)
            if 매핑된대상 != 변동대상:
                continue
            중첩수 = 항목.get("중첩", 1)
            if isinstance(수식, str):
                식 = 수식.replace("중첩수", str(중첩수))
                합계 += 수식_평가(식, {"차수": 차수(참가자)})
            else:
                합계 += 수식

    return 합계


_능력치_목록 = ("근력", "민첩", "건강", "지능", "지혜", "매력")


def 장비_스탯보너스(참가자, 능력치이름):
    """전투_시작()이 캐싱한 장비(전 부위+세트) "스탯보너스" 중 해당
    능력치 값(아군 전용, 없으면 0)."""
    보너스 = 참가자.get("장비보너스") or {}
    값 = (보너스.get("스탯보너스") or {}).get(능력치이름, 0)
    return 값 if isinstance(값, (int, float)) else 0


def 장비_수치(참가자, 키):
    """전투_시작()이 캐싱한 장비(전 부위+활성 세트) 보너스 중 숫자 항목
    (명중률보너스/데미지보너스/속도보너스/AC보너스). 몬스터는 0."""
    값 = (참가자.get("장비보너스") or {}).get(키, 0)
    return 값 if isinstance(값, (int, float)) else 0


def 유효_능력치값(전투상태, 참가자, 능력치이름):
    """원본 능력치 + 장비 스탯보너스 + 버프/디버프(해당 능력치와 "전체")."""
    원본값 = 참가자["원본"].get(능력치이름, 10)
    if not isinstance(원본값, (int, float)):
        원본값 = 10
    return (원본값 + 장비_스탯보너스(참가자, 능력치이름)
            + 버프디버프_수치(전투상태, 참가자, 능력치이름)
            + 버프디버프_수치(전투상태, 참가자, "전체"))


def 유효_능력치_보정치(전투상태, 참가자, 능력치이름):
    return (유효_능력치값(전투상태, 참가자, 능력치이름) - 10) // 2


def 유효_능력치(전투상태, 참가자):
    """수식_평가 컨텍스트의 "능력치"로 쓰는 사본 - 6개 능력치를
    유효_능력치값()으로 바꿔 넣는다("근력보정치" 같은 키워드가 장비/버프를
    반영하게 된다)."""
    사본 = dict(참가자["원본"])
    for 이름 in _능력치_목록:
        사본[이름] = 유효_능력치값(전투상태, 참가자, 이름)
    return 사본


def 평타_능력치_보정치(전투상태, 참가자):
    """"평타스탯" 후보 중 가장 높은 보정치를 쓴다. 몬스터는 평타스탯
    개념이 없어 근력을 기준으로 삼는다. 캐릭터 특성의 "평타스탯"(계시의
    지혜 등)도 후보에 더한다."""
    if 참가자["진영"] != "아군":
        return 유효_능력치_보정치(전투상태, 참가자, "근력")
    후보 = list(참가자["원본"]["평타스탯"])
    for 이름 in 캐릭터특성_평타스탯(전투상태, 참가자):
        if 이름 not in 후보:
            후보.append(이름)
    return max(유효_능력치_보정치(전투상태, 참가자, 이름) for 이름 in 후보)


def 주문시전_보정치(전투상태, 참가자):
    if 참가자["진영"] != "아군":
        return 0
    스탯 = 참가자["원본"]["주문시전능력치"]
    if 스탯 is None:
        return 0
    return 유효_능력치_보정치(전투상태, 참가자, 스탯)


def 귀신보유수(전투상태, 참가자):
    """참가자(캐릭터 원본)의 "보유스킬" 중 "타입"에 "귀신" 태그가 있는 스킬 개수.
    job_skill_format.py <데미지 문법>의 "(귀신보유수)d8"용 - 데이터에 저장하지 않고
    전투 시스템이 계산해 대입한다. 스킬정의가 없거나 몬스터면 0."""
    스킬정의 = 전투상태.get("스킬정의") or {}
    return sum(
        1 for 이름 in 참가자.get("원본", {}).get("보유스킬", [])
        if "귀신" in (스킬정의.get(이름) or {}).get("타입", [])
    )


def 기본_컨텍스트(전투상태, 참가자, 무기공격력필요=False):
    """수식_평가용 기본 컨텍스트(차수/추가공격/보정치/주문시전보정치/
    능력치/[무기공격력])를 만든다. skill_system._기본_컨텍스트는 이제
    이 함수를 그대로 위임 호출한다."""
    컨텍스트 = {
        "차수": 차수(참가자),
        "추가공격": 참가자.get("추가공격_사용가능", 0),
        "보정치": 평타_능력치_보정치(전투상태, 참가자),
        "주문시전보정치": 주문시전_보정치(전투상태, 참가자),
        "능력치": 유효_능력치(전투상태, 참가자),
        "귀신보유수": 귀신보유수(전투상태, 참가자),
    }
    if 무기공격력필요:
        무기데이터 = 참가자.get("장비데이터", {}).get("무기")
        if 무기데이터 is None:
            raise ValueError(f"'{참가자['이름']}'은(는) 무기를 장착하지 않았다.")
        컨텍스트["무기공격력"] = 무기데이터["무기공격력"]
    return 컨텍스트


