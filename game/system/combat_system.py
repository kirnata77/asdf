def _캐릭터특성_정의목록(전투상태, 참가자):
    """상시 적용 대상인 캐릭터 특성 정의만 골라 반환한다."""
    정의모음 = 전투상태.get("캐릭터특성정의", {})
    결과 = []
    for 이름 in (참가자["원본"].get("보유특성") or []):
        정의 = 정의모음.get(이름)
        if 정의 is None or 정의.get("토글"):
            continue
        if 정의.get("분류") in ("반응특성", "강화특성"):
            continue
        if 정의.get("발동조건") is not None:
            continue
        결과.append(정의)
    return 결과


def _캐릭터특성_항목목록(정의):
    """특성 "효과"를 (원래이름, 변동값, 원소) 튜플 리스트로 펼친다."""
    효과 = 정의.get("효과")
    원소들 = [효과] if isinstance(효과, dict) else (효과 or [])
    결과 = []
    for 원소 in 원소들:
        if not isinstance(원소, dict):
            continue
        if "변동대상" in 원소:
            결과.append((원소["변동대상"], 원소.get("변동값", 0), 원소))
        else:
            for 키, 값 in 원소.items():
                결과.append((키, 값, 원소))
    return 결과


def _캐릭터특성_조건충족(전투상태, 조건, 명중률종류, 대상, 속성):
    if 조건 is None:
        return True
    if 조건 == "주문":
        return 명중률종류 == "주문시전명중률"
    if 조건 == "첫턴":
        return 전투상태.get("라운드", 1) == 1
    if 조건 == "약점":
        if 대상 is None or 속성 is None:
            return False
        속성들 = 속성 if isinstance(속성, list) else [속성]
        return any(_속성_피해배율(전투상태, 대상, s) > 1 for s in 속성들)
    return False


def _캐릭터특성_수치(전투상태, 참가자, 변동대상, 명중률종류=None, 대상=None,
              속성=None, 행동종류=None):
    합계 = 0
    컨텍스트 = None
    for 정의 in _캐릭터특성_정의목록(전투상태, 참가자):
        for 원래이름, 값, 원소 in _캐릭터특성_항목목록(정의):
            매핑 = _캐릭터특성_이름매핑.get(원래이름)
            if 매핑 is None or 매핑[0] != 변동대상:
                continue
            if 변동대상 == "행동보너스" and 행동종류 is not None \
                    and 원소.get("행동종류") != 행동종류:
                continue
            if not _캐릭터특성_조건충족(전투상태, 매핑[1], 명중률종류, 대상, 속성):
                continue
            if isinstance(값, bool):
                continue
            if isinstance(값, str):
                if 컨텍스트 is None:
                    컨텍스트 = {
                        "차수": 차수(참가자),
                        "레벨": 참가자["원본"].get("레벨") or 1,
                        "주문시전보정치": 주문시전_보정치(전투상태, 참가자),
                        "능력치": 유효_능력치(전투상태, 참가자),
                    }
                try:
                    값 = 수식_평가(값, 컨텍스트)
                except Exception:
                    continue
            if isinstance(값, (int, float)):
                합계 += 값
    return 합계


def 캐릭터특성_평타스탯(전투상태, 참가자):
    """캐릭터 특성의 "평타스탯" 변동값(능력치 이름, 예: 계시의 "지혜")
    목록. effect_engine이 습득 시 캐릭터 "평타스탯"에 넣지만, 그 전에
    저장된 캐릭터도 전투에서 바로 반영되도록 여기서도 읽는다."""
    결과 = []
    for 정의 in _캐릭터특성_정의목록(전투상태, 참가자):
        for 원래이름, 값, _ in _캐릭터특성_항목목록(정의):
            if 원래이름 == "평타스탯" and isinstance(값, str):
                결과.append(값)
    return 결과


