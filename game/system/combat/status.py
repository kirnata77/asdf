from game.system.combat import core

# =====================================================
# 상태이상 조회 (status_effects.py 4분류 공용 헬퍼)
# =====================================================
# 참가자["상태이상"]은 이름/진행상태만 갖고, 실제 의미(행동불가/
# 피격시강제치명타/이니셔티브보너스 등)는 전투상태["상태이상정의"]를
# 이름으로 찾아봐야 안다 - 아래는 그 공용 조회 함수.


def _상태이상_정의_목록(전투상태, 참가자):
    결과 = []
    for 항목 in 참가자.get("상태이상", []):
        정의 = 전투상태["상태이상정의"].get(항목["이름"])
        if 정의 is not None:
            결과.append((항목, 정의))
    return 결과


def 상태이상_면역(전투상태, 참가자, 이름):
    """참가자가 가진 상태이상 중 "효과"."상태이상면역"(이름 리스트)에 이름이
    들어 있는 것이 있으면 True(슈퍼아머 - 넘어짐/공중에뜸).
    상태이상을 거는 모든 경로가 부여 직전에 확인한다."""
    for _, 정의 in _상태이상_정의_목록(전투상태, 참가자):
        면역 = 정의.get("효과", {}).get("상태이상면역") or []
        if isinstance(면역, str):
            면역 = [면역]
        if 이름 in 면역:
            return True
    return False


def _면역_로그(전투상태, 참가자, 이름, 출처설명=None):
    core._로그(
        전투상태,
        {
            "대상": 참가자["이름"],
            "비고": (f"{출처설명} - " if 출처설명 else "") + f"'{이름}' 상태이상 면역",
        },
    )


def 상태이상_플래그(전투상태, 참가자, 키):
    """상태이상정의 "효과"에서 주어진 키가 참인 것이 하나라도 있으면
    True(행동불가/피격시강제치명타/명중·회피불리점/지정불가/표적고정/
    도망불가/내성굴림불리점/타겟반전 등 공용으로 사용)."""
    for _, 정의 in _상태이상_정의_목록(전투상태, 참가자):
        if 정의.get("효과", {}).get(키):
            return True
    return False


def 상태이상_행동제한(전투상태, 참가자):
    """ "행동제한" 효과값(문자열, 예: "일반공격만")이 있으면 그 값을,
    없으면 None을 반환한다. ("혼란" 참고)"""
    for _, 정의 in _상태이상_정의_목록(전투상태, 참가자):
        제한 = 정의.get("효과", {}).get("행동제한")
        if 제한:
            return 제한
    return None


def _은신_자동해제_검사(전투상태, 진영):
    """같은 진영 생존자 전원이 은신 중이면(은신 아닌 동료가 없으면)
    전부 해제한다. 매 턴(_턴_시작_처리 시점) 검사로 단순화했다."""
    같은진영생존 = [p for p in 전투상태["참가자"] if p["진영"] == 진영 and p["생존"]]
    은신아닌동료있음 = any(
        not any(i.get("이름") == "은신" for i in p.get("상태이상", []))
        for p in 같은진영생존
    )
    if 은신아닌동료있음:
        return
    for p in 같은진영생존:
        은신항목들 = [i for i in p.get("상태이상", []) if i.get("이름") == "은신"]
        for 항목 in 은신항목들:
            p["상태이상"].remove(항목)
            core._로그(
                전투상태,
                {
                    "대상": p["이름"],
                    "비고": "은신하지 않은 동료가 없어 '은신' 자동 해제",
                },
            )
