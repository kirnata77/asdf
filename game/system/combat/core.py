# =====================================================
# 능력치/보정치 조회
# =====================================================
# skill_system.py의 스킬 실행 엔진도 재사용하는 공용 헬퍼(그래서
# 밑줄 접두사 없이 공개 이름으로 남겨둔다).


def 차수(참가자):
    if 참가자["진영"] == "아군":
        return 캐릭터데이터.차수_계산(참가자["원본"])
    return 1  # 몬스터는 차수 개념이 없다.


def 참가자_찾기(전투상태, 참가자id):
    """전투 시작 때 붙인 고유 "id"로 참가자를 찾는다(없으면 None). 이름은 같은
    몬스터끼리 겹칠 수 있어 참가자를 다시 찾을 때 쓰면 안 된다(B8)."""
    return next((p for p in 전투상태["참가자"] if p.get("id") == 참가자id), None)


def 로그(전투상태, 항목):
    전투상태["로그"].append(항목)


# =====================================================
# 전투 종료 판정
# =====================================================
# 전투상태만 보는 함수들이라 여기에 둔다 - 반응(reactions)과 턴 진행(flow)이 둘 다
# 쓰는데, flow에 두면 reactions가 flow를 불러 순환이 생겼다(구조 점검 R-3).


def 전투_종료_판정(전투상태):
    """아군이 전멸했으면 "적승리". 적이 모두 쓰러지거나 도망쳤으면, 처치한 적이
    하나라도 있으면 "아군승리", 모두 도망쳤으면 "적도망"(전리품 없음). 아니면 None."""
    아군생존 = any(p["진영"] == "아군" and p["생존"] for p in 전투상태["참가자"])
    적 = [p for p in 전투상태["참가자"] if p["진영"] == "적"]
    if not 아군생존:
        return "적승리"
    if not any(p["생존"] for p in 적):
        return "아군승리" if any(not p.get("도망") for p in 적) else "적도망"
    return None


def 전투종료시_보유자원_초기화(전투상태):
    """전투 종료 시 클래스 공유 자원(참가자["보유자원"])을 전투 시작
    시점 값("보유자원_전투시작값")으로 되돌린다(참조 공유라 되돌리지
    않으면 소모량이 다음 전투까지 그대로 남는다)."""
    for 참가자 in 전투상태["참가자"]:
        스냅샷 = 참가자.get("보유자원_전투시작값")
        if 스냅샷 is None:
            continue
        보유자원 = 참가자.get("보유자원")
        if 보유자원 is None:
            continue
        보유자원.clear()
        보유자원.update(스냅샷)


def 종료판정_갱신(전투상태):
    """전투상태["종료"]를 재계산해 반영한다(행동 - 공격/스킬/몬스터 턴 - 직후 승패를 바로
    반영한다, B9). None -> 비-None으로 막
    전환된 시점에만 전투종료시_보유자원_초기화()를 실행한다. 전투_시작/
    다음_턴 양쪽 모두 "종료" 갱신은 반드시 이 함수를 통해서만 한다.

    이미 "종료"가 None이 아니면 다시 계산하지 않는다 - 그렇지 않으면
    "전투이탈"처럼 전멸과 무관하게 끝난 전투가 다음_턴() 재호출 시
    전투_종료_판정()의 None으로 덮어써져 되살아나는 문제가 생긴다."""
    if 전투상태["종료"] is not None:
        return 전투상태["종료"]
    전투상태["종료"] = 전투_종료_판정(전투상태)
    if 전투상태["종료"] is not None:
        전투종료시_보유자원_초기화(전투상태)
    return 전투상태["종료"]
