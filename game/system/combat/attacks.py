# 전투 시스템 - 아군 일반공격.
# (combat 패키지에서 분리 - R4. 전체 설계 설명은 game/system/combat/__init__.py)

from game.system.combat import (
    core,
    damage,
    formula,
    reactions,
    resources,
    stats,
    traits,
)

# =====================================================
# 공격 실행
# =====================================================


def 일반공격_실행(전투상태, 공격자, 대상):
    """장착 무기 기반 일반공격 1회(아군 전용) - 몬스터는 monster_ai.py로
    고른 "패턴"을 몬스터_턴_실행()에서 처리한다.

    "장전 : OO"(은탄 등) 버프가 있으면 명중 여부와 무관하게 소모하고
    "속성변환"/"추가피해"를 반영한다(장전소모_처리 참고)."""
    무기데이터 = 공격자["장비데이터"].get("무기")
    if 무기데이터 is None:
        raise ValueError(f"'{공격자['이름']}'은(는) 무기를 장착하지 않았다.")

    _, 장전속성변환, 장전추가피해, 장전추가피해속성 = resources.장전소모_처리(
        전투상태, 공격자
    )
    속성 = 장전속성변환 or 무기데이터.get("속성")
    # 추가피해속성이 있으면 추가피해는 따로 그 속성으로 계산한다(은탄).
    추가피해목록 = (
        [(장전추가피해, 장전추가피해속성)]
        if 장전추가피해속성 and 장전추가피해
        else None
    )
    if 추가피해목록:
        장전추가피해 = 0
    공격전상태 = reactions.상태이상_이름목록(대상)

    판정 = damage.명중_판정(전투상태, 공격자, 대상, "보정명중률")
    결과 = {"공격자": 공격자["이름"], "대상": 대상["이름"], "판정": 판정, "피해": 0}

    if 판정["성공"]:
        보정치 = stats.평타_능력치_보정치(전투상태, 공격자)
        컨텍스트 = {"보정치": 보정치, "무기공격력": 무기데이터["무기공격력"]}
        피해 = formula.수식_평가("보정공격력", 컨텍스트, 치명타=판정["치명타"])

        # 무기만이 아니라 장비 전 부위+활성 세트의 데미지보너스.
        피해 += (
            stats.장비_수치(공격자, "데미지보너스")
            + 장전추가피해
            + stats.버프디버프_수치(전투상태, 공격자, "데미지보너스")
            + traits.특성_수치(
                전투상태,
                공격자,
                "데미지보너스",
                명중률종류="보정명중률",
                대상=대상,
                속성=속성,
            )
            + traits.칭호_수치(전투상태, 공격자, "데미지보너스")
        )

        결과["피해"] = damage.피해_적용(
            전투상태, 대상, 피해, 속성=속성, 추가피해목록=추가피해목록
        )
        damage.피격_처리(전투상태, 공격자, 대상, 판정, 속성=속성)

    core._로그(전투상태, 결과)
    reactions.공격후_반응(전투상태, 공격자, 대상, 공격전상태)
    return 결과
