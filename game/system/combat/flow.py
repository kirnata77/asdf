def _턴_시작_처리(전투상태, 참가자):
    """행동자원을 최대치로 채우고, 상태이상/버프/디버프의 지속턴을
    1씩 줄여 만료된 항목을 제거한다. "이번턴_스킬사용횟수"도 여기서
    비운다.

    "행동불가" 상태면 행동자원을 0으로 만든다. 지속피해형 "턴시작시"
    발동(화상)은 여기서 처리하고, "지속피해정지"(빙결/석화) 중에는
    지속피해형의 발동/지속턴 감소를 모두 건너뛴다.

    행동버프/디버프("행동보너스" + 행동종류)도 기본치에 더해 반영한다
    (0 밑으로 안 내려감). "쇼타임행동"은 참가자["기타행동"]에 같은
    방식으로 매 턴 채운다.

    "은신" 자동해제 검사는 아래 행동불가 판정에 영향을 주지 않도록
    먼저 처리한다. 상태이상이 지속턴 만료로 사라질 때 "공중에뜸"/
    "넘어짐"이면 "OO 해제시" 몬스터특성(기상 충격파 등)을 발동시킨다
    (신규 - 피격 등으로 인한 조기 해제는 아직 반영하지 않는다)."""
    status._은신_자동해제_검사(전투상태, 참가자["진영"])
    # 몬스터가 이번 턴에 아직 행동하지 않았다는 표시 - 몬스터_턴_실행이 True로
    # 바꾼다. 선공 몬스터의 첫 턴을 턴_넘기기가 건너뛰지 않게 하는 데 쓴다(B2).
    전투상태["현재턴_행동완료"] = False

    원본 = 참가자["원본"]
    if 참가자["진영"] == "아군":
        참가자["행동자원"] = {
            "일반행동": 원본["기본일반행동"],
            "보조행동": 원본["기본보조행동"],
            "반응행동": 원본["기본반응행동"],
        }
        참가자["추가공격_사용가능"] = 원본["추가공격"]
        참가자["이번턴_스킬사용횟수"] = {}
    else:
        참가자["행동자원"] = {"일반행동": 1, "보조행동": 1, "반응행동": 1}

    for 행동종류 in ("일반행동", "보조행동", "반응행동"):
        행동보너스 = stats.버프디버프_수치(
            전투상태, 참가자, "행동보너스", 행동종류=행동종류
        ) + traits.특성_수치(전투상태, 참가자, "행동보너스", 행동종류=행동종류)
        if 행동보너스:
            참가자["행동자원"][행동종류] = max(
                0, 참가자["행동자원"][행동종류] + 행동보너스
            )

    쇼타임보너스 = stats.버프디버프_수치(
        전투상태, 참가자, "행동보너스", 행동종류="쇼타임행동"
    ) + traits.특성_수치(전투상태, 참가자, "행동보너스", 행동종류="쇼타임행동")
    참가자["기타행동"] = {"쇼타임행동": max(0, 쇼타임보너스)}

    if status.상태이상_플래그(전투상태, 참가자, "행동불가"):
        참가자["행동자원"] = {"일반행동": 0, "보조행동": 0, "반응행동": 0}
        참가자["추가공격_사용가능"] = 0
        참가자["기타행동"]["쇼타임행동"] = 0

    지속피해정지 = status.상태이상_플래그(전투상태, 참가자, "지속피해정지")
    if not 지속피해정지:
        for 항목 in list(참가자.get("상태이상", [])):
            정의 = 전투상태["상태이상정의"].get(항목["이름"])
            if 정의 is None or 정의.get("분류") != "지속피해형":
                continue
            if 정의.get("효과", {}).get("발동시점") == "턴시작시":
                damage._지속피해_적용(전투상태, 참가자, 항목, 정의)

    for 목록이름 in ("상태이상", "버프", "디버프"):
        새목록 = []
        for 항목 in 참가자[목록이름]:
            if 목록이름 == "상태이상" and 지속피해정지:
                정의 = 전투상태["상태이상정의"].get(항목["이름"], {})
                if 정의.get("분류") == "지속피해형":
                    새목록.append(항목)  # 빙결/석화 중에는 지속턴이 줄지 않는다
                    continue
            지속턴 = 항목.get("지속턴")
            if 지속턴 is None:
                새목록.append(항목)
                continue
            항목["지속턴"] = 지속턴 - 1
            if 항목["지속턴"] > 0:
                새목록.append(항목)
            elif 목록이름 == "상태이상" and 항목.get("이름") in ("공중에뜸", "넘어짐"):
                traits._특성_상태이상해제시_발동(전투상태, 참가자, 항목["이름"])
        참가자[목록이름] = 새목록


def _턴_종료_처리(전투상태, 참가자):
    """턴 종료 시 발동하는 지속피해형("턴종료시" - 출혈/중독 등)을
    발동시킨다. 인스턴스별로 관리되므로(같은 이름도 병합하지 않음)
    여러 개면 각각 피해를 입힌다. "지속피해정지"(빙결/석화) 중이면
    아무것도 하지 않는다.

    이어서 job_skill_format.py "지속피해"(스킬에 곁들이는 커스텀 도트)도
    같은 시점(대상 본인 턴종료시)에 발동시킨다. 마지막으로 "발동조건":
    "턴종료시"인 몬스터특성(냉기방출 등)도 참가자 자신의 턴 종료
    시점에 발동시킨다(신규)."""
    if not status.상태이상_플래그(전투상태, 참가자, "지속피해정지"):
        for 항목 in list(참가자.get("상태이상", [])):
            정의 = 전투상태["상태이상정의"].get(항목["이름"])
            if 정의 is None or 정의.get("분류") != "지속피해형":
                continue
            효과 = 정의.get("효과", {})
            if 효과.get("발동시점") == "턴종료시":
                damage._지속피해_적용(전투상태, 참가자, 항목, 정의)

        for 항목 in list(참가자.get("상태이상", [])):
            if 항목.get("종류") == "지속피해":
                damage._지속피해_스킬_적용(전투상태, 참가자, 항목)

    traits._특성_턴종료시_발동(전투상태, 참가자)

    # 몬스터 소환수는 소환한 몬스터의 턴 종료 시 행동한다.
    if 참가자["진영"] == "적" and 참가자["생존"]:
        monster_actions._몬스터_소환수_행동_실행(전투상태, 참가자)
    reactions.반응대기_처리(전투상태)


def 현재_턴_참가자(전투상태):
    return 전투상태["참가자"][전투상태["현재턴"]]


def 다음_턴(전투상태):
    """현재 턴을 종료하고 다음 생존자에게 턴을 넘긴다. 참가자를 한
    바퀴 다 돌면 라운드가 1 증가하며, 그 시점에 이니셔티브/우선도를
    다시 계산해 재정렬한다. "턴즉시종료"(공중에뜸) 상태인 참가자는
    턴 시작/종료 처리는 받지만 실제 행동 기회 없이 곧바로 다음
    사람에게 넘어간다. 전투 종료 여부도 갱신한다."""
    현재참가자 = 전투상태["참가자"][전투상태["현재턴"]]
    _턴_종료_처리(전투상태, 현재참가자)

    인원수 = len(전투상태["참가자"])
    다음인덱스 = 전투상태["현재턴"]
    최대반복 = 인원수 * 3 + 1  # 전원이 턴즉시종료 상태인 극단적 경우의 안전장치

    for _ in range(최대반복):
        다음인덱스 = (다음인덱스 + 1) % 인원수
        if 다음인덱스 == 0:
            전투상태["라운드"] += 1
            _이니셔티브_재계산_및_정렬(전투상태)

        후보 = 전투상태["참가자"][다음인덱스]
        if not 후보["생존"]:
            continue

        _턴_시작_처리(전투상태, 후보)
        if status.상태이상_플래그(전투상태, 후보, "턴즉시종료"):
            core._로그(
                전투상태, {"공격자": 후보["이름"], "행동": "무행동 (턴즉시종료 상태)"}
            )
            _턴_종료_처리(전투상태, 후보)
            continue

        전투상태["현재턴"] = 다음인덱스
        _종료판정_갱신(전투상태)
        return 후보

    전투상태["현재턴"] = 다음인덱스
    _종료판정_갱신(전투상태)
    return 전투상태["참가자"][다음인덱스]


def 전투_종료_판정(전투상태):
    """아군/적 중 한쪽이 전멸했으면 "아군승리"/"적승리", 아니면 None."""
    아군생존 = any(p["진영"] == "아군" and p["생존"] for p in 전투상태["참가자"])
    적생존 = any(p["진영"] == "적" and p["생존"] for p in 전투상태["참가자"])
    if not 아군생존:
        return "적승리"
    if not 적생존:
        return "아군승리"
    return None


def _전투종료시_보유자원_초기화(전투상태):
    """전투 종료 시 클래스 공유 자원(참가자["보유자원"])을 전투 시작
    시점 값("보유자원_전투시작값")으로 되돌린다(참조 공유라 되돌리지
    않으면 소모량이 다음 전투까지 그대로 남는다)."""
    for 참가자 in 전투상태["참가자"]:
        스냅샷 = 참가자.get("보유자원_전투시작값")
        if 스냅샷 is None:
            continue
        보유자원 = 참가자.get("보유자원")
        if 보유자원 is None:
            continue
        보유자원.clear()
        보유자원.update(스냅샷)


def _종료판정_갱신(전투상태):
    """전투상태["종료"]를 재계산해 반영한다. None -> 비-None으로 막
    전환된 시점에만 _전투종료시_보유자원_초기화()를 실행한다. 전투_시작/
    다음_턴 양쪽 모두 "종료" 갱신은 반드시 이 함수를 통해서만 한다.

    이미 "종료"가 None이 아니면 다시 계산하지 않는다 - 그렇지 않으면
    "전투이탈"처럼 전멸과 무관하게 끝난 전투가 다음_턴() 재호출 시
    전투_종료_판정()의 None으로 덮어써져 되살아나는 문제가 생긴다."""
    if 전투상태["종료"] is not None:
        return 전투상태["종료"]
    전투상태["종료"] = 전투_종료_판정(전투상태)
    if 전투상태["종료"] is not None:
        _전투종료시_보유자원_초기화(전투상태)
    return 전투상태["종료"]


def 전투이탈_시도(전투상태, 참가자):
    """참가자가 파티를 대표해 전투 이탈(도망)을 시도한다. 성공하면
    파티 전체가 전투에서 빠져나온다. "도망불가" 상태면 판정 없이 실패.

    판정: 참가자의 민첩판정(1d20+보정치)이 생존한 적 중 가장 민첩한
    개체의 민첩보정치+10(난이도)을 넘으면 성공(D&D 5판의 "상대적 민첩
    대결" 관례를 가져와 구현 - 확정된 공식은 아니다).

    성공하면 전투상태["종료"]를 "전투이탈"로 표시한다("아군승리"/
    "적승리"와 구분되는 결과값 - 호출부가 승패 없이 물러난 것으로
    처리해야 한다). 실패하면 로그만 남고 아무것도 바뀌지 않는다.

    반환값: (성공여부, 최종굴림값, 난이도). "도망불가"로 판정 자체를
    못 했으면 (False, None, None)."""
    if status.상태이상_플래그(전투상태, 참가자, "도망불가"):
        core._로그(
            전투상태,
            {"공격자": 참가자["이름"], "행동": "도망 시도 실패 (도망불가 상태)"},
        )
        return False, None, None

    적생존 = [p for p in 전투상태["참가자"] if p["진영"] == "적" and p["생존"]]
    난이도 = 10 + max(
        (stats.유효_능력치_보정치(전투상태, 적, "민첩") for 적 in 적생존), default=0
    )
    민첩보정치 = stats.유효_능력치_보정치(전투상태, 참가자, "민첩")
    최종값, _ = dice_utils.판정_굴림(민첩보정치)
    성공 = 최종값 >= 난이도

    if 성공:
        전투상태["종료"] = "전투이탈"
        _전투종료시_보유자원_초기화(전투상태)
        core._로그(
            전투상태,
            {
                "공격자": 참가자["이름"],
                "행동": f"도망 성공 (파티 전체 전투 이탈, {최종값} vs DC{난이도})",
            },
        )
    else:
        core._로그(
            전투상태,
            {
                "공격자": 참가자["이름"],
                "행동": f"도망 실패 ({최종값} vs DC{난이도})",
            },
        )

    return 성공, 최종값, 난이도
