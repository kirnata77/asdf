def 전투_시작(
    파티,
    몬스터원본목록,
    장비데이터모음,
    버프정의모음=None,
    디버프정의모음=None,
    상태이상정의모음=None,
    특성정의모음=None,
    캐릭터특성정의모음=None,
    칭호정의모음=None,
    세트정의모음=None,
    시작반응_보류=False,
    스킬정의모음=None,
):
    """새 전투를 시작한다.

    파티: 생존자만 참가시킨다. 몬스터원본목록: 순서대로 참가시키며
    이 순서가 그대로 "대형위치"(좌우 인접 판정 기준)가 된다.
    장비데이터모음: {캐릭터명: {슬롯: 아이템데이터, ...}, ...}.
    버프정의모음/디버프정의모음/상태이상정의모음: buff.py/debuff.py/
    status_effects.py의 각 목록을 그대로 넘긴다(생략 시 빈 딕셔너리).
    특성정의모음: 몬스터의 "특성" 이름을 찾을 정의 테이블(monster_ability.py
    "특성목록" 등). 생략 시 몬스터 특성은 아무 효과도 반영되지 않는다.
    캐릭터특성정의모음: 아군 캐릭터의 "보유특성" 이름을 찾을 정의 테이블
    (job_ability_XX.py "특성목록"들을 합친 것) - AC/명중/데미지/방어력/
    속도/치명타범위/행동보너스에 반영된다(_캐릭터특성_수치 참고).
    칭호정의모음: monster_title.py "칭호목록".
    세트정의모음: eq_02_armor_set.py "방어구세트목록" 등 - 활성화된 세트
    (구성품 전부 장착, 또는 방어구 5부위를 같은 재질로 - equipment_system.
    세트효과_목록)의 효과가 AC/속도 등에 더해진다.
    스킬정의모음: job_skill_XX.py "스킬목록"들을 합친 것 - 수식 변수
    "귀신보유수"(시전자가 보유한 "귀신" 태그 스킬 개수)를 셀 때 쓴다.
    """
    전투상태 = {
        "참가자": [],
        "현재턴": 0,
        "라운드": 1,
        "로그": [],
        "종료": None,
        "버프정의": 버프정의모음 or {},
        "디버프정의": 디버프정의모음 or {},
        "상태이상정의": 상태이상정의모음 or {},
        "특성정의": 특성정의모음 or {},
        "캐릭터특성정의": 캐릭터특성정의모음 or {},
        "칭호정의": 칭호정의모음 or {},
        "세트정의": 세트정의모음 or {},
        "스킬정의": 스킬정의모음 or {},
    }

    for 대형위치, 캐릭터 in enumerate(party_system.생존자_목록(파티)):
        인스턴스 = participants._아군_참가자_생성(
            캐릭터, 장비데이터모음.get(캐릭터["캐릭터명"], {})
        )
        인스턴스["대형위치"] = 대형위치
        장비보너스 = equipment_system.장비_보너스_합산(
            인스턴스["장비데이터"],
            전투상태["세트정의"],
        )
        인스턴스["장비보너스"] = 장비보너스
        속도 = 캐릭터["기본속도"] + 장비보너스["속도보너스"]
        기본값 = dice_utils.d20_굴림() + 속도
        인스턴스["기본이니셔티브"] = 기본값
        인스턴스["이니셔티브"] = 기본값
        전투상태["참가자"].append(인스턴스)

    for 대형위치, 몬스터원본 in enumerate(몬스터원본목록):
        인스턴스 = participants._적_참가자_생성(몬스터원본)
        인스턴스["대형위치"] = 대형위치
        속도수식 = 몬스터원본.get("속도", 0)
        기본값 = formula.수식_평가(속도수식, {"능력치": 몬스터원본})
        인스턴스["기본이니셔티브"] = 기본값
        인스턴스["이니셔티브"] = 기본값
        전투상태["참가자"].append(인스턴스)

    # 몬스터 시작 HP를 특성(종족:타우/체력증가 등)과 칭호(보스 등)까지
    # 반영한 최대HP로 채운다 - 참가자가 전부 들어온 뒤에 계산해야
    # "조건부효과"(적상태 등) 판정도 정상적으로 된다.
    for 참가자 in 전투상태["참가자"]:
        if 참가자["진영"] == "적":
            참가자["현재HP"] = max(1, int(stats.유효_최대HP(전투상태, 참가자)))

    # 특성/버프의 "속도"(선빵필승/암살자/종족:루가루/계시 등)가 첫
    # 라운드 순서에도 반영되도록 시작 시점에 한 번 계산한다.
    for 참가자 in 전투상태["참가자"]:
        참가자["이니셔티브"] = stats.유효_이니셔티브(전투상태, 참가자)
        참가자["우선도"] = stats.유효_우선도(전투상태, 참가자)
    _턴순서_정렬(전투상태)
    traits.전투시작_특성(전투상태)
    # 시작반응_보류: 반응 선택 팝업을 띄울 화면이 아직 없으면(던전
    # 화면에서 전투가 시작됨) 전투시작 반응은 전투 화면이 전투시작_반응_처리로 한다.
    if 시작반응_보류:
        전투상태["시작반응_대기"] = True
    else:
        reactions.전투시작_반응(전투상태)
    _종료판정_갱신(전투상태)
    if 전투상태["참가자"]:
        _턴_시작_처리(전투상태, 전투상태["참가자"][0])
    return 전투상태


def _턴순서_정렬(전투상태):
    """참가자 리스트를 (우선도, 이니셔티브) 순으로 내림차순 정렬한다 -
    우선도가 먼저고, 우선도가 같을 때만 이니셔티브로 가른다."""
    전투상태["참가자"].sort(
        key=lambda p: (p.get("우선도", 0), p["이니셔티브"]), reverse=True
    )


def _이니셔티브_재계산_및_정렬(전투상태):
    """라운드 전환 시 다음_턴()이 호출한다. 생존자만 "이니셔티브"/
    "우선도"를 재계산해 다시 정렬한다(사망자는 재계산하지 않는다)."""
    for 참가자 in 전투상태["참가자"]:
        if 참가자["생존"]:
            참가자["이니셔티브"] = stats.유효_이니셔티브(전투상태, 참가자)
            참가자["우선도"] = stats.유효_우선도(전투상태, 참가자)
    _턴순서_정렬(전투상태)


