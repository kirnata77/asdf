# 참가자 원본의 "칭호"(예: "보스")를 전투상태["칭호정의"]에서 찾는다.
# 칭호가 None이거나 정의에 없는 이름("미정" 등)이면 아무 효과도 없다.
# "변동값"이 수식(예: "2×차수")이면 몬스터 원본의 레벨/차수/능력치로
# 평가한다. 칭호 데이터의 "명중률보너스"는 엔진이 쓰는 "명중보너스"로
# 맞춰 읽는다.

_칭호_변동대상_매핑 = {"명중률보너스": "명중보너스"}


def _칭호_효과목록(전투상태, 참가자):
    칭호 = 참가자.get("원본", {}).get("칭호")
    if not isinstance(칭호, str):
        return []
    정의 = 전투상태.get("칭호정의", {}).get(칭호)
    if not 정의:
        return []
    효과 = 정의.get("효과")
    if isinstance(효과, dict):
        return [효과]
    return 효과 or []


def 칭호_수치(전투상태, 참가자, 변동대상):
    """칭호 효과 중 "변동대상"에 해당하는 "변동값"을 전부 더한다."""
    합계 = 0
    for 원소 in _칭호_효과목록(전투상태, 참가자):
        대상 = _칭호_변동대상_매핑.get(원소.get("변동대상"), 원소.get("변동대상"))
        if 대상 != 변동대상 or "변동값" not in 원소:
            continue
        값 = participants._몬스터_수식_평가(원소["변동값"], 참가자["원본"], 0)
        if isinstance(값, (int, float)):
            합계 += 값
    return 합계


def 칭호_배율(전투상태, 참가자, 변동대상):
    """칭호 효과 중 "변동대상"에 해당하는 "배율"을 전부 곱한다(없으면 1)."""
    배율 = 1
    for 원소 in _칭호_효과목록(전투상태, 참가자):
        대상 = _칭호_변동대상_매핑.get(원소.get("변동대상"), 원소.get("변동대상"))
        if 대상 == 변동대상 and isinstance(원소.get("배율"), (int, float)):
            배율 *= 원소["배율"]
    return 배율


def _상태이상_효과_적용(전투상태, 시전자, 대상, 효과, 출처설명):
    """job_skill_format.py <효과 하위 양식> "상태이상"(명중/발동 후
    내성굴림 실패 시 상태이상 부여)의 최소 구현. 몬스터 패턴의 "효과"/
    "명중실패시효과"와 몬스터특성의 상태이상형 "효과"가 공용으로 쓴다.

    실제 상태이상 인스턴스 생성(중첩/부여버프 등)은 skill_system.py
    쪽이 더 정교하게 하지만, combat 패키지는 그 파일을 부르지
    않는 구조(순환 참조 방지)라 여기서는 이름/지속턴만 반영하는
    최소 버전이다 - "내성"이 없으면(즉시 부여) 내성굴림 없이 건다."""
    if not isinstance(효과, dict) or 효과.get("종류") != "상태이상":
        return
    if status.상태이상_면역(전투상태, 대상, 효과.get("이름")):
        status._면역_로그(전투상태, 대상, 효과.get("이름"), 출처설명)
        return
    내성스탯 = 효과.get("내성")
    if 내성스탯:
        난이도 = formula.수식_평가(
            str(효과.get("난이도", "10")), stats.기본_컨텍스트(전투상태, 시전자)
        )
        내성보정치 = stats.유효_능력치_보정치(전투상태, 대상, 내성스탯)
        불리 = status.상태이상_플래그(전투상태, 대상, "내성굴림불리점")
        이점 = 상태이상_내성이점(전투상태, 대상, 효과.get("이름"))
        if dice_utils.내성_성공(내성보정치, 난이도, 이점=이점, 불리=불리):
            return
    대상.setdefault("상태이상", []).append(
        {
            "이름": 효과.get("이름"),
            "지속턴": 효과.get("지속턴", 1),
        }
    )
    core._로그(
        전투상태,
        {
            "공격자": 시전자["이름"],
            "대상": 대상["이름"],
            "비고": f"{출처설명} - '{효과.get('이름')}' 상태이상 부여",
        },
    )


def _특성_공격명중시_발동(전투상태, 공격자, 대상):
    """ "발동조건":"공격명중시"인 몬스터특성(화염의 마녀/빙결의 마녀 등)을
    공격자 기준으로 검사해 발동시킨다. "효과"가 "종류":"상태이상"인
    것만 다룬다. 피격_처리()가 매 성공 공격마다 호출한다(일반공격_실행/
    _몬스터_패턴_실행 공용)."""
    for 이름, 정의 in _특성_목록(전투상태, 공격자):
        if 정의.get("분류") != "몬스터특성" or 정의.get("발동조건") != "공격명중시":
            continue
        _상태이상_효과_적용(전투상태, 공격자, 대상, 정의.get("효과"), f"'{이름}' 특성")


def _특성_턴종료시_발동(전투상태, 참가자):
    """ "발동조건":"턴종료시"인 몬스터특성(냉기방출 등)을 참가자 자신의
    턴이 끝날 때 발동시킨다. "효과"가 "종류":"데미지"이고 "타겟":
    "적전체"인 것만 다룬다(지금까지 나온 유일한 형태). "내성성공시":
    "데미지절반"이면 내성굴림 성공 시 피해를 절반으로 줄인다."""
    for 이름, 정의 in _특성_목록(전투상태, 참가자):
        if 정의.get("분류") != "몬스터특성" or 정의.get("발동조건") != "턴종료시":
            continue
        효과 = 정의.get("효과")
        if not isinstance(효과, dict) or 효과.get("종류") != "데미지":
            continue
        if 효과.get("타겟") != "적전체":
            continue
        상대진영 = "아군" if 참가자["진영"] == "적" else "적"
        for 대상 in [
            p for p in 전투상태["참가자"] if p["진영"] == 상대진영 and p["생존"]
        ]:
            피해 = formula.수식_평가(
                str(효과.get("데미지", "0")), stats.기본_컨텍스트(전투상태, 참가자)
            )
            내성스탯 = 효과.get("내성")
            내성성공 = False
            if 내성스탯:
                난이도 = formula.수식_평가(
                    str(효과.get("난이도", "10")), stats.기본_컨텍스트(전투상태, 참가자)
                )
                내성보정치 = stats.유효_능력치_보정치(전투상태, 대상, 내성스탯)
                불리 = status.상태이상_플래그(전투상태, 대상, "내성굴림불리점")
                내성성공 = dice_utils.내성_성공(내성보정치, 난이도, 불리=불리)
            if 내성성공 and 효과.get("내성성공시") == "데미지절반":
                피해 *= 0.5
            최종피해 = damage.피해_적용(
                전투상태, 대상, 피해, 속성=효과.get("속성"), 공격자=참가자
            )
            core._로그(
                전투상태,
                {
                    "공격자": 참가자["이름"],
                    "대상": 대상["이름"],
                    "피해": 최종피해,
                    "비고": f"'{이름}' 특성 턴종료시 발동",
                },
            )


def _특성_상태이상해제시_발동(전투상태, 참가자, 상태이상이름):
    """ "발동조건"에 "{상태이상이름} 해제시" 문자열이 들어있는 몬스터특성
    (기상 충격파 등)을, 참가자 자신에게서 그 상태이상이 사라질 때
    발동시킨다. "효과"가 "종류":"데미지+상태이상"이고 "타겟":"적전체"인
    것만 다룬다. _턴_시작_처리()의 지속턴 만료 시점에서 호출한다 -
    피격 등으로 인한 조기 해제는 아직 반영하지 않는다(TODO)."""
    for 이름, 정의 in _특성_목록(전투상태, 참가자):
        if 정의.get("분류") != "몬스터특성":
            continue
        조건 = 정의.get("발동조건")
        조건목록 = 조건 if isinstance(조건, list) else [조건]
        if f"{상태이상이름} 해제시" not in 조건목록:
            continue
        효과 = 정의.get("효과")
        if not isinstance(효과, dict) or 효과.get("종류") != "데미지+상태이상":
            continue
        if 효과.get("타겟") != "적전체":
            continue
        상대진영 = "아군" if 참가자["진영"] == "적" else "적"
        for 대상 in [
            p for p in 전투상태["참가자"] if p["진영"] == 상대진영 and p["생존"]
        ]:
            피해 = formula.수식_평가(
                str(효과.get("데미지", "0")), stats.기본_컨텍스트(전투상태, 참가자)
            )
            최종피해 = damage.피해_적용(
                전투상태, 대상, 피해, 속성=효과.get("속성"), 공격자=참가자
            )
            내성스탯 = 효과.get("내성")
            부여 = not 내성스탯
            if 내성스탯:
                난이도 = formula.수식_평가(
                    str(효과.get("난이도", "10")), stats.기본_컨텍스트(전투상태, 참가자)
                )
                내성보정치 = stats.유효_능력치_보정치(전투상태, 대상, 내성스탯)
                불리 = status.상태이상_플래그(전투상태, 대상, "내성굴림불리점")
                이점 = 상태이상_내성이점(전투상태, 대상, 효과.get("상태이상"))
                부여 = not dice_utils.내성_성공(
                    내성보정치, 난이도, 이점=이점, 불리=불리
                )
            if (
                부여
                and 효과.get("상태이상")
                and status.상태이상_면역(전투상태, 대상, 효과["상태이상"])
            ):
                status._면역_로그(전투상태, 대상, 효과["상태이상"], f"'{이름}' 특성")
                부여 = False
            if (
                부여
                and 효과.get("적용시점") in (None, "실패시")
                and 효과.get("상태이상")
            ):
                대상.setdefault("상태이상", []).append(
                    {
                        "이름": 효과.get("상태이상"),
                        "지속턴": 효과.get("지속턴", 1),
                    }
                )
            core._로그(
                전투상태,
                {
                    "공격자": 참가자["이름"],
                    "대상": 대상["이름"],
                    "피해": 최종피해,
                    "비고": f"'{이름}' 특성 발동 ('{상태이상이름}' 해제)",
                },
            )


def _집계_수(전투상태, 참가자, 집계조건):
    """몬스터특성 "집계조건"({"범위":"필드", "분류":..., "자신제외":...})에
    맞는 생존 참가자 수. "분류"는 몬스터 원본 "분류"와 비교한다."""
    수 = 0
    for p in 전투상태["참가자"]:
        if not p["생존"]:
            continue
        if 집계조건.get("자신제외") and p is 참가자:
            continue
        if 집계조건.get("분류") and p.get("원본", {}).get("분류") != 집계조건["분류"]:
            continue
        수 += 1
    return 수


def 전투시작_특성(전투상태):
    """ "발동조건":"전투시작시" 몬스터특성을 전투 시작 때 한 번 발동한다
    지금은 "종류":"임시생명력", "타겟":"자신"만 처리한다(겁쟁이).
    "수치" 수식의 "고블린수"는 "집계조건"으로 센 값으로 바꿔 평가한다."""
    for 참가자 in [p for p in 전투상태["참가자"] if p["생존"]]:
        for 이름, 정의 in _특성_목록(전투상태, 참가자):
            if 정의.get("분류") != "몬스터특성" or 정의.get("발동조건") != "전투시작시":
                continue
            효과 = 정의.get("효과")
            if not isinstance(효과, dict) or 효과.get("종류") != "임시생명력":
                continue
            if 효과.get("타겟", "자신") != "자신":
                continue
            수식 = str(효과.get("수치", "0"))
            집계조건 = 효과.get("집계조건") or {}
            if 집계조건:
                집계명 = f"{집계조건.get('분류', '')}수"
                수식 = 수식.replace(집계명, str(_집계_수(전투상태, 참가자, 집계조건)))
            양 = max(0, int(monster_actions._몬스터_수식값(전투상태, 참가자, 수식)))
            if 양 <= 0:
                continue
            참가자["임시생명력"] = 참가자.get("임시생명력", 0) + 양
            core._로그(
                전투상태,
                {
                    "대상": 참가자["이름"],
                    "비고": f"'{이름}' 특성 - 임시생명력 {양} 획득",
                },
            )
