def 유효_치명타범위(전투상태, 참가자):
    """치명타가 나는 최소 d20 눈. 기본 20에서 버프/특성의 "치명타범위"
    (치명타확률증가/급소지정 등, 양수 = 범위 확장)만큼 내려간다."""
    기본 = 참가자.get("치명타범위", 20)
    확장 = stats.버프디버프_수치(전투상태, 참가자, "치명타범위") + traits.특성_수치(
        전투상태, 참가자, "치명타범위"
    )
    return max(2, 기본 - 확장)


def 유효_펌블범위(전투상태, 공격자, 대상=None):
    """자동실패(펌블)가 나는 최대 d20 눈. 기본 1(참가자 "펌블범위")에 공격자의
    버프/디버프/특성 "펌블범위"(펌블확률증가 +1, 펌블확률감소 -1)와, 대상이 있으면
    대상의 "피격펌블범위"(피격펌블증가 +1, 피격펌블감소 -1 - 나를 공격하는 쪽의
    펌블 확률)를 더한다. 0이면 자연 1도 펌블이 아니다(0 아래로는 안 내려감)."""
    기본 = 공격자.get("펌블범위", 1)
    증감 = stats.버프디버프_수치(전투상태, 공격자, "펌블범위") + traits.특성_수치(
        전투상태, 공격자, "펌블범위"
    )
    if 대상 is not None:
        증감 += stats.버프디버프_수치(
            전투상태, 대상, "피격펌블범위"
        ) + traits.특성_수치(전투상태, 대상, "피격펌블범위")
    return max(0, int(기본 + 증감))


def 명중_판정(전투상태, 공격자, 대상, 명중률종류, 명중보너스=0):
    """명중_판정_계산()으로 판정한 뒤, 아군이 적의 공격을 받는 경우
    캐릭터 반응특성(회피형 - 크라우치 등, 회피성공시 반격 - 백스텝커터/
    리벤저)을 적용한다(피격판정_반응 참고)."""
    판정 = 명중_판정_계산(전투상태, 공격자, 대상, 명중률종류, 명중보너스)
    if 대상.get("진영") == "아군" and 공격자.get("진영") != "아군":
        판정 = reactions.가드_반응(전투상태, 공격자, 대상, 판정)
        판정 = reactions.피격판정_반응(전투상태, 공격자, 대상, 판정)
    return 판정


def 명중_판정_계산(전투상태, 공격자, 대상, 명중률종류, 명중보너스=0):
    """명중률종류(job_skill_format.py 값, 또는 몬스터 패턴의 "OO판정")에
    따라 판정한다. 반환값: {"성공", "자연눈", "치명타", "자동실패"}.

    "대상"이 "피격시강제치명타" 상태면 명중률종류와 상관없이 항상
    명중+치명타로 처리한다. "대상"의 "회피불리점"은 공격자에게 이점을,
    "공격자"의 "명중불리점"은 공격자 본인에게 불리를 준다."""
    강제치명타 = status.상태이상_플래그(전투상태, 대상, "피격시강제치명타")

    if 명중률종류 == "자동":
        return {"성공": True, "자연눈": None, "치명타": 강제치명타, "자동실패": False}

    이점 = status.상태이상_플래그(전투상태, 대상, "회피불리점")
    불리 = status.상태이상_플래그(전투상태, 공격자, "명중불리점")
    눈 = dice_utils.d20_굴림(이점=이점, 불리=불리)
    치명타범위 = 유효_치명타범위(전투상태, 공격자)
    펌블범위 = 유효_펌블범위(전투상태, 공격자, 대상)

    if 강제치명타:
        return {"성공": True, "자연눈": 눈, "치명타": True, "자동실패": False}

    if 명중률종류 == "필중":
        return {
            "성공": True,
            "자연눈": 눈,
            "치명타": 눈 >= 치명타범위,
            "자동실패": False,
        }

    if 눈 <= 펌블범위:
        return {"성공": False, "자연눈": 눈, "치명타": False, "자동실패": True}
    if 눈 >= 치명타범위:
        return {"성공": True, "자연눈": 눈, "치명타": True, "자동실패": False}

    보정치 = 0
    if 명중률종류 == "보정명중률":
        보정치 = stats.평타_능력치_보정치(전투상태, 공격자)
    elif 명중률종류 == "주문시전명중률":
        보정치 = stats.주문시전_보정치(전투상태, 공격자)
    elif 명중률종류 == "기본명중률":
        보정치 = 0
    elif isinstance(명중률종류, str) and 명중률종류.endswith("판정"):
        보정치 = stats.유효_능력치_보정치(전투상태, 공격자, 명중률종류[:-2])

    명중률보너스 = 공격자["원본"].get("명중률보너스", 0)
    if not isinstance(명중률보너스, (int, float)):
        명중률보너스 = 0
    # 장비(전 부위+활성 세트) 명중률보너스 - 아군만, 모든 명중 굴림.
    명중률보너스 += stats.장비_수치(공격자, "명중률보너스")
    명중률보너스 += stats.버프디버프_수치(전투상태, 공격자, "명중보너스")
    명중률보너스 += traits.특성_수치(
        전투상태, 공격자, "명중보너스", 명중률종류=명중률종류, 대상=대상
    )
    명중률보너스 += traits.칭호_수치(전투상태, 공격자, "명중보너스")

    최종 = 눈 + 보정치 + 명중률보너스 + 명중보너스
    대상AC = stats.최종AC(전투상태, 대상)
    return {
        "성공": 최종 >= 대상AC,
        "자연눈": 눈,
        "치명타": False,
        "자동실패": False,
        "명중결과": 최종,
        "대상AC": 대상AC,
    }


def 최종피해_계산(원래피해, 방어력, 보호률):
    """비율(보호률) 감소를 먼저 적용하고, 고정(방어력) 감소를 나중에 뺀다.
    최종피해 = max(0, 원래피해 x (1-보호률) - 방어력)"""
    return max(0, round(원래피해 * (1 - 보호률) - 방어력))


_속성_줄임말 = {
    "무": "무속성",
    "화": "화속성",
    "수": "수속성",
    "명": "명속성",
    "암": "암속성",
}


def 속성_정식명(속성):
    """속성 이름은 "무속성"/"화속성"/"수속성"/"명속성"/"암속성"으로 통일했다(데이터
    일괄 개명). 혹시 남은 줄임말("화" 등)은 정식명으로 바꾸고, 그 밖의 값은 그대로 둔다."""
    return _속성_줄임말.get(속성, 속성) if isinstance(속성, str) else 속성


def 피해_속성배율(전투상태, 대상, 속성):
    """속성이 리스트면 가장 큰 배율, None이면 1(피해_적용 공용)."""
    if isinstance(속성, list):
        return max((속성_피해배율(전투상태, 대상, s) for s in 속성), default=1.0)
    if 속성 is None:
        return 1.0
    return 속성_피해배율(전투상태, 대상, 속성)


def 속성_피해배율(전투상태, 대상, 속성):
    """단일 속성 하나에 대해, 대상의 "저항"/"취약"(원본 고정 리스트 +
    특성이 부여하는 리스트)을 반영한 배율을 계산한다(저항 0.5배/취약
    2배, 둘 다면 상쇄돼 1배). 비교 전에 속성을 짧은 표기로 맞춘다
    (속성_정식명 참고)."""
    속성 = 속성_정식명(속성)
    원본 = 대상.get("원본", {})
    저항목록 = list(원본.get("저항") or []) + traits.특성_문자열_변동값_목록(
        전투상태, 대상, "저항"
    )
    취약목록 = list(원본.get("취약") or []) + traits.특성_문자열_변동값_목록(
        전투상태, 대상, "취약"
    )
    면역목록 = list(원본.get("면역") or []) + traits.특성_문자열_변동값_목록(
        전투상태, 대상, "면역"
    )
    if 속성 in [속성_정식명(s) for s in 면역목록]:
        return 0.0  # 면역: 그 속성 피해는 0
    저항목록 = [속성_정식명(s) for s in 저항목록]
    취약목록 = [속성_정식명(s) for s in 취약목록]
    배율 = 1.0
    if 속성 in 저항목록:
        배율 *= 0.5
    if 속성 in 취약목록:
        배율 *= 2
    return 배율


def 속성_최종배율(전투상태, 공격측, 대상, 속성):
    """방어력/보호률 뒤 최종피해에 곱하는 배율 - 공격측 속성강화 1당 +10%, 대상
    속성내성 1당 -10%(각각 0 아래로 안 내려감). 저항/취약/면역과 곱연산."""
    속성 = 속성_정식명(속성)
    강화 = stats.속성_보정합(전투상태, 공격측, "속성강화", 속성)
    내성 = stats.속성_보정합(전투상태, 대상, "속성내성", 속성)
    return max(0.0, 1 + 0.1 * 강화) * max(0.0, 1 - 0.1 * 내성)


def _주속성(전투상태, 공격측, 대상, 속성):
    """속성이 여러 개면 저항/취약/면역 x 강화/내성이 가장 큰(가장 아픈) 속성 하나."""
    if not isinstance(속성, list):
        return 속성
    if not 속성:
        return None
    return max(
        속성,
        key=lambda s: (
            속성_피해배율(전투상태, 대상, s) * 속성_최종배율(전투상태, 공격측, 대상, s)
        ),
    )


def 피해_적용(
    전투상태,
    대상,
    피해량,
    *,
    피해감소무시=False,
    방어력무시=False,
    속성=None,
    공격자=None,
    추가피해목록=None,
    공격측=None,
    최종피해배율=1,
):
    """방어력/보호률을 적용해 최종 피해를 계산하고 대상 HP에서 뺀다.
    피해감소무시=True면 방어력/보호률 자체를 무시한다(출혈 등 지속피해용).

    속성이 주어지면 대상["원본"]의 "저항"/"취약"(및 특성이 부여하는
    저항/취약 - 예: 종족:좀비)을 확인해 절반(저항)/2배(취약)로
    조정한다(둘 다 있으면 상쇄). 속성이 리스트면(예: 굴 구위시의
    ["무속성", "수속성", "암속성"]) 각 속성으로 계산했을 때 나오는
    배율 중 가장 큰 쪽을 쓴다("속성이 여러 개면 더 높은 데미지 쪽
    속성으로 공격한다" - 속성 다중판정의 기본 설정).
    속성=None(지속피해형 등 속성 정보가 없는 경우)이면 이 조정을
    받지 않는다.

    공격자: 적의 공격/능력으로 아군이 피해를 받으면 넘긴다 -
    그때만 "피격시" 반응특성(건가드/위상 변화)을 적용한다(피격피해_반응).
    지속피해 등 공격자가 없는 피해는 반응 대상이 아니다.

    추가피해목록: [(값, 속성), ...] - 공격 속성과 따로 자기
    속성으로 저항/취약을 적용한 뒤 본 피해에 더한다(은탄의 명속성 추가피해).
    방어력/보호률은 합친 피해에 한 번만 적용한다.

    면역 속성이면 그 속성 피해는 0. 속성강화(공격측 - 없으면 공격자)/속성내성(대상)은
    방어력/보호률 뒤의 최종피해에 곱한다(속성_최종배율). 추가피해가 있으면 최종피해를
    부분(저항/취약 반영 후) 비율로 나눠 부분마다 자기 속성의 배율을 곱한다.
    공격측: 반응특성 없이 속성강화만 볼 공격한 참가자(아군 공격 등).
    최종피해배율: 스킬강화(레벨 12)의 배율 - 속성 배율 뒤 최종피해에 곱한다(반올림)."""
    공격측 = 공격측 or 공격자
    속성 = _주속성(전투상태, 공격측, 대상, 속성)
    # (저항/취약/면역 반영 값, 속성) - 속성마다 따로 계산하고 방어는 합에 한 번
    부분들 = [(피해량 * 피해_속성배율(전투상태, 대상, 속성), 속성)]
    for 추가값, 추가속성 in 추가피해목록 or []:
        추가속성 = _주속성(전투상태, 공격측, 대상, 추가속성)
        부분들.append((추가값 * 피해_속성배율(전투상태, 대상, 추가속성), 추가속성))
    피해량 = sum(값 for 값, _ in 부분들)

    if 피해감소무시:
        최종피해 = max(0, round(피해량))
    else:
        방어력 = 0 if 방어력무시 else stats.유효_방어력(전투상태, 대상)
        보호률 = stats.유효_보호률(전투상태, 대상)
        최종피해 = 최종피해_계산(피해량, 방어력, 보호률)
    if 피해량 > 0 and any(s is not None for _, s in 부분들):
        # 속성강화/속성내성은 방어 뒤 최종피해를 부분 비율로 나눠 각자 속성으로 곱한다
        최종피해 = max(
            0,
            round(
                sum(
                    최종피해
                    * (값 / 피해량)
                    * (1 if s is None else 속성_최종배율(전투상태, 공격측, 대상, s))
                    for 값, s in 부분들
                )
            ),
        )
    if 최종피해배율 != 1:
        최종피해 = max(0, round(최종피해 * 최종피해배율))

    if (
        공격자 is not None
        and 대상.get("진영") == "아군"
        and 공격자.get("진영") != "아군"
        and 최종피해 > 0
    ):
        최종피해 = reactions.피격피해_반응(전투상태, 공격자, 대상, 최종피해)

    # 임시생명력이 있으면 현재HP보다 먼저 깎는다. 반환값(최종피해)은
    # 이 공격이 입힌 총 피해 그대로다 - 실제로 현재HP에서 빠지는 양만
    # 임시생명력이 흡수한 만큼 줄어든다.
    임시생명력 = 대상.get("임시생명력", 0)
    실HP피해 = 최종피해
    if 임시생명력 > 0:
        흡수량 = min(임시생명력, 최종피해)
        대상["임시생명력"] = 임시생명력 - 흡수량
        실HP피해 = 최종피해 - 흡수량

    대상["현재HP"] = max(0, 대상["현재HP"] - 실HP피해)
    if 대상["현재HP"] <= 0:
        대상["생존"] = False
    return 최종피해


def 피격_처리(전투상태, 공격자, 대상, 판정, 속성=None):
    """명중 시 상태이상 부가효과를 처리한다: 감전(피격시추가피해),
    수면(무조건 해제), 빙결(화속성 피격시 해제), 은신/집중(내성굴림
    실패 시 해제 - DC는 인스턴스의 "해제난이도", 기본 10). 이어서
    공격자의 "발동조건":"공격명중시" 몬스터특성(화염의 마녀/빙결의
    마녀 등)도 여기서 함께 발동시킨다(일반공격_실행/_몬스터_패턴_실행
    공용 훅)."""
    if not 판정.get("성공"):
        return
    for 항목, 정의 in list(status.상태이상_정의_목록(전투상태, 대상)):
        효과 = 정의.get("효과", {})

        if 효과.get("타입") == "피격시추가피해" and 효과.get("발동시점") == "피격시":
            피해 = formula.수식_평가(효과.get("수식", "0"), {"차수": core.차수(대상)})
            최종피해 = 피해_적용(
                전투상태,
                대상,
                피해,
                피해감소무시=효과.get("피해감소무시", False),
                방어력무시=효과.get("방어력무시", False),
            )
            core.로그(
                전투상태,
                {
                    "공격자": 항목["이름"],
                    "대상": 대상["이름"],
                    "피해": 최종피해,
                    "비고": "지속피해형 피격시추가피해",
                },
            )

        해제조건 = 효과.get("해제조건")
        속성들 = 속성 if isinstance(속성, list) else [속성]
        화속성피격 = "화속성" in [속성_정식명(s) for s in 속성들]
        if 해제조건 == "피격시":
            if 항목 in 대상.get("상태이상", []):
                대상["상태이상"].remove(항목)
        elif 해제조건 == "화속성피격시" and 화속성피격:
            if 항목 in 대상.get("상태이상", []):
                대상["상태이상"].remove(항목)
        elif isinstance(해제조건, list):
            for 조건항목 in 해제조건:
                내성스탯 = 조건항목.get("내성")
                if 조건항목.get("조건") == "피격시" and 내성스탯:
                    난이도 = 항목.get("해제난이도", 10)
                    내성보정치 = stats.유효_능력치_보정치(전투상태, 대상, 내성스탯)
                    불리 = status.상태이상_플래그(전투상태, 대상, "내성굴림불리점")
                    if not dice_utils.내성_성공(내성보정치, 난이도, 불리=불리):
                        if 항목 in 대상.get("상태이상", []):
                            대상["상태이상"].remove(항목)
                    break

    traits.특성_공격명중시_발동(전투상태, 공격자, 대상)


