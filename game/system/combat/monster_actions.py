def _몬스터_패턴_대상목록(전투상태, 몬스터참가자, 패턴, 기본대상):
    """패턴의 "타겟"에 따라 실제로 공격할 대상 목록을 정한다.

    "적단일"(기본값/미지정)이면 monster_ai가 고른 기본대상 1체 그대로.
    "적전체"면 반대 진영 생존자 전원. "적3체"면 밸런스 기준의
    범위공격(주대상 1체+좌우 각 1체, 최대 3체, 구석이면 2체)처럼
    기본대상을 중심으로 "대형위치" 기준 좌우 인접까지 포함한다."""
    타겟 = 패턴.get("타겟", "적단일")
    상대진영 = "아군" if 몬스터참가자["진영"] == "적" else "적"
    if 타겟 == "적전체":
        return [p for p in 전투상태["참가자"] if p["진영"] == 상대진영 and p["생존"]]
    if 타겟 == "적3체":
        같은편전체 = sorted(
            (p for p in 전투상태["참가자"] if p["진영"] == 상대진영),
            key=lambda p: p.get("대형위치", 0),
        )
        if 기본대상 not in 같은편전체:
            return [기본대상]
        idx = 같은편전체.index(기본대상)
        후보 = 같은편전체[max(0, idx - 1) : idx + 2]
        return [p for p in 후보 if p["생존"]]
    return [기본대상]


def 몬스터_데미지보너스(전투상태, 몬스터참가자):
    """몬스터 공통 데미지보너스 = 원본 "데미지보너스"(숫자 또는 수식,
    "미정"처럼 평가 불가면 0) + 특성 + 칭호. 패턴 자체의 "데미지보너스"는
    호출부가 따로 더한다."""
    원본값 = participants._몬스터_수식_평가(
        몬스터참가자["원본"].get("데미지보너스", 0), 몬스터참가자["원본"], 0
    )
    if not isinstance(원본값, (int, float)):
        원본값 = 0
    return (
        원본값
        + traits.특성_수치(전투상태, 몬스터참가자, "데미지보너스")
        + traits.칭호_수치(전투상태, 몬스터참가자, "데미지보너스")
    )


def _몬스터_패턴_실행(전투상태, 몬스터참가자, 패턴, 대상):
    """패턴 하나를 대상 1체에게 실행한다("공격횟수"만큼 같은 대상을
    반복 타격). 명중한 타격마다 패턴의 "효과"(job_skill_format.py
    <효과 하위 양식> "상태이상")를 적용하고, 빗나간 타격은 "명중실패시
    효과"(타우 아미/타우 어썰터의 들이받기 자기 기절 등, "대상":"자신"
    일 때만)를 적용한다."""
    명중률 = 패턴.get("명중률")
    if (
        not isinstance(명중률, str)
        or "데미지" not in 패턴
        or "미정" in str(패턴.get("데미지"))
    ):
        결과 = {
            "공격자": 몬스터참가자["이름"],
            "대상": 대상["이름"],
            "패턴": 패턴.get("이름"),
            "비고": "데이터 미비(미정)로 스킵",
        }
        core._로그(전투상태, 결과)
        return 결과

    명중보너스 = 패턴.get("명중보너스", 0)
    if not isinstance(명중보너스, (int, float)):
        명중보너스 = 0

    공격횟수 = 패턴.get("공격횟수", 1)
    if not isinstance(공격횟수, int):
        공격횟수 = 1

    능력치이름 = 명중률[:-2] if 명중률.endswith("판정") else "근력"
    총피해 = 0
    타격들 = []
    for _ in range(공격횟수):
        판정 = damage.명중_판정(전투상태, 몬스터참가자, 대상, 명중률, 명중보너스)
        타격 = {"판정": 판정, "피해": 0}
        if 판정["성공"]:
            보정치 = stats.유효_능력치_보정치(전투상태, 몬스터참가자, 능력치이름)
            # 몬스터는 "차수" 미사용 - 1 고정(TODO: 성장 개념 생기면 재검토).
            피해 = formula.수식_평가(
                패턴["데미지"],
                {"보정치": 보정치, "차수": 1, "능력치": 몬스터참가자["원본"]},
                치명타=판정["치명타"],
            )

            데미지보너스 = 패턴.get("데미지보너스", 0)
            if isinstance(데미지보너스, (int, float)):
                피해 += 데미지보너스
            피해 += 몬스터_데미지보너스(전투상태, 몬스터참가자)

            타격["피해"] = damage.피해_적용(
                전투상태, 대상, 피해, 속성=패턴.get("속성"), 공격자=몬스터참가자
            )
            damage.피격_처리(전투상태, 몬스터참가자, 대상, 판정, 속성=패턴.get("속성"))
            총피해 += 타격["피해"]
            traits._상태이상_효과_적용(
                전투상태,
                몬스터참가자,
                대상,
                패턴.get("효과"),
                f"'{패턴.get('이름')}' 패턴",
            )
        else:
            명중실패시효과 = 패턴.get("명중실패시효과")
            if (
                isinstance(명중실패시효과, dict)
                and 명중실패시효과.get("대상") == "자신"
            ):
                traits._상태이상_효과_적용(
                    전투상태,
                    몬스터참가자,
                    몬스터참가자,
                    명중실패시효과,
                    f"'{패턴.get('이름')}' 패턴(빗나감)",
                )
        타격들.append(타격)

    결과 = {
        "공격자": 몬스터참가자["이름"],
        "대상": 대상["이름"],
        "패턴": 패턴.get("이름"),
        "타격": 타격들,
        "총피해": 총피해,
    }
    core._로그(전투상태, 결과)
    return 결과


def _몬스터_패턴_실행_다중(전투상태, 몬스터참가자, 패턴, 대상목록):
    """대상이 둘 이상인 패턴("적전체"/"적3체")을 실행한다. "공격횟수"는
    "같은 대상을 반복 타격"이 아니라 "대상 목록 전체를 상대로 한 회차를
    반복"으로 해석한다(체인 메테오 = 메테오를 3번 연속 - 사용자 설명
    재현, 확정된 해석은 아니다). 각 회차·각 대상은 _몬스터_패턴_실행을
    그대로 재사용해 "효과"/"명중실패시효과"/특성 공격명중시 훅을
    동일하게 받는다(공격횟수는 회차 쪽에서 이미 소진했으므로 내부
    호출에서는 1로 고정)."""
    공격횟수 = 패턴.get("공격횟수", 1)
    if not isinstance(공격횟수, int):
        공격횟수 = 1
    단일회_패턴 = dict(패턴)
    단일회_패턴["공격횟수"] = 1

    결과들 = []
    for _ in range(공격횟수):
        for 대상 in 대상목록:
            if not 대상["생존"]:
                continue
            결과들.append(_몬스터_패턴_실행(전투상태, 몬스터참가자, 단일회_패턴, 대상))
    return 결과들


def _몬스터_자폭패턴_실행(전투상태, 몬스터참가자, 패턴):
    """ "자폭패턴"(고블린 십장/고블린 투척십장의 "자폭명령" 등) 전용
    실행 함수(신규 - "공격패턴"과 달리 명중 판정 없이 즉발로 처리된다).

    패턴["폭사대상"](몬스터명 리스트, 예: ["고블린", "고블린 투척병"])에
    해당하고 몬스터참가자와 같은 진영인 생존 참가자를 전부 즉사시킨다
    (방어력/보호률을 거치지 않는 자폭이므로 피해_적용이 아니라 현재HP를
    직접 0으로 만든다 - 시전자 자신은 "고블린 십장"/"고블린 투척십장"
    이라는 이름이 "폭사대상" 목록에 없으므로 대상에서 자연히 빠진다).

    죽은 한 마리마다 상대 진영 생존자 중 무작위 1체를 다시 뽑아
    패턴["데미지"] 만큼 피해를 입힌다(같은 대상이 여러 번
    맞을 수 있음 - 매번 새로 무작위 선택, 명중 판정 없이 확정 적중).
    상대 진영 생존자가 없어지면(전멸) 남은 폭사는 피해 없이 죽기만
    한다."""
    폭사대상이름 = 패턴.get("폭사대상") or []
    폭사자들 = [
        p
        for p in 전투상태["참가자"]
        if p["진영"] == 몬스터참가자["진영"]
        and p["생존"]
        and p.get("원본", {}).get("몬스터명") in 폭사대상이름
    ]

    상대진영 = "아군" if 몬스터참가자["진영"] == "적" else "적"
    타격들 = []
    for 폭사자 in 폭사자들:
        폭사자["현재HP"] = 0
        폭사자["생존"] = False

        생존상대 = [
            p for p in 전투상태["참가자"] if p["진영"] == 상대진영 and p["생존"]
        ]
        if not 생존상대:
            continue
        대상 = random.choice(생존상대)
        피해 = formula.수식_평가(
            패턴.get("데미지", "0"), {"능력치": 몬스터참가자["원본"]}
        )
        피해 += 몬스터_데미지보너스(전투상태, 몬스터참가자)
        최종피해 = damage.피해_적용(
            전투상태, 대상, 피해, 속성=패턴.get("속성"), 공격자=몬스터참가자
        )
        타격들.append(
            {"폭사자": 폭사자["이름"], "대상": 대상["이름"], "피해": 최종피해}
        )

    결과 = {
        "공격자": 몬스터참가자["이름"],
        "패턴": 패턴.get("이름"),
        "폭사수": len(폭사자들),
        "타격": 타격들,
    }
    core._로그(전투상태, 결과)
    return 결과


def _몬스터_패턴_컨텍스트(전투상태, 몬스터참가자):
    """버프/회복/내성 패턴 수식용 컨텍스트. "차수"/"레벨"은 gameflow가
    던전 데이터에서 채워 넣은 몬스터 원본 값을 쓰고(없으면 1), 능력치는
    버프가 반영된 값을 쓴다."""
    원본 = 몬스터참가자["원본"]
    return {
        "차수": 원본.get("차수") or 1,
        "레벨": 원본.get("레벨") or 1,
        "보정치": stats.유효_능력치_보정치(전투상태, 몬스터참가자, "근력"),
        "능력치": stats.유효_능력치(전투상태, 몬스터참가자),
    }


def _몬스터_수식값(전투상태, 몬스터참가자, 수식, 기본값=0):
    if isinstance(수식, (int, float)):
        return 수식
    try:
        값 = formula.수식_평가(str(수식), _몬스터_패턴_컨텍스트(전투상태, 몬스터참가자))
    except Exception:
        return 기본값
    return 값 if isinstance(값, (int, float)) else 기본값


def _몬스터_버프_부여(전투상태, 대상, 이름, 지속턴):
    """skill_system.이름있는효과_부여의 최소판(combat 패키지는
    skill_system을 부르지 않는다). buff.py/debuff.py의 "중첩":True는
    인스턴스를 새로 추가, skill_effects.py 기술효과(소환:비명초 등)의
    "중첩":True는 기존 인스턴스 중첩+1, 그 외는 지속턴만 갱신한다.
    정의에 없는 이름도 이름만으로 등록한다.

    이름이 버프/디버프/기술효과 정의에는 없고 status_effects.py 상태이상이면
    (슈퍼아머 등) 상태이상 목록에 건다 - 면역 확인, 이미 있으면(비중첩)
    지속턴만 갱신."""
    정의, 출처 = resources.효과정의_조회(이름)
    상태정의 = 전투상태.get("상태이상정의", {}).get(이름)
    if 정의 is None and 상태정의 is not None:
        if status.상태이상_면역(전투상태, 대상, 이름):
            status._면역_로그(전투상태, 대상, 이름)
            return
        목록 = 대상.setdefault("상태이상", [])
        기존 = next((i for i in 목록 if i.get("이름") == 이름), None)
        if 기존 is not None and not 상태정의.get("중첩"):
            if 지속턴 is not None:
                기존["지속턴"] = 지속턴
            return
        새항목 = {"이름": 이름}
        if 지속턴 is not None:
            새항목["지속턴"] = 지속턴
        if 상태정의.get("중첩"):
            새항목["중첩"] = 1
        목록.append(새항목)
        return
    목록이름 = "디버프" if 출처 == "디버프" else "버프"
    if 지속턴 is None and 정의 is not None and isinstance(정의.get("지속턴"), int):
        지속턴 = 정의["지속턴"]
    중첩형 = bool(정의 and 정의.get("중첩"))

    기존 = next((i for i in 대상[목록이름] if i.get("이름") == 이름), None)
    if 기존 is not None and not (중첩형 and 출처 in ("버프", "디버프")):
        if 중첩형:
            기존["중첩"] = 기존.get("중첩", 1) + 1
        if 지속턴 is not None:
            기존["지속턴"] = 지속턴
        return
    새항목 = {"이름": 이름, "중첩": 1}
    if 지속턴 is not None:
        새항목["지속턴"] = 지속턴
    대상[목록이름].append(새항목)


def _몬스터_버프패턴_실행(전투상태, 몬스터참가자, 패턴):
    """ "타입":"버프패턴" - "타겟"(자신/아군전체)에게 "버프획득"을 걸고,
    "임시생명력"이 있으면 그만큼 더한다."""
    if 패턴.get("타겟") == "아군전체":
        대상목록 = [
            p
            for p in 전투상태["참가자"]
            if p["진영"] == 몬스터참가자["진영"] and p["생존"]
        ]
    else:
        대상목록 = [몬스터참가자]

    지속턴 = 패턴.get("지속턴")
    지속턴 = 지속턴 if isinstance(지속턴, int) else None
    버프이름들 = 패턴.get("버프획득") or []
    if isinstance(버프이름들, str):
        버프이름들 = [버프이름들]

    for 대상 in 대상목록:
        for 이름 in 버프이름들:
            _몬스터_버프_부여(전투상태, 대상, 이름, 지속턴)
        if 패턴.get("임시생명력"):
            양 = max(0, int(_몬스터_수식값(전투상태, 몬스터참가자, 패턴["임시생명력"])))
            대상["임시생명력"] = 대상.get("임시생명력", 0) + 양

    결과 = {
        "공격자": 몬스터참가자["이름"],
        "패턴": 패턴.get("이름"),
        "대상": [p["이름"] for p in 대상목록],
        "버프": 버프이름들,
    }
    core._로그(전투상태, 결과)
    return 결과


def _몬스터_회복패턴_실행(전투상태, 몬스터참가자, 패턴):
    """ "타입":"회복패턴" - "타겟"이 "아군최저체력비율1체"면 같은 편
    생존자 중 현재HP/최대HP 비율이 가장 낮은 1체, "자신"이면 자신,
    "아군전체"면 같은 편 전원을 "회복량"만큼(최대HP까지) 회복한다."""
    같은편 = [
        p for p in 전투상태["참가자"] if p["진영"] == 몬스터참가자["진영"] and p["생존"]
    ]
    타겟 = 패턴.get("타겟")
    if 타겟 == "아군전체":
        대상목록 = 같은편
    elif 타겟 == "자신":
        대상목록 = [몬스터참가자]
    else:

        def 비율(p):
            최대 = stats.유효_최대HP(전투상태, p)
            return p["현재HP"] / 최대 if 최대 > 0 else 1

        대상목록 = [min(같은편, key=비율)] if 같은편 else []

    회복들 = []
    for 대상 in 대상목록:
        양 = max(0, int(_몬스터_수식값(전투상태, 몬스터참가자, 패턴.get("회복량", 0))))
        최대HP = int(stats.유효_최대HP(전투상태, 대상))
        실회복 = max(0, min(양, 최대HP - 대상["현재HP"]))
        대상["현재HP"] += 실회복
        회복들.append({"대상": 대상["이름"], "회복": 실회복})

    결과 = {"공격자": 몬스터참가자["이름"], "패턴": 패턴.get("이름"), "회복": 회복들}
    core._로그(전투상태, 결과)
    return 결과


def _몬스터_내성패턴_실행(전투상태, 몬스터참가자, 패턴, 대상목록):
    """ "데미지" 대신 "내성"/"난이도"/"실패시데미지"가 있는 공격패턴(포효 등).
    대상마다 내성굴림을 하고, 실패한 대상에게만 "실패시데미지"(+몬스터
    공통 데미지보너스)를 입힌다. 명중 굴림은 없다."""
    난이도 = _몬스터_수식값(전투상태, 몬스터참가자, 패턴.get("난이도", 10), 10)
    내성스탯 = 패턴.get("내성")
    타격들 = []
    총피해 = 0
    for 대상 in 대상목록:
        if not 대상["생존"]:
            continue
        내성보정치 = (
            stats.유효_능력치_보정치(전투상태, 대상, 내성스탯) if 내성스탯 else 0
        )
        불리 = status.상태이상_플래그(전투상태, 대상, "내성굴림불리점")
        if 내성스탯 and dice_utils.내성_성공(내성보정치, 난이도, 불리=불리):
            타격들.append({"대상": 대상["이름"], "내성": "성공", "피해": 0})
            continue
        피해 = _몬스터_수식값(
            전투상태, 몬스터참가자, 패턴.get("실패시데미지", 0)
        ) + 몬스터_데미지보너스(전투상태, 몬스터참가자)
        최종피해 = damage.피해_적용(
            전투상태, 대상, 피해, 속성=패턴.get("속성"), 공격자=몬스터참가자
        )
        총피해 += 최종피해
        타격들.append({"대상": 대상["이름"], "내성": "실패", "피해": 최종피해})
        traits._상태이상_효과_적용(
            전투상태, 몬스터참가자, 대상, 패턴.get("효과"), f"'{패턴.get('이름')}' 패턴"
        )

    결과 = {
        "공격자": 몬스터참가자["이름"],
        "패턴": 패턴.get("이름"),
        "난이도": 난이도,
        "타격": 타격들,
        "총피해": 총피해,
    }
    core._로그(전투상태, 결과)
    return 결과


def 몬스터_턴_실행(전투상태, 몬스터참가자):
    """몬스터 턴 자동 처리. 행동/타겟 선택은 monster_ai.py에 맡기고
    명중/피해 계산은 여기서 한다. "행동불가" 상태면 곧바로 무행동.

    monster_ai가 고른 것은 항상 단일 대상(아군 1체)이지만, 패턴의
    "타겟"이 "적전체"/"적3체"면 그 대상을 기준으로 실제 공격 범위를
    넓힌다(_몬스터_패턴_대상목록 참고) - 신규."""
    몬스터참가자["몬스터턴카운트"] += 1
    생존아군 = [p for p in 전투상태["참가자"] if p["진영"] == "아군" and p["생존"]]
    if not 생존아군:
        return None

    if status.상태이상_플래그(전투상태, 몬스터참가자, "행동불가"):
        결과 = {"공격자": 몬스터참가자["이름"], "행동": "행동불가 상태로 무행동"}
        core._로그(전투상태, 결과)
        return 결과

    행동 = monster_ai.행동_선택(몬스터참가자)
    if 행동 is None or 행동.get("타입") == "무행동":
        결과 = {"공격자": 몬스터참가자["이름"], "행동": "무행동"}
        core._로그(전투상태, 결과)
        return 결과

    if 행동.get("타입") == "자폭패턴":
        return _몬스터_자폭패턴_실행(전투상태, 몬스터참가자, 행동)
    if 행동.get("타입") == "버프패턴":
        return _몬스터_버프패턴_실행(전투상태, 몬스터참가자, 행동)
    if 행동.get("타입") == "회복패턴":
        return _몬스터_회복패턴_실행(전투상태, 몬스터참가자, 행동)

    대상 = monster_ai.타겟_선택(생존아군, 전투상태["상태이상정의"])
    대상목록 = _몬스터_패턴_대상목록(전투상태, 몬스터참가자, 행동, 대상)
    if "실패시데미지" in 행동 and "데미지" not in 행동:
        결과 = _몬스터_내성패턴_실행(전투상태, 몬스터참가자, 행동, 대상목록)
    elif len(대상목록) <= 1:
        결과 = _몬스터_패턴_실행(
            전투상태, 몬스터참가자, 행동, 대상목록[0] if 대상목록 else 대상
        )
    else:
        결과 = _몬스터_패턴_실행_다중(전투상태, 몬스터참가자, 행동, 대상목록)
    reactions.반응대기_처리(전투상태)
    return 결과


