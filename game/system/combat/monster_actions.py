# 몬스터 소환수 행동
# =====================================================
# 몬스터가 버프패턴으로 얻은 "소환:OO" 버프(소환:비명초/소환:나이아스/
# 소환:아도르 등)를 소환수로 보고, 그 몬스터의 턴이 끝날 때
# summon_00.py "소환수목록"의 "행동표"(1d6)를 굴려 실행한다. 아군 소환수
# (skill_system._소환수_행동_실행)와 같은 규칙이지만 대상은 반대 진영
# (아군 파티)이다. 소환수 이름은 버프 정의의 "효과"."소환수이름", 없으면
# 버프 이름에서 "소환:"을 뗀 값. 버프 정의 "효과"에 "중첩당공격":True가
# 있으면(비명초) 중첩 수만큼 행동을 반복한다. 명중 판정은 소환한 몬스터의
# 능력치로 한다("능력치참조":"시전자").


def _몬스터_소환수_목록(몬스터참가자):
    결과 = []
    for 항목 in 몬스터참가자.get("버프", []):
        이름 = 항목.get("이름", "")
        if not 이름.startswith("소환:"):
            continue
        정의, _ = resources.효과정의_조회(이름)
        효과 = (정의 or {}).get("효과") or {}
        소환수이름 = 효과.get("소환수이름") or 이름[len("소환:") :]
        횟수 = 항목.get("중첩", 1) if 효과.get("중첩당공격") else 1
        결과.append((소환수이름, max(1, int(횟수))))
    return 결과


def _소환수_공격_실행(전투상태, 소환자, 행동, 표시이름):
    상대진영 = "아군" if 소환자["진영"] == "적" else "적"
    생존상대 = [p for p in 전투상태["참가자"] if p["진영"] == 상대진영 and p["생존"]]
    if not 생존상대:
        return
    타겟 = 행동.get("타겟", "적단일")
    공격횟수 = 행동.get("공격횟수", 1)
    if not isinstance(공격횟수, int):
        공격횟수 = 1
    명중률 = 행동.get("명중률", "자동")
    명중보너스 = 행동.get("명중보너스", 0)
    if not isinstance(명중보너스, (int, float)):
        명중보너스 = 0

    if 타겟 == "적전체":
        대상목록 = 생존상대
    elif 타겟 in ("적랜덤", "적랜덤반복"):
        대상목록 = None  # 타격마다 새로 고른다
    else:
        기본 = monster_ai.타겟_선택(생존상대, 전투상태["상태이상정의"])
        if 타겟 == "적3체":
            대상목록 = _몬스터_패턴_대상목록(전투상태, 소환자, {"타겟": "적3체"}, 기본)
        else:
            대상목록 = [기본]

    타격들 = []
    for _ in range(공격횟수):
        이번대상들 = 대상목록
        if 이번대상들 is None:
            살아있는 = [p for p in 생존상대 if p["생존"]]
            이번대상들 = [random.choice(살아있는)] if 살아있는 else []
        for 대상 in 이번대상들:
            if not 대상["생존"]:
                continue
            판정 = damage.명중_판정(전투상태, 소환자, 대상, 명중률, 명중보너스)
            타격 = {"대상": 대상["이름"], "판정": 판정, "피해": 0}
            if 판정["성공"]:
                피해 = formula.수식_평가(
                    str(행동.get("데미지", "0")),
                    _몬스터_패턴_컨텍스트(전투상태, 소환자),
                    치명타=판정["치명타"],
                )
                타격["피해"] = damage.피해_적용(
                    전투상태, 대상, 피해, 속성=행동.get("속성"), 공격자=소환자
                )
                damage.피격_처리(전투상태, 소환자, 대상, 판정, 속성=행동.get("속성"))
            타격들.append(타격)
    core._로그(
        전투상태,
        {
            "공격자": 표시이름,
            "패턴": 행동.get("이름"),
            "타격": 타격들,
            "총피해": sum(t["피해"] for t in 타격들),
            "비고": "소환수 행동",
        },
    )


def _몬스터_소환수_행동_실행(전투상태, 몬스터참가자):
    for 소환수이름, 횟수 in _몬스터_소환수_목록(몬스터참가자):
        정의 = summon_00.소환수목록.get(소환수이름)
        행동표 = (정의 or {}).get("행동표")
        if not 행동표:
            core._로그(
                전투상태,
                {
                    "공격자": 몬스터참가자["이름"],
                    "비고": f"소환수 '{소환수이름}' 행동표 없음 - 스킵",
                },
            )
            continue
        for _ in range(횟수):
            행동 = 행동표.get(dice_utils.주사위_합(1, 6))
            if not isinstance(행동, dict) or 행동.get("타입") != "공격":
                continue
            _소환수_공격_실행(
                전투상태, 몬스터참가자, 행동, f"{몬스터참가자['이름']}의 {소환수이름}"
            )
