# 새 캐릭터를 만드는 처리를 담당한다. character_data_system.py의
# 빈_캐릭터()로 기본 틀을 만들고, 여기에 이름/직업/능력치를 채우고
# 레벨 1 시작 특성을 부여해서 실제로 쓸 수 있는 레벨 1 캐릭터를
# 완성한다.
#
# 이 파일은 "직업 이름 → 어느 job_level_XX.py 파일"인지, "무기 이름 →
# 어느 eq_weapon_XX.py 무기 데이터"인지를 스스로 찾아가지 않는다. 그
# 연결은 아직 정해지지 않아서(직업/장비 데이터를 찾아주는 레지스트리
# 같은 게 필요해 보임), 여기서는 호출하는 쪽이 job_level_XX.py의
# "레벨업테이블"에서 레벨 1 항목을, eq_weapon_XX.py에서 시작 무기의
# 데이터를 직접 찾아 넘겨준다고 가정한다.

from game.system import character_data_system as 캐릭터데이터
from game.system import effect_engine

# =====================================================
# 직업별 주스탯/보조스탯/약점스탯
# =====================================================
# 능력치 배분은 더 이상 플레이어가 6개 능력치 중 아무거나 골라서
# 정하지 않는다. 직업을 고르면 아래 표에 따라 세 능력치(주스탯/
# 보조스탯/약점스탯)가 자동으로 정해지고, 나머지 세 능력치는 기본값
# 10이 된다.
#
# 각 직업의 "주스탯"은 그 직업 레벨 1 특성(job_ability_00.py 계열의
# "귀수"/"단련된 육체"/"군인"/"마법재능"/"성직자")이 이미 +1 시켜주는
# 능력치와 정확히 일치한다.
직업별_주보조약점스탯 = {
    "귀검사": {"주스탯": "근력", "보조스탯": "민첩", "약점스탯": "지능"},
    "격투가": {"주스탯": "건강", "보조스탯": "근력", "약점스탯": "지혜"},
    "거너": {"주스탯": "민첩", "보조스탯": "지능", "약점스탯": "근력"},
    "마법사": {"주스탯": "지능", "보조스탯": "지혜", "약점스탯": "건강"},
    "프리스트": {"주스탯": "지혜", "보조스탯": "건강", "약점스탯": "민첩"},
}

주스탯_점수 = 13
보조스탯_점수 = 12
약점스탯_점수 = 8
기본스탯_점수 = 10


def 초기능력치_생성(직업):
    """직업별_주보조약점스탯을 참고해서 능력치(근력~매력) 초기값을
    만든다. 주스탯 13점, 보조스탯 12점, 약점스탯 8점, 나머지 세
    능력치는 10점이다.

    반환값은 (능력치딕셔너리, 주스탯이름, 보조스탯이름, 약점스탯이름)
    튜플이다."""
    스탯구성 = 직업별_주보조약점스탯[직업]
    주스탯 = 스탯구성["주스탯"]
    보조스탯 = 스탯구성["보조스탯"]
    약점스탯 = 스탯구성["약점스탯"]

    능력치 = {
        스탯이름: 기본스탯_점수
        for 스탯이름 in ["근력", "민첩", "건강", "지능", "지혜", "매력"]
    }
    능력치[주스탯] = 주스탯_점수
    능력치[보조스탯] = 보조스탯_점수
    능력치[약점스탯] = 약점스탯_점수

    return 능력치, 주스탯, 보조스탯, 약점스탯


def 캐릭터_생성(
    캐릭터명,
    직업,
    레벨1_레벨업항목,
    레벨1_특성정의모음,
    시작무기데이터,
    주문시전능력치=None,
):
    """새 레벨 1 캐릭터를 만든다.

    캐릭터명, 직업     : 문자열. 직업은 직업별_주보조약점스탯에 등록된
                          이름이어야 한다 (예: "귀검사").
    레벨1_레벨업항목   : 해당 직업 job_level_XX.py의 "레벨업테이블"에서
                          키 1(레벨 1)에 해당하는 항목. "타입":"특성획득"
                          형식이어야 한다 (job_level_format.py 참고).
    레벨1_특성정의모음 : {특성이름: 특성정의, ...} 형태의 딕셔너리.
                          레벨1_레벨업항목의 "획득"."획득특성"에 있는
                          특성 이름들을, 그 특성이 정의된 job_ability_XX.py
                          "특성목록"에서 찾은 실제 정의와 매칭해서 넘긴다.
                          이 정의의 "효과"를 읽어서 능력치 등을 즉시
                          반영하는 데 쓴다.
    시작무기데이터     : 레벨1_레벨업항목["시작장비"] 이름에 해당하는
                          eq_weapon_XX.py 무기 데이터 딕셔너리
                          (예: 귀검사무기목록["녹슨 소검"]).
    주문시전능력치     : 주문을 쓰는 직업만 지정. 예) "지능"

    능력치(근력~매력)과 "주스탯"/"보조스탯"/"약점스탯"은 더 이상
    인자로 받지 않는다. 직업이 정해지면 초기능력치_생성()이 자동으로
    계산해서 채운다.
    """
    캐릭터 = 캐릭터데이터.빈_캐릭터()

    캐릭터["캐릭터명"] = 캐릭터명
    캐릭터["직업"] = 직업
    캐릭터["주문시전능력치"] = 주문시전능력치

    능력치, 주스탯, 보조스탯, 약점스탯 = 초기능력치_생성(직업)
    for 스탯이름 in ["근력", "민첩", "건강", "지능", "지혜", "매력"]:
        캐릭터[스탯이름] = 능력치[스탯이름]
    캐릭터["주스탯"] = 주스탯
    캐릭터["보조스탯"] = 보조스탯
    캐릭터["약점스탯"] = 약점스탯

    _레벨1_특성_부여(캐릭터, 레벨1_레벨업항목, 레벨1_특성정의모음)
    _초기_자원_설정(캐릭터, 레벨1_레벨업항목)
    _시작_장비_설정(캐릭터, 레벨1_레벨업항목)
    _평타스탯_설정(캐릭터, 시작무기데이터)

    return 캐릭터


def _레벨1_특성_부여(캐릭터, 레벨1_레벨업항목, 특성정의모음):
    """job_level_format.py의 <획득 하위 양식> 1) "특성" 형식을 그대로
    처리한다. "획득특성"은 특성 이름 하나거나 이름 리스트일 수 있다.
    character_levelup_system.py의 레벨업 처리와 같은 방식이다."""
    획득 = 레벨1_레벨업항목["획득"]
    특성이름들 = 획득["획득특성"]
    if isinstance(특성이름들, str):
        특성이름들 = [특성이름들]

    for 특성이름 in 특성이름들:
        effect_engine.특성_부여(캐릭터, 특성이름, 특성정의모음[특성이름])


def _초기_자원_설정(캐릭터, 레벨1_레벨업항목):
    """MP는 프로젝트 공식(최대 50 + 10×주문시전보정치)대로 계산해서
    채운다. HP는 D&D 5판 방식으로 계산한다: 레벨 1은 "기본체력"(히트다이스
    최대치) + 건강보정치, 레벨 2부터는 레벨업마다 "레벨당체력증가"(히트
    다이스 평균치 고정) + 건강보정치가 더해진다 (job_level_format.py
    참고). 이 함수는 레벨 1 생성 시점만 다루므로 레벨-1 항목은 0이 된다."""
    if 캐릭터["주문시전능력치"] is not None:
        주문시전보정치 = 캐릭터데이터.능력치_보정치(캐릭터, 캐릭터["주문시전능력치"])
    else:
        주문시전보정치 = 0

    캐릭터["기본최대MP"] = 50 + 10 * 주문시전보정치
    캐릭터["현재MP"] = 캐릭터["기본최대MP"]

    캐릭터["기본최대HP"] = 캐릭터데이터.기본최대HP_계산(
        캐릭터, 레벨1_레벨업항목["기본체력"], 레벨1_레벨업항목["레벨당체력증가"]
    )
    캐릭터["현재HP"] = 캐릭터["기본최대HP"]


def _시작_장비_설정(캐릭터, 레벨1_레벨업항목):
    """job_level_XX.py 레벨 1 항목의 "기본가용무기"/"시작장비"/"시작상의"를
    그대로 반영한다. "가용무기"는 비전직부터 쓸 수 있는 무기 종류 목록이고,
    "시작장비"는 처음부터 장착하고 시작하는 무기 이름, "시작상의"는
    처음부터 장착하고 시작하는 상의 이름이다 (job_level_format.py 참고)."""
    캐릭터["가용무기"] = list(레벨1_레벨업항목["기본가용무기"])
    캐릭터["장착장비"]["무기"] = 레벨1_레벨업항목["시작장비"]
    캐릭터["장착장비"]["상의"] = 레벨1_레벨업항목["시작상의"]


def _평타스탯_설정(캐릭터, 시작무기데이터):
    """character_format.py 기준 "평타스탯" = 기본 근력 + 무기의
    "무기능력치" + 특성으로 추가된 후보. 특성으로 추가되는 부분은
    해당 특성을 얻을 때(퍽/레벨업 처리 쪽에서) 이 리스트에 추가해주면
    된다. 여기서는 생성 시점 기준으로 근력과 장착한 시작 무기의
    "무기능력치"만 합친다."""
    후보 = ["근력"]
    for 스탯이름 in 시작무기데이터["무기능력치"]:
        if 스탯이름 not in 후보:
            후보.append(스탯이름)

    캐릭터["평타스탯"] = 후보
