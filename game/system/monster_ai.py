# 몬스터가 "이번 턴에 무엇을 할지"와 "누구를 때릴지"만 결정한다.
# 실제로 명중을 굴리고 피해를 적용하는 처리는 combat 패키지가 하며,
# combat 패키지가 이 파일의 결정 함수를 불러 쓰는 방향으로만 의존한다
# (이 파일은 combat 패키지를 불러오지 않는다 - 순환 참조 방지).

import random

from game.system import dice_utils


def 행동_선택(몬스터참가자):
    """몬스터가 이번 자기 턴에 쓸 "패턴"(monster_race_*.py "패턴" 항목)
    하나를 고른다.

    패턴은 순차 실행이 아니라, 패턴 개수만큼의 주사위(패턴이 6개면
    1d6)를 굴려서 나온 번호의 패턴을 그대로 쓴다. 턴 수와는 무관하다.

    "조건부행동" 타입 패턴(예: 겁쟁이 고블린의 "광포" 스택 조건)은
    몬스터참가자의 "버프스택"을 확인해서 조건 충족 시/미충족 시 중
    하나를 반환한다."""
    패턴목록 = 몬스터참가자["원본"].get("패턴")
    if not 패턴목록:
        return None

    패턴키들 = sorted(패턴목록.keys())
    순번 = dice_utils.주사위_합(1, len(패턴키들)) - 1
    패턴 = 패턴목록[패턴키들[순번]]

    if 패턴.get("이름") == "조건부행동":
        조건 = 패턴.get("조건", {})
        필요버프 = 조건.get("버프")
        필요스택 = 조건.get("필요스택", 1)
        보유스택 = 몬스터참가자.get("버프스택", {}).get(필요버프, 0)

        if 보유스택 >= 필요스택:
            조건충족시 = 패턴.get("조건충족시")
            if isinstance(조건충족시, dict):
                # 데이터에 실제 패턴 딕셔너리가 그대로 들어있으면 그걸 쓴다
                # (겁쟁이 고블린 패턴 2~5는 이렇게 정리했다).
                return 조건충족시
            # "조건충족시"가 아직 "몽둥이질 (패턴1과 동일)"처럼 설명
            # 문자열인 구버전 데이터(예: 겁쟁이 고블린 패턴 6)는 하위 호환으로
            # 기존처럼 패턴 1번을 대신 쓴다 (TODO: 그 데이터도 dict 참조로
            # 바꾸면 이 대비책은 필요 없어진다).
            return 패턴목록.get(패턴키들[0])

        return 패턴.get("조건미충족시")

    return 패턴


def 타겟_선택(생존아군참가자목록, 상태이상정의=None):
    """어그로 비중에 비례한 확률로 아군 1체를 무작위로 고른다
    (job_ability_format.py "어그로" 변동대상 설명 참고 - 아군 기본
    어그로 10, 적은 파티 전체 어그로 합계 중 자신의 비중만큼 확률로
    공격 대상을 정한다). "천갑숙련"/"판금숙련" 같은 특성의 어그로
    배율(캐릭터 "어그로배율", 기본값 1.0)도 가중치에 곱해서 반영한다.

    "상태이상정의"(status_effects.py "상태이상목록")를 넘겨주면, "이목집중"
    (표적고정) 상태인 아군이 있는지 먼저 확인해서 있으면 어그로 계산을
    건너뛰고 그 아군을 최우선으로 공격한다. combat 패키지를 이 파일이
    직접 부르지 않기 위해(순환 참조 방지) 판정에 필요한 정의 테이블만
    인자로 받는다 - 넘기지 않으면(하위 호환) 표적고정 판정을 하지 않는다."""
    if not 생존아군참가자목록:
        return None

    if 상태이상정의:
        표적고정후보 = [
            p
            for p in 생존아군참가자목록
            if any(
                상태이상정의.get(항목["이름"], {}).get("효과", {}).get("표적고정")
                for 항목 in p.get("상태이상", [])
            )
        ]
        if 표적고정후보:
            return random.choice(표적고정후보)

    가중치들 = [
        max(0, p["원본"].get("어그로", 10) * p["원본"].get("어그로배율", 1.0))
        for p in 생존아군참가자목록
    ]
    if sum(가중치들) == 0:
        return random.choice(생존아군참가자목록)
    return random.choices(생존아군참가자목록, weights=가중치들, k=1)[0]
