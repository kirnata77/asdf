# =====================
# 스킬 습득 시스템
# =====================
# 파티 화면 [스킬습득]으로 골드를 내고 스킬을 배운다. 레벨업으로는 스킬을
# 배우지 않는다(습득레벨 1 스킬만 캐릭터를 만들 때 자동으로 배운다 -
# character_creation_system.py).
#
# 배울 수 있는 스킬은 지금 직업 계열의 job_skill_XX.py "스킬목록" 중
# "습득방법"이 "레벨습득"이고 아직 없는 스킬이다. 1차 계열(예: 귀검사)은
# 차수 1, 1차 전직(예: 웨펀마스터)은 차수 2 - 전직한 캐릭터는 두 목록을
# 다 배울 수 있다. 비용은 50 x 차수 골드. 캐릭터 레벨 제한은 없다.
#
# 직업 이름 → 스킬목록 연결은 호출하는 쪽(gameflow)이 찾아 넘긴다.

스킬습득_골드단위 = 50


def 스킬습득_비용(차수):
    return 스킬습득_골드단위 * 차수


def 습득가능_스킬목록(캐릭터, 차수별스킬목록):
    """[(스킬이름, 차수, 비용, 스킬데이터)] - 데이터 순서(차수 낮은 것부터).

    차수별스킬목록 : [(차수, {스킬이름: 스킬데이터}), ...]"""
    결과 = []
    for 차수, 스킬목록 in 차수별스킬목록:
        for 이름, 스킬 in 스킬목록.items():
            if 스킬.get("습득방법") != "레벨습득" or 이름 in 캐릭터["보유스킬"]:
                continue
            결과.append((이름, 차수, 스킬습득_비용(차수), 스킬))
    return 결과


def 스킬_습득(캐릭터, 소지품, 스킬이름, 차수별스킬목록):
    """골드를 내고 스킬을 배운다. 낸 골드를 반환한다. 배울 수 없는 스킬이거나
    골드가 모자라면 ValueError(캐릭터/소지품은 바뀌지 않는다)."""
    for 이름, _차수, 비용, _스킬 in 습득가능_스킬목록(캐릭터, 차수별스킬목록):
        if 이름 == 스킬이름:
            break
    else:
        raise ValueError(f"'{스킬이름}'은(는) 지금 배울 수 있는 스킬이 아니다.")
    if 소지품.get("골드", 0) < 비용:
        raise ValueError(f"골드가 모자란다({비용}골드 필요).")
    소지품["골드"] -= 비용
    캐릭터["보유스킬"].append(스킬이름)
    return 비용
