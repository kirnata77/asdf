# 여러 화면(ui_battle.py, ui_town.py 등)이 똑같이 그려야 하는 작은
# tkinter 부품들을 모아둔다. town_formet.py 주석에서 말하는 "화면 하단의
# 파티 상태 표시는 전투 화면과 공유하는 UI"가 이 파일의 역할이다.
#
# 지금까지는 이 파일이 빈 껍데기("test")였던 탓에 ui_battle.py와
# ui_town.py가 HP/MP 막대 그리기 코드를 각자 파일에 그대로 중복
# 작성해뒀었다 - 이번에 이 파일을 채우면서 그 중복을 걷어내고 양쪽 다
# 이 파일의 함수를 불러 쓰도록 정리했다.
#
# 화면 전체(파티원 행 레이아웃, 상태이상/행동자원 표시 등)까지 공용화한
# 것은 아니다 - ui_battle.py는 combat_system.py "참가자" 딕셔너리를,
# ui_town.py는 character_data_system.py 캐릭터 딕셔너리를 직접 다뤄서
# 두 화면이 보여주는 정보의 폭 자체가 달라(행동자원/상태이상은 전투
# 중에만 의미가 있다), 지금은 정말로 똑같이 반복되던 부분(막대 그리기,
# HP 색 판정)만 공용화했다.
#
# 공통조작키_바인딩()은 이번에 새로 추가했다 - Z(확인)/X(취소)/ESC를
# 화면마다 각자 구현하지 않고 한 군데서 규칙을 정한다(사용자 확정 규칙:
# Z=확인/상호작용, X=취소, ESC=취소할 게 있으면 취소 아니면 화면별 대체
# 동작).

import tkinter as tk


def HP_색(비율):
    """체력 비율(0.0~1.0)에 따라 초록/노랑/빨강 중 하나를 고른다.
    ui_battle.py가 쓰던 기준을 그대로 옮겼다."""
    if 비율 > 0.5:
        return "#4caf50"
    if 비율 > 0.25:
        return "#ffc107"
    return "#e53935"


def 막대_그리기(캔버스, 현재값, 최대값, 색):
    """캔버스 전체를 배경색(#333333)으로 채운 뒤, 현재값/최대값 비율만큼
    지정한 색으로 왼쪽부터 채운다. 캔버스의 width/height 속성을 그대로
    읽어서 쓰므로, 호출 전에 캔버스 크기(생성 시 width=.., height=..)를
    정해둬야 한다. 최대값이 0 이하면 그냥 빈 막대로 그린다."""
    캔버스.delete("all")
    폭 = int(캔버스["width"])
    높이 = int(캔버스["height"])
    캔버스.create_rectangle(0, 0, 폭, 높이, fill="#333333", outline="")
    비율 = 0 if 최대값 <= 0 else max(0.0, min(1.0, 현재값 / 최대값))
    if 비율 > 0:
        캔버스.create_rectangle(0, 0, 폭 * 비율, 높이, fill=색, outline="")


def HP막대_그리기(캔버스, 현재값, 최대값):
    """HP 막대는 색이 항상 비율에 따라 자동으로 정해지는 경우가
    대부분이라(HP_색), 그 둘을 묶은 편의 함수. MP처럼 색이 고정인
    막대는 막대_그리기()를 색을 직접 지정해서 쓰면 된다."""
    비율 = 0 if 최대값 <= 0 else max(0.0, min(1.0, 현재값 / 최대값))
    막대_그리기(캔버스, 현재값, 최대값, HP_색(비율))


def 공통조작키_바인딩(화면, 확인콜백=None, 취소콜백=None, esc콜백=None):
    """여러 화면이 똑같이 따르는 Z(확인)/X(취소)/ESC 키 규칙을 한 군데에
    모아둔 것 - 사용자 확정 조작 규칙: Z=확인/상호작용, X=취소,
    ESC=취소할 게 있으면 취소(취소콜백과 동일), 없으면 화면별 대체 동작
    (예: 마을/던전의 설정메뉴).

    화면(이 함수를 부른 tk.Frame/Toplevel) 자신이 아니라
    화면.winfo_toplevel()에 건다 - 인스턴스 단위 bind는 그 위젯이 직접
    키보드 포커스를 들고 있을 때만 동작하는데, 방향 버튼 등 아무 버튼이나
    한 번 클릭하면 포커스가 그 버튼으로 넘어가 버려서(예: ui_dungeon.py
    방향키가 방향 버튼을 누른 뒤로 안 먹던 문제 - 이번에 같이 고쳤다),
    최상위 창 단위로 걸어 어떤 자식 위젯이 포커스를 들고 있어도 항상
    동작하게 했다. 그 대신 화면이 바뀔 때마다(새 화면의 __init__에서)
    다시 호출해야 한다 - 같은 창에 새로 건 바인딩이 이전 화면 것을
    덮어쓰므로, 화면 전환 뼈대(main_system.py)가 화면을 한 번에 하나씩만
    띄우는 한(또는 Toplevel 팝업처럼 별도 창인 한) 문제없다.

    확인콜백 : Z를 누르면 부른다. 생략하면, 그 순간 포커스된 위젯이
               invoke()를 지원하면(Button/Radiobutton 등 - Tab으로
               옮겨 다닌다고 가정) 그걸 대신 눌러준다.
    취소콜백 : X를 누르면 부른다. 생략하면 X는 아무 일도 하지 않는다.
    esc콜백  : ESC를 누르면, 취소콜백이 있으면 그것부터 부르고(X와
               동일), 없으면 이걸 부른다. 취소콜백도 esc콜백도 없으면
               ESC는 아무 일도 하지 않는다.
    """
    최상위 = 화면.winfo_toplevel()

    def _확인(event=None):
        if 확인콜백 is not None:
            확인콜백()
            return
        위젯 = 화면.focus_get()
        if 위젯 is not None and hasattr(위젯, "invoke"):
            위젯.invoke()

    def _취소(event=None):
        if 취소콜백 is not None:
            취소콜백()

    def _esc(event=None):
        if 취소콜백 is not None:
            취소콜백()
        elif esc콜백 is not None:
            esc콜백()

    최상위.bind("<KeyPress-z>", _확인)
    최상위.bind("<KeyPress-Z>", _확인)
    최상위.bind("<KeyPress-x>", _취소)
    최상위.bind("<KeyPress-X>", _취소)
    최상위.bind("<Escape>", _esc)