def _조건_확인(전투상태, 시전자, 대상, 조건, 조건값):
    if 조건 == "자원보유":
        return resources.자원_보유량(전투상태, 시전자, 조건값) > 0
    if 조건 == "적상태":
        if 대상 is None:
            return False
        return any(항목["이름"] == 조건값 for 항목 in 대상.get("상태이상", []))
    if 조건 == "아군상태":
        return any(
            항목["이름"] == 조건값
            for 항목 in (시전자.get("상태이상", []) + 시전자.get("버프", []))
        )
    if 조건 == "HP비율이하":
        최대HP = stats.유효_최대HP(전투상태, 시전자)
        if 최대HP <= 0:
            return False
        return (시전자["현재HP"] / 최대HP) <= 조건값
    if 조건 == "특성보유":
        원본 = 시전자["원본"]
        return 조건값 in 원본.get("보유특성", [])
    return False


def 조건부효과_평가(전투상태, 시전자, 대상, 조건부효과리스트):
    """조건부효과 리스트를 순서대로 전부 검사해서 만족하는 항목을 누적
    적용한 오버라이드 딕셔너리를 만든다. "데미지보너스"/"명중보너스"는
    여러 항목이 만족해도 전부 더하고, "타겟"/"타겟제한"/"일반공격취급"/
    "MP소모"처럼 하나의 값만 가질 수 있는 항목은 나중에 만족한 조건이
    앞선 것을 덮어쓴다(리스트 순서 그대로). "자원소모"는 만족한 조건들의
    소모 목록을 전부 모은다.

    "대상"이 None이면(스킬 사용 시작 시 전역 오버라이드를 구할 때)
    "적상태" 조건은 항상 불만족으로 처리한다 - 대상별로 달라지는 조건이라
    특정 대상 없이는 판정할 수 없기 때문이다."""
    오버라이드 = {
        "데미지보너스": 0,
        "명중보너스": 0,
        "자원소모추가": [],
        "버프해제": [],
        "디버프해제": [],
        "상태이상해제": [],
    }
    for 항목 in 조건부효과리스트 or []:
        if not _조건_확인(전투상태, 시전자, 대상, 항목.get("조건"), 항목.get("조건값")):
            continue

        if "자원소모" in 항목:
            # <조건부효과 하위 양식>의 "자원소모"는 (스킬 최상위 키의
            # {"이름": 개수} 딕셔너리와 달리) 그냥 자원 이름 문자열이고,
            # 항상 1개 소모하는 것으로 취급한다 (job_skill_11_weapon_master.py
            # "류심 : 충" 등 실제 데이터 참고).
            오버라이드["자원소모추가"].append(항목["자원소모"])
        if "데미지보너스" in 항목:
            컨텍스트 = stats.기본_컨텍스트(
                전투상태,
                시전자,
                무기공격력필요=(
                    "보정공격력" in str(항목["데미지보너스"])
                    or "무기공격력" in str(항목["데미지보너스"])
                ),
            )
            오버라이드["데미지보너스"] += formula.수식_평가(
                항목["데미지보너스"], 컨텍스트
            )
        if "명중보너스" in 항목:
            오버라이드["명중보너스"] += _정수_평가(
                항목["명중보너스"], 전투상태, 시전자, 0
            )
        if "타겟" in 항목:
            오버라이드["타겟"] = 항목["타겟"]
        if "타겟제한" in 항목:
            오버라이드["타겟제한"] = 항목["타겟제한"]
        if "일반공격취급" in 항목:
            오버라이드["일반공격취급"] = 항목["일반공격취급"]
        if "MP소모" in 항목:
            오버라이드["MP소모"] = 항목["MP소모"]
        if "버프해제" in 항목:
            오버라이드["버프해제"].append(항목["버프해제"])
        if "디버프해제" in 항목:
            오버라이드["디버프해제"].append(항목["디버프해제"])
        if "상태이상해제" in 항목:
            오버라이드["상태이상해제"].append(항목["상태이상해제"])

    return 오버라이드


# =====================================================
# 효과(<효과 하위 양식>) 적용
# =====================================================


def 효과_적용(
    전투상태,
    시전자,
    대상,
    효과리스트,
    주대상피해=0,
    속성=None,
    데미지식=None,
    데미지보너스=0,
    명중률종류=None,
    명중보너스=0,
):
    """공격/해제 스킬의 "효과" 리스트를 대상 하나에 적용한다. 명중 후
    상황(상태이상/자동상태/지속피해 부여, 아군버프, 버프해제/디버프해제,
    범위분배)을 다룬다.

    "주대상피해"는 이 효과가 곁들여진 공격이 "대상"에게 실제로 입힌
    피해량이다("범위분배"의 "주대상피해" 수식 키워드에 쓴다 - 공격_1회가
    이미 계산해둔 결과["피해"]를 그대로 넘겨준다). "속성"도 마찬가지로
    범위분배 피해에 그대로 반영해 저항/취약이 적용되게 한다.

    "데미지식"/"데미지보너스"/"명중률종류"/"명중보너스"는 "지속피해"
    종류에만 쓰인다 - job_skill_format.py에 "턴당 피해량은 스킬 자신의
    '데미지' 키 값을 그대로 사용한다"고 돼 있어서, 이 효과가 곁들여진
    스킬(공격_1회) 쪽의 값을 그대로 받아 항목에 저장해둔다(대상 본인
    턴종료시 combat.damage._지속피해_스킬_적용이 나중에 이 값으로
    재계산한다).

    "상태이상" 종류의 내성굴림은 대상이 "저주"(내성굴림불리점) 상태면
    불리하게 굴린다. 실제 상태이상 부여는 _상태이상_부여()에 맡긴다 -
    status_effects.py에 정의된 이름(기절/공중에뜸 등)이면 그 정의를 보고
    지속피해형 중첩 병합/부여버프까지 같이 처리해 준다."""
    로그 = []
    for 항목 in 효과리스트 or []:
        종류 = 항목.get("종류")

        if 종류 in ("상태이상", "자동상태") and status.상태이상_면역(
            전투상태, 대상, 항목.get("이름")
        ):
            로그.append(f"{대상['이름']}은(는) '{항목['이름']}' 상태이상에 면역")
            continue

        if 종류 == "상태이상":
            난이도 = 항목.get("난이도", 10)
            if isinstance(난이도, str):
                난이도 = formula.수식_평가(
                    난이도, stats.기본_컨텍스트(전투상태, 시전자)
                )
            내성보정치 = stats.유효_능력치_보정치(전투상태, 대상, 항목["내성"])
            불리 = status.상태이상_플래그(전투상태, 대상, "내성굴림불리점")
            이점 = traits.상태이상_내성이점(전투상태, 대상, 항목["이름"])
            if not dice_utils.내성_성공(내성보정치, 난이도, 이점=이점, 불리=불리):
                _상태이상_부여(
                    전투상태,
                    대상,
                    항목["이름"],
                    _정수_평가(항목.get("지속턴", 1), 전투상태, 대상),
                    해제난이도=항목.get("해제난이도"),
                )
                로그.append(f"{대상['이름']}에게 '{항목['이름']}' 부여 (내성 실패)")
            else:
                로그.append(
                    f"{대상['이름']}이(가) 내성에 성공해 '{항목['이름']}'을(를) 피함"
                )

        elif 종류 == "자동상태":
            _상태이상_부여(
                전투상태,
                대상,
                항목["이름"],
                _정수_평가(항목.get("지속턴", 1), 전투상태, 대상),
                해제난이도=항목.get("해제난이도"),
            )
            로그.append(f"{대상['이름']}에게 '{항목['이름']}' 자동 부여")

        elif 종류 == "지속피해":
            # 이 "지속피해"는 status_effects.py 4분류(지속피해형)와는 다른,
            # 스킬이 직접 정의하는 커스텀 지속피해다. "상태이상" 종류와 같은
            # 방식으로 최초 적용될 때만 "내성"/"난이도"로 내성굴림을 하고
            # (지속공격과 달리 매 턴 재판정하지 않는다),
            # 실패해야만 걸린다. 한 번 걸리면 지속턴이 다 될 때까지(또는
            # 디버프해제로 없어질 때까지) 매 턴 그대로 피해를 입는다 - 대상
            # 본인 턴종료시 combat.damage._지속피해_스킬_적용이 "출처"에
            # 저장된 값으로 실제 발동시킨다(combat 패키지 모듈 docstring
            # 참고).
            난이도 = 항목.get("난이도", 10)
            if isinstance(난이도, str):
                난이도 = formula.수식_평가(
                    난이도, stats.기본_컨텍스트(전투상태, 시전자)
                )
            내성보정치 = stats.유효_능력치_보정치(전투상태, 대상, 항목["내성"])
            불리 = status.상태이상_플래그(전투상태, 대상, "내성굴림불리점")
            if dice_utils.내성_성공(내성보정치, 난이도, 불리=불리):
                로그.append(
                    f"{대상['이름']}이(가) 내성에 성공해 지속피해 '{항목['이름']}'을(를) 피함"
                )
            else:
                대상.setdefault("상태이상", []).append(
                    {
                        "이름": 항목["이름"],
                        "종류": "지속피해",
                        "지속턴": _정수_평가(항목.get("지속턴", 1), 전투상태, 대상),
                        "출처": {
                            "데미지": 데미지식,
                            "데미지보너스": 데미지보너스,
                            "속성": 속성,
                            "시전자이름": 시전자["이름"],
                            "시전자id": 시전자.get("id"),
                        },
                    }
                )
                로그.append(
                    f"{대상['이름']}에게 지속피해 '{항목['이름']}' 등록 (내성 실패)"
                )

        elif 종류 == "아군버프":
            대상들 = 타겟_확장(전투상태, 시전자, 항목.get("타겟", "아군전체"))
            for 아군 in 대상들:
                이름있는효과_부여(
                    전투상태,
                    아군,
                    항목["이름"],
                    지속턴오버라이드=_정수_평가(항목.get("지속턴", 1), 전투상태, 아군),
                    시전자=시전자,
                )
            로그.append(f"'{항목['이름']}' 버프를 {항목.get('타겟')}에 부여")

        elif 종류 in ("버프해제", "디버프해제"):
            목록이름 = "버프" if 종류 == "버프해제" else "디버프"
            if 항목.get("대상") == "지정":
                이름있는효과_해제(대상, 목록이름, 항목["이름"])
            else:
                해제개수 = _정수_평가(항목.get("해제개수", 1), 전투상태, 대상)
                후보 = [
                    i
                    for i in 대상[목록이름]
                    if not _자원류_효과인가(resources.효과정의_조회(i["이름"])[0])
                ]
                random.shuffle(후보)
                for i in 후보[:해제개수]:
                    대상[목록이름].remove(i)
            로그.append(f"{대상['이름']}의 {종류} 처리")

        elif 종류 == "범위분배":
            대상지정 = 항목.get("대상")
            if 대상지정 == "양옆1체씩":
                # 같은 편 전체(생존 여부 무관)를 "대형위치" 순으로 나열해
                # 바로 옆 칸만 본다 - 중간에 죽은 참가자가 있어도 대열이
                # 당겨지지 않는다. 그 옆 칸이 죽은 참가자면
                # 그냥 아무도 피해를 받지 않는다.
                같은편전체 = sorted(
                    (p for p in 전투상태["참가자"] if p["진영"] == 대상["진영"]),
                    key=lambda p: p.get("대형위치", 0),
                )
                이웃들 = []
                if 대상 in 같은편전체:
                    idx = 같은편전체.index(대상)
                    if idx > 0 and 같은편전체[idx - 1]["생존"]:
                        이웃들.append(같은편전체[idx - 1])
                    if idx < len(같은편전체) - 1 and 같은편전체[idx + 1]["생존"]:
                        이웃들.append(같은편전체[idx + 1])

                피해량식 = 항목.get("피해량", 0)
                if isinstance(피해량식, str):
                    식 = 피해량식.replace("주대상피해", str(주대상피해))
                    분배피해 = formula.수식_평가(식, {"차수": core.차수(시전자)})
                elif isinstance(피해량식, (int, float)):
                    분배피해 = 피해량식 * 주대상피해
                else:
                    분배피해 = 0

                for 이웃 in 이웃들:
                    최종피해 = damage.피해_적용(
                        전투상태, 이웃, 분배피해, 속성=속성, 공격측=시전자
                    )
                    로그.append(f"{이웃['이름']}에게 범위분배 피해 {최종피해}")
            else:
                로그.append(
                    f"'범위분배' 대상 표기 '{대상지정}'은 아직 지원하지 않는다 (TODO)"
                )

    return 로그


# =====================================================
# 명중 판정 (강제치명타/치명타체크 반영)
# =====================================================


def 스킬_명중_판정(
    전투상태, 시전자, 대상, 명중률종류, 명중보너스=0, 강제치명타=False, 치명타체크=False
):
    if 명중률종류 == "자동" and 치명타체크:
        눈 = dice_utils.d20_굴림()
        치명타범위 = damage.유효_치명타범위(전투상태, 시전자)
        return {
            "성공": True,
            "자연눈": 눈,
            "치명타": 눈 >= 치명타범위,
            "자동실패": False,
        }

    판정 = damage.명중_판정(전투상태, 시전자, 대상, 명중률종류, 명중보너스)
    if 강제치명타 and 판정["성공"]:
        판정 = dict(판정)
        판정["치명타"] = True
    return 판정


# =====================================================
# 공격 1회 (일반 공격스킬/분할공격 단계/지속공격에 공용)
# =====================================================


def 공격_1회(
    전투상태,
    시전자,
    대상,
    데미지식,
    데미지보너스,
    명중률종류,
    명중보너스,
    강제치명타,
    치명타체크,
    효과리스트,
    조건부효과리스트,
    미리계산된판정=None,
    속성=None,
    추가피해목록=None,
    속성변환=None,
    속성추가피해=None,
    일반공격취급=False,
):
    """속성추가피해: 스킬 "속성추가피해"([{"데미지": 식, "속성": 속성}]) - 본 피해와
    따로 그 속성으로 계산해 더한다(귀참의 귀신 d8 = 암속성). 본 피해식에 무기 주사위가
    있으면 치명타 주사위는 본 피해(무기 주사위)에만 붙는다."""
    # 무기 주사위를 쓰는 피해는 무기 속성, 아니면 스킬 속성(stats.공격_속성)
    속성 = stats.공격_속성(시전자, 데미지식, 속성, 속성변환)
    조건부오버라이드 = 조건부효과_평가(전투상태, 시전자, 대상, 조건부효과리스트)
    for 이름 in 조건부오버라이드["자원소모추가"]:
        resources.자원_소모(전투상태, 시전자, 이름, 1)
    공격전상태 = reactions.상태이상_이름목록(대상)

    판정 = 미리계산된판정 or 스킬_명중_판정(
        전투상태,
        시전자,
        대상,
        명중률종류,
        명중보너스 + 조건부오버라이드["명중보너스"],
        강제치명타,
        치명타체크,
    )

    결과 = {
        "공격자": 시전자["이름"],
        "대상": 대상["이름"],
        "판정": 판정,
        "피해": 0,
        "효과로그": [],
    }
    if not 판정["성공"]:
        reactions.공격후_반응(전투상태, 시전자, 대상, 공격전상태)
        return 결과

    무기필요 = "보정공격력" in str(데미지식) or "무기공격력" in str(데미지식)
    컨텍스트 = stats.기본_컨텍스트(전투상태, 시전자, 무기공격력필요=무기필요)
    # combat.formula.수식_평가에 치명타 여부를 그대로 넘긴다 - 이전에는
    # 여기서 데미지식을 통째로 한 번 더 평가해 더하는 방식(보정치/차수까지
    # 2배가 되는 버그)을 썼는데, 이제 combat.attacks.일반공격_실행/
    # _몬스터_패턴_실행과 같은 방식(다이스만, 그것도 1개 추가)으로 통일했다.
    피해 = stats.피해_굴림(전투상태, 시전자, 데미지식, 컨텍스트, 치명타=판정["치명타"])
    if 일반공격취급:
        # 일반공격취급 스킬에만 붙는 특성 피해(무기의 극의 - 광검 1d6)
        피해 += stats.일반공격_추가피해(전투상태, 시전자, 컨텍스트)
    피해 += 데미지보너스 + 조건부오버라이드["데미지보너스"]
    피해 += stats.버프디버프_수치(전투상태, 시전자, "데미지보너스")
    # 캐릭터 특성(무기의 극의/패황색 등)과 몬스터 특성 -
    # 주문 전용/약점속성 조건은 명중률종류/대상/속성으로 판정한다.
    피해 += traits.특성_수치(
        전투상태, 시전자, "데미지보너스", 명중률종류=명중률종류, 대상=대상, 속성=속성
    )
    # 장비(전 부위+활성 세트) 데미지보너스 - 주문 포함 모든 공격 스킬.
    피해 += stats.장비_수치(시전자, "데미지보너스")
    if 속성추가피해:
        추가치명 = (
            stats.치명타_주사위수(전투상태, 시전자)
            if 판정["치명타"] and not 무기필요
            else 0
        )
        추가피해목록 = list(추가피해목록 or []) + [
            (
                formula.수식_평가(항목["데미지"], 컨텍스트, 치명타=추가치명),
                항목.get("속성") or "무속성",
            )
            for 항목 in 속성추가피해
        ]

    결과["피해"] = damage.피해_적용(
        전투상태, 대상, 피해, 속성=속성, 추가피해목록=추가피해목록, 공격측=시전자
    )
    damage.피격_처리(전투상태, 시전자, 대상, 판정, 속성=속성)
    결과["효과로그"] = 효과_적용(
        전투상태,
        시전자,
        대상,
        효과리스트,
        주대상피해=결과["피해"],
        속성=속성,
        데미지식=데미지식,
        데미지보너스=데미지보너스,
        명중률종류=명중률종류,
        명중보너스=명중보너스,
    )

    for 디버프이름 in 조건부오버라이드["디버프해제"]:
        이름있는효과_해제(대상, "디버프", 디버프이름)
    for 버프이름 in 조건부오버라이드["버프해제"]:
        이름있는효과_해제(대상, "버프", 버프이름)
    for 상태이상이름 in 조건부오버라이드["상태이상해제"]:
        if 상태이상_해제(전투상태, 대상, 상태이상이름):
            결과["효과로그"].append(f"{대상['이름']}의 '{상태이상이름}' 상태이상 해제")

    # 반응특성(공중연속베기 등 "적상태" 추가 공격).
    reactions.공격후_반응(전투상태, 시전자, 대상, 공격전상태)
    return 결과


