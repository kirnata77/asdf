def 회복스킬_실행(전투상태, 시전자, 스킬데이터, 중심대상=None):
    대상목록 = 타겟_확장(전투상태, 시전자, 스킬데이터["타겟"], 중심대상)
    총회복 = 0
    for 대상 in 대상목록:
        양 = formula.수식_평가(
            스킬데이터["회복량"], stats.기본_컨텍스트(전투상태, 시전자)
        )
        최대HP = stats.유효_최대HP(전투상태, 대상)
        회복량 = max(0, min(양, 최대HP - 대상["현재HP"]))
        대상["현재HP"] += 회복량
        총회복 += 회복량

    결과 = {
        "공격자": 시전자["이름"],
        "스킬": 스킬데이터.get("_이름"),
        "대상": [p["이름"] for p in 대상목록],
        "총회복": 총회복,
    }
    core._로그(전투상태, 결과)
    return 결과


