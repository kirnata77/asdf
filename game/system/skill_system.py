def _행동종류목록(행동):
    if 행동 is None:
        return []
    if isinstance(행동, list):
        return 행동
    return [행동]


# "쇼타임행동"(buff.py "쇼타임행동증가", job_skill_40_mage.py "쇼타임" 버프스킬로
# 획득)이 있으면, 아래 타입이 붙은 스킬(job_skill_41_elemental_master.py의
# "중급마법"/"상급마법" 태그 등 실 데이터로 확인)의 "일반행동" 요구를
# 참가자["기타행동"]["쇼타임행동"]으로 대신 낼 수 있다 - 진짜 일반행동보다
# 우선 소모한다.
_쇼타임_적용_타입 = {"하급마법", "중급마법", "상급마법"}


def _쇼타임_대상스킬인가(스킬데이터):
    return bool(_쇼타임_적용_타입.intersection(스킬데이터.get("타입", [])))


def _일반행동_지불수단(전투상태, 참가자, 스킬데이터):
    """스킬의 "일반행동"을 무엇으로 낼지 - "쇼타임행동"(쇼타임 대상 마법) ->
    "일반행동" -> "보조행동"(특성 "보조행동대체타입", 메모라이즈의 하급마법) 순.
    낼 수단이 없으면 None."""
    if (
        _쇼타임_대상스킬인가(스킬데이터)
        and 참가자.get("기타행동", {}).get("쇼타임행동", 0) > 0
    ):
        return "쇼타임행동"
    if 참가자["행동자원"].get("일반행동", 0) > 0:
        return "일반행동"
    대체타입 = traits.캐릭터특성_보조행동대체타입(전투상태, 참가자)
    if (
        대체타입.intersection(스킬데이터.get("타입", []))
        and 참가자["행동자원"].get("보조행동", 0) > 0
    ):
        return "보조행동"
    return None


def 사용_가능여부(
    전투상태, 참가자, 스킬데이터, MP소모오버라이드=None, 자원소모오버라이드=None
):
    """행동자원/MP/자원소모/턴당사용제한/전투당횟수를 검사한다. "행동불가"
    (기절/공중에뜸/수면/빙결/석화)면 어떤 스킬도 쓸 수 없고, "혼란"의
    "행동제한"(일반공격만)이면 "일반공격취급"이 아닌 스킬은 쓸 수 없다.
    "하급마법"/"중급마법"/"상급마법" 타입 스킬은 "일반행동" 대신
    참가자["기타행동"]["쇼타임행동"]이 있으면 그걸로 대신 낼 수 있고,
    특성 "보조행동대체타입"(메모라이즈) 타입이면 일반행동이 없을 때 보조행동으로
    낼 수 있다(_일반행동_지불수단 참고).
    (가능여부, 사유) 튜플을 반환하며, 불가능할 때만 사유가 채워진다."""
    if status.상태이상_플래그(전투상태, 참가자, "행동불가"):
        return False, "행동불가 상태라 아무 것도 할 수 없다."

    행동제한 = status.상태이상_행동제한(전투상태, 참가자)
    if 행동제한 == "일반공격만" and not 스킬데이터.get("일반공격취급"):
        return False, "혼란 상태라 일반공격(취급 스킬)만 쓸 수 있다."

    행동들 = _행동종류목록(스킬데이터.get("행동"))
    if "전체소모" in 행동들:
        if all(
            참가자["행동자원"].get(k, 0) <= 0
            for k in ("일반행동", "보조행동", "반응행동")
        ):
            return False, "소모할 행동이 하나도 남아있지 않다."
    else:
        for 행동 in 행동들:
            if 행동 == "일반행동":
                if _일반행동_지불수단(전투상태, 참가자, 스킬데이터) is None:
                    return False, f"'{행동}'이(가) 남아있지 않다."
                continue
            if 참가자["행동자원"].get(행동, 0) <= 0:
                return False, f"'{행동}'이(가) 남아있지 않다."

    MP소모 = MP소모오버라이드
    if MP소모 is None:
        MP소모 = 스킬데이터.get("MP소모", 0)
    MP소모 *= stats.MP소모_배율(참가자)  # 중갑/판금 패널티
    # MP 칸이 없는 참가자(몬스터)는 보유 0으로 본다 - MP가 드는 스킬은 못 쓴다.
    if MP소모 and 참가자.get("현재MP", 0) < MP소모:
        return False, f"MP가 부족하다 (필요 {MP소모}, 보유 {참가자.get('현재MP', 0)})."

    자원소모 = (
        자원소모오버라이드
        if 자원소모오버라이드 is not None
        else 스킬데이터.get("자원소모")
    )
    if 자원소모:
        for 이름, 개수 in 자원소모.items():
            if resources.자원_보유량(전투상태, 참가자, 이름) < 개수:
                return False, f"'{이름}' 자원이 부족하다."

    스킬이름 = 스킬데이터.get("_이름", "이스킬")
    턴당제한 = 스킬데이터.get("턴당사용제한")
    if 턴당제한 is not None:
        이번턴 = 참가자.get("이번턴_스킬사용횟수", {}).get(스킬이름, 0)
        if 이번턴 >= _정수_평가(턴당제한, 전투상태, 참가자):
            return False, "이번 턴에 더 쓸 수 없다 (턴당사용제한)."

    전투당제한 = 스킬데이터.get("전투당횟수")
    if 전투당제한 is not None:
        이번전투 = 참가자.get("전투당_스킬사용횟수", {}).get(스킬이름, 0)
        if 이번전투 >= _정수_평가(전투당제한, 전투상태, 참가자):
            return False, "이번 전투에 더 쓸 수 없다 (전투당횟수)."
    # 휴식당횟수: 캐릭터["횟수제한스킬"]["휴식제한스킬"]에 남은
    # 횟수를 영구 저장한다(휴식_남은횟수 참고). 다 쓰면 휴식 전까지 못 쓴다.
    남은정보 = 휴식_남은횟수(전투상태, 참가자, 스킬데이터)
    if 남은정보 is not None and 남은정보[0] <= 0:
        return (
            False,
            f"휴식당 사용 횟수({남은정보[1]}회)를 모두 썼다. 휴식하면 회복된다.",
        )

    return True, None


def _휴식제한_칸(참가자):
    """캐릭터 원본의 "횟수제한스킬"["휴식제한스킬"] 딕셔너리(스킬이름 ->
    남은횟수). 필드가 없는 캐릭터(구버전 세이브)도 여기서 만들어 준다. 몬스터는 None."""
    if 참가자.get("진영") != "아군":
        return None
    원본 = 참가자["원본"]
    return 원본.setdefault("횟수제한스킬", {}).setdefault("휴식제한스킬", {})


def 휴식_남은횟수(전투상태, 참가자, 스킬데이터):
    """ "휴식당횟수"가 있는 스킬이면 (남은횟수, 최대횟수), 아니면 None.
    칸에 기록이 없으면 아직 안 쓴 것으로 보고 최대횟수를 남은횟수로 쓴다
    (character_data_system.py "횟수제한스킬" 설명). 최대횟수 수식("2+차수")은
    지금 차수로 평가한다."""
    제한 = 스킬데이터.get("휴식당횟수")
    칸 = _휴식제한_칸(참가자)
    if 제한 is None or 칸 is None:
        return None
    최대 = _정수_평가(제한, 전투상태, 참가자)
    스킬이름 = 스킬데이터.get("_이름", "이스킬")
    return min(칸.get(스킬이름, 최대), 최대), 최대


def 자원_소비_처리(
    전투상태, 참가자, 스킬데이터, MP소모오버라이드=None, 자원소모오버라이드=None
):
    """행동자원/MP/자원소모를 실제로 깎고 사용 횟수를 기록한다.
    사용_가능여부()로 가능하다고 확인한 뒤에만 불러야 한다. "일반행동"은
    _일반행동_지불수단() 순서(쇼타임행동 -> 일반행동 -> 보조행동)로 깎는다."""
    행동들 = _행동종류목록(스킬데이터.get("행동"))
    if "전체소모" in 행동들:
        for k in ("일반행동", "보조행동", "반응행동"):
            참가자["행동자원"][k] = 0
    else:
        for 행동 in 행동들:
            if 행동 == "일반행동":
                수단 = _일반행동_지불수단(전투상태, 참가자, 스킬데이터)
                if 수단 == "쇼타임행동":
                    참가자["기타행동"]["쇼타임행동"] -= 1
                    continue
                행동 = 수단 or "일반행동"
            참가자["행동자원"][행동] = 참가자["행동자원"].get(행동, 0) - 1

    MP소모 = MP소모오버라이드
    if MP소모 is None:
        MP소모 = 스킬데이터.get("MP소모", 0)
    MP소모 *= stats.MP소모_배율(참가자)  # 중갑/판금 패널티
    if MP소모:
        참가자["현재MP"] -= MP소모

    자원소모 = (
        자원소모오버라이드
        if 자원소모오버라이드 is not None
        else 스킬데이터.get("자원소모")
    )
    if 자원소모:
        for 이름, 개수 in 자원소모.items():
            resources.자원_소모(전투상태, 참가자, 이름, 개수)

    스킬이름 = 스킬데이터.get("_이름", "이스킬")
    남은정보 = 휴식_남은횟수(전투상태, 참가자, 스킬데이터)
    if 남은정보 is not None:
        _휴식제한_칸(참가자)[스킬이름] = max(0, 남은정보[0] - 1)
    참가자.setdefault("이번턴_스킬사용횟수", {})
    참가자.setdefault("전투당_스킬사용횟수", {})
    참가자["이번턴_스킬사용횟수"][스킬이름] = (
        참가자["이번턴_스킬사용횟수"].get(스킬이름, 0) + 1
    )
    참가자["전투당_스킬사용횟수"][스킬이름] = (
        참가자["전투당_스킬사용횟수"].get(스킬이름, 0) + 1
    )


