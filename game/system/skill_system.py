def 공격스킬_실행(
    전투상태,
    시전자,
    스킬데이터,
    중심대상=None,
    지정대상목록=None,
    타겟종류오버라이드=None,
    대상기록=None,
):
    """대상기록: 리스트를 넘기면 실제로 친 참가자를 타격 순서대로 담는다
    (분할공격 2단계가 1단계 대상을 이름 대신 객체로 이어받는 데 쓴다 - B8)."""
    타겟종류 = 타겟종류오버라이드 or 스킬데이터["타겟"]
    각개별굴림 = 스킬데이터.get("각공격명중굴림", False)
    공격횟수 = _정수_평가(스킬데이터.get("공격횟수", 1), 전투상태, 시전자)
    대상당제한 = 스킬데이터.get("대상당피격제한")
    if 대상당제한 is not None:
        대상당제한 = _정수_평가(대상당제한, 전투상태, 시전자)

    강제치명타 = 스킬데이터.get("강제치명타", False)
    치명타체크 = 스킬데이터.get("치명타체크", False)
    효과리스트 = 스킬데이터.get("효과", [])
    조건부효과리스트 = 스킬데이터.get("조건부효과", [])
    데미지보너스 = 스킬데이터.get("데미지보너스", 0)
    명중보너스 = 스킬데이터.get("명중보너스", 0)
    속성 = 스킬데이터.get("속성")
    속성변환 = None
    추가피해목록 = None

    if 스킬데이터.get("일반공격취급") or 스킬데이터.get("장전소모"):
        _, 장전속성변환, 장전추가피해, 장전추가피해속성 = resources.장전소모_처리(
            전투상태, 시전자
        )
        속성변환 = 장전속성변환
        if 장전추가피해속성 and 장전추가피해:
            # 은탄: 추가피해는 공격 속성과 따로 명속성으로 계산.
            추가피해목록 = [(장전추가피해, 장전추가피해속성)]
        else:
            데미지보너스 += 장전추가피해

    타격들 = []

    if 타겟종류 in ("적랜덤반복", "적반복지정"):
        후보풀 = 타겟_확장(전투상태, 시전자, 타겟종류, 중심대상)
        선택횟수 = {}
        for i in range(공격횟수):
            if 타겟종류 == "적반복지정" and 지정대상목록:
                대상 = 지정대상목록[i] if i < len(지정대상목록) else 지정대상목록[-1]
                if not 대상["생존"]:
                    # 앞선 타격으로 지정 대상이 쓰러지면 남은 적 중 무작위로
                    # 대신 맞힌다(가정 - 헛치지 않게).
                    남은적 = [p for p in 후보풀 if p["생존"]]
                    대상 = random.choice(남은적) if 남은적 else None
            else:
                유효후보 = [
                    p
                    for p in 후보풀
                    if p["생존"]
                    and (대상당제한 is None or 선택횟수.get(id(p), 0) < 대상당제한)
                ]
                if not 유효후보:
                    유효후보 = [p for p in 후보풀 if p["생존"]]
                대상 = random.choice(유효후보) if 유효후보 else None
            if 대상 is None:
                타격들.append({"비고": "대상 없음"})
                continue
            선택횟수[id(대상)] = 선택횟수.get(id(대상), 0) + 1
            결과 = 공격_1회(
                전투상태,
                시전자,
                대상,
                _값_또는_리스트(스킬데이터["데미지"], i),
                데미지보너스,
                _값_또는_리스트(스킬데이터["명중률"], i),
                명중보너스,
                강제치명타,
                치명타체크,
                효과리스트,
                조건부효과리스트,
                속성=속성,
                추가피해목록=추가피해목록,
                속성변환=속성변환,
                속성추가피해=스킬데이터.get("속성추가피해"),
                일반공격취급=bool(스킬데이터.get("일반공격취급")),
            )
            타격들.append(결과)
            if 대상기록 is not None:
                대상기록.append(대상)
    else:
        대상목록 = 타겟_확장(전투상태, 시전자, 타겟종류, 중심대상)
        for 대상 in 대상목록:
            공유판정 = None
            for i in range(공격횟수):
                미리계산된판정 = None if (i == 0 or 각개별굴림) else 공유판정
                결과 = 공격_1회(
                    전투상태,
                    시전자,
                    대상,
                    _값_또는_리스트(스킬데이터["데미지"], i),
                    데미지보너스,
                    _값_또는_리스트(스킬데이터["명중률"], i),
                    명중보너스,
                    강제치명타,
                    치명타체크,
                    효과리스트,
                    조건부효과리스트,
                    미리계산된판정=미리계산된판정,
                    속성=속성,
                    추가피해목록=추가피해목록,
                    속성변환=속성변환,
                    속성추가피해=스킬데이터.get("속성추가피해"),
                    일반공격취급=bool(스킬데이터.get("일반공격취급")),
                )
                if i == 0:
                    공유판정 = 결과["판정"]
                타격들.append(결과)
                if 대상기록 is not None:
                    대상기록.append(대상)

    총피해 = sum(t.get("피해", 0) for t in 타격들)
    결과 = {
        "공격자": 시전자["이름"],
        "스킬": 스킬데이터.get("_이름"),
        "타격": 타격들,
        "총피해": 총피해,
    }
    core._로그(전투상태, 결과)
    return 결과


def 분할공격_실행(전투상태, 시전자, 스킬데이터, 중심대상=None):
    단계1 = dict(스킬데이터["공격단계1"])
    단계1["_이름"] = f"{스킬데이터.get('_이름')} (1단계)"
    단계1대상 = []
    결과1 = 공격스킬_실행(전투상태, 시전자, 단계1, 중심대상, 대상기록=단계1대상)

    단계2 = dict(스킬데이터["공격단계2"])
    단계2["_이름"] = f"{스킬데이터.get('_이름')} (2단계)"
    단계2중심 = 중심대상
    if 단계2.get("기준대상") == "공격단계1" and 단계1대상:
        단계2중심 = 단계1대상[0]
    if 단계2.get("타겟") in ("아군단일", "적단일") and not 단계2중심["생존"]:
        # 1단계에서 기준 대상이 쓰러졌다 - 단일 대상 2단계는 칠 대상이 없다(B12).
        결과2 = {
            "공격자": 시전자["이름"],
            "스킬": 단계2["_이름"],
            "타격": [],
            "총피해": 0,
        }
        core._로그(전투상태, dict(결과2, 비고="기준 대상이 쓰러져 2단계 없음"))
    else:
        결과2 = 공격스킬_실행(전투상태, 시전자, 단계2, 단계2중심)

    return {
        "공격자": 시전자["이름"],
        "스킬": 스킬데이터.get("_이름"),
        "1단계": 결과1,
        "2단계": 결과2,
        "총피해": 결과1["총피해"] + 결과2["총피해"],
    }


def 지속공격_등록(전투상태, 시전자, 스킬데이터, 중심대상=None):
    """즉시 데미지 없이 지속 데미지만 주는 순수 지속형 공격("지속공격"
    태그)을 대상에게 등록한다. 실제 매 턴 발동은 _지속공격_발동()이
    맡는다 - 여기서는 상태이상 자료구조에 등록만 한다.

    "출처스킬"에는 스킬데이터 전체가 아니라 그 안의 "지속공격" 상세
    (job_skill_format.py <지속공격 양식>의 데미지/명중률/공격횟수 등이
    실제로 들어있는 자리)를 저장해야 한다 - _지속공격_발동()이
    출처스킬.get("데미지")처럼 그 안의 값을 바로 읽기 때문이다."""
    상세 = 스킬데이터["지속공격"]
    대상목록 = 타겟_확장(전투상태, 시전자, 상세["타겟"], 중심대상)
    for 대상 in 대상목록:
        대상.setdefault("상태이상", []).append(
            {
                "이름": 스킬데이터.get("_이름"),
                "지속턴": _정수_평가(상세.get("지속턴", 1), 전투상태, 대상),
                "종류": "지속공격",
                "출처스킬": 상세,
                "시전자이름": 시전자["이름"],
                "시전자id": 시전자.get("id"),
                "매턴명중굴림": 상세.get("매턴명중굴림", False),
            }
        )
    결과 = {
        "공격자": 시전자["이름"],
        "스킬": 스킬데이터.get("_이름"),
        "대상": [p["이름"] for p in 대상목록],
        "비고": "지속공격 등록됨 (실제 발동은 시전자 턴 종료 시 - 아래 다음_턴 참고)",
    }
    core._로그(전투상태, 결과)
    return 결과


# =====================================================
# 지속공격 / 소환수 자동 발동 (시전자 턴 종료 시)
# =====================================================
# 둘 다 "대상"이 아니라 "시전자의 턴이 끝날 때" 발동해야 하는데,
# combat.flow._턴_종료_처리는 대상 기준(참가자 자신에게 걸린 상태이상)
# 으로만 순회하고, combat 패키지는 skill_system.py를 부르지 않는 구조라
# 그 안에 넣을 수도 없다. 그래서 아래 두 함수는 이 파일에서 combat 패키지를
# 불러 쓰는 방향으로만 두고, 공용 다음_턴()이 combat.flow.다음_턴()을
# 부르기 직전에 호출해준다.


def _지속공격_발동(전투상태, 시전자):
    """job_skill_format.py <지속공격 양식>(예: 보이드, 나이트 할로우)이
    걸어둔 지속공격을 실제로 발동시킨다. 전투상태의 모든 참가자를 돌며,
    "종류":"지속공격"이고 "시전자id"가 이 시전자인 항목을 찾아
    공격_1회를 그대로 재사용해 타격한다(효과/조건부효과/치명타 등이
    일반 공격스킬과 동일하게 반영된다).

    "매턴명중굴림"이 False면 항목에 저장해둔 첫 판정 결과를 계속
    재사용하고(재판정 없음), True면 매번 새로 판정한다. 어느 쪽이든
    판정에 실패하면 그 시점에 항목을 제거해 효과를 끝낸다."""
    for 참가자 in 전투상태["참가자"]:
        for 항목 in list(참가자.get("상태이상", [])):
            if 항목.get("종류") != "지속공격" or 항목.get("시전자id") != 시전자.get(
                "id"
            ):
                continue

            출처스킬 = 항목.get("출처스킬", {})
            매턴명중굴림 = 출처스킬.get("매턴명중굴림", False)
            공격횟수 = _정수_평가(출처스킬.get("공격횟수", 1), 전투상태, 시전자)
            강제치명타 = 출처스킬.get("강제치명타", False)
            치명타체크 = 출처스킬.get("치명타체크", False)
            효과리스트 = 출처스킬.get("효과", [])
            조건부효과리스트 = 출처스킬.get("조건부효과", [])

            총피해 = 0
            중단됨 = False
            공유판정 = 항목.get("명중판정")
            for i in range(공격횟수):
                재판정필요 = 매턴명중굴림 or 공유판정 is None
                미리계산된판정 = None if 재판정필요 else 공유판정
                결과 = 공격_1회(
                    전투상태,
                    시전자,
                    참가자,
                    _값_또는_리스트(출처스킬.get("데미지", "0"), i),
                    출처스킬.get("데미지보너스", 0),
                    _값_또는_리스트(출처스킬.get("명중률", "자동"), i),
                    출처스킬.get("명중보너스", 0),
                    강제치명타,
                    치명타체크,
                    효과리스트,
                    조건부효과리스트,
                    미리계산된판정=미리계산된판정,
                    속성=출처스킬.get("속성"),
                    속성추가피해=출처스킬.get("속성추가피해"),
                )
                if i == 0:
                    공유판정 = 결과["판정"]
                    항목["명중판정"] = 공유판정
                총피해 += 결과.get("피해", 0)
                if not 결과["판정"]["성공"]:
                    중단됨 = True
                    break

            core._로그(
                전투상태,
                {
                    "공격자": 시전자["이름"],
                    "대상": 참가자["이름"],
                    "스킬": 항목.get("이름"),
                    "총피해": 총피해,
                    "비고": "지속공격 자동 발동"
                    + (" (판정 실패로 해제)" if 중단됨 else ""),
                },
            )
            if 중단됨 and 항목 in 참가자.get("상태이상", []):
                참가자["상태이상"].remove(항목)


def _소환수_행동_실행(전투상태, 시전자):
    """summon_00.py "소환수목록"의 "행동표"를, 시전자가 부린 소환수마다
    1d6을 굴려 나온 행동을 자동으로 실행한다. "능력치참조":"시전자"라
    소환수 자체의 참가자 인스턴스나 이니셔티브가 없다 - 공격스킬_실행을
    시전자 명의로 그대로 재사용해서, 시전자의 능력치/버프가 그대로
    쓰이게 한다(stats.기본_컨텍스트가 어차피 "시전자"를 기준으로 계산하므로
    별도 처리가 필요 없다). "타입"이 "공격"이 아닌 행동표 항목(현재
    데이터에는 없음)은 아직 지원하지 않아 건너뛴다."""
    for 소환수이름 in list(시전자.get("소환수", [])):
        정의 = summon_00.소환수목록.get(소환수이름)
        행동표 = (정의 or {}).get("행동표")
        if not 행동표:
            continue

        눈 = dice_utils.주사위_합(1, 6)
        행동 = 행동표.get(눈)
        if 행동 is None or 행동.get("타입") != "공격":
            continue

        스킬데이터 = dict(행동)
        스킬데이터["분류"] = "공격스킬"
        스킬데이터.setdefault("효과", [])
        스킬데이터.setdefault("조건부효과", [])
        스킬데이터.setdefault("일반공격취급", False)
        스킬데이터["_이름"] = f"{소환수이름}의 {행동.get('이름', '행동')}"
        # 소환수는 대상을 직접 고르지 않는다 - "적단일"/"적3체"는 지정
        # 가능한(은신 아닌) 생존 적 중 무작위를 중심으로 삼는다(중심대상
        # 없이 부르면 ValueError).
        중심 = None
        if 스킬데이터.get("타겟") in ("적단일", "적3체"):
            후보 = [p for p in 전투상태["참가자"] if p["진영"] == "적" and p["생존"]]
            지정가능 = [
                p for p in 후보 if not status.상태이상_플래그(전투상태, p, "지정불가")
            ]
            후보 = 지정가능 or 후보
            if not 후보:
                continue
            중심 = random.choice(후보)
            if not 지정가능:
                스킬데이터["타겟"] = (
                    "적3체" if 스킬데이터["타겟"] == "적3체" else "적랜덤"
                )
        공격스킬_실행(전투상태, 시전자, 스킬데이터, 중심)


def 다음_턴(전투상태):
    """combat.flow.다음_턴()을 감싼다. 위 _지속공격_발동()/
    _소환수_행동_실행()이 "combat 패키지는 skill_system을 부르지 않는다"는
    순환 참조 방지 원칙 때문에 combat.flow._턴_종료_처리 안에 들어갈 수
    없어서, 이 파일에 별도로 감싸는 함수를 두었다. 지속공격 스킬이나
    소환스킬을 쓰는 프로젝트라면 앞으로 턴을 넘길 때 combat.flow.다음_턴
    대신 반드시 이 함수를 호출해야 한다."""
    현재참가자 = flow.현재_턴_참가자(전투상태)
    _지속공격_발동(전투상태, 현재참가자)
    _소환수_행동_실행(전투상태, 현재참가자)
    return flow.다음_턴(전투상태)


def 버프자원소환_스킬_실행(전투상태, 시전자, 스킬데이터, 중심대상=None):
    명중률 = 스킬데이터.get("명중률", "자동")
    if 명중률 != "자동":
        raise NotImplementedError(
            f"버프/자원/소환스킬의 명중률 '{명중률}'은 지원하지 않는다 "
            f"(버프/자원/소환스킬은 항상 '자동'만 쓰는 것으로 확정됨 - 사용자 확인)."
        )

    대상목록 = 타겟_확장(전투상태, 시전자, 스킬데이터["타겟"], 중심대상)
    지속턴 = 스킬데이터.get("지속턴")
    지속턴값 = _정수_평가(지속턴, 전투상태, 시전자) if 지속턴 is not None else None

    버프이름들 = 스킬데이터.get("버프획득") or (
        [스킬데이터["자원획득"]] if "자원획득" in 스킬데이터 else []
    )
    if isinstance(버프이름들, str):
        버프이름들 = [버프이름들]

    # 중첩량 수식("주문시전보정치" 등)은 건 사람(시전자) 기준이다 - 용맹의 축복처럼
    # 시전자의 보정치만큼 거는 스킬. 0 이하면 걸지 않는다(음수 중첩 방지).
    중첩량 = _정수_평가(스킬데이터.get("중첩량", 1), 전투상태, 시전자)
    for 대상 in 대상목록:
        for 이름 in 버프이름들:
            if 중첩량 <= 0:
                continue
            이름있는효과_부여(
                전투상태,
                대상,
                이름,
                중첩량=중첩량,
                지속턴오버라이드=지속턴값,
                시전자=시전자,
                무기조건=스킬데이터.get("버프무기조건"),
                출처스킬=스킬데이터.get("_이름"),
            )

        if "임시생명력" in 스킬데이터:
            양 = formula.수식_평가(
                스킬데이터["임시생명력"], stats.기본_컨텍스트(전투상태, 대상)
            )
            대상["임시생명력"] = 대상.get("임시생명력", 0) + 양

    결과 = {
        "공격자": 시전자["이름"],
        "스킬": 스킬데이터.get("_이름"),
        "대상": [p["이름"] for p in 대상목록],
        "버프": 버프이름들,
    }
    core._로그(전투상태, 결과)
    return 결과


