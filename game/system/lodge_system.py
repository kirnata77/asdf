# =====================
# 모험단 숙소 시스템
# =====================
# 마을 [주점]의 파티원 영입/대기/합류/추방. 파티에 없는 동료는 "모험단 숙소"
# (최대 20명, 캐릭터 리스트)에서 기다린다. 숙소 동료도 장비를 낀 채로 있고,
# 그 장비는 소지품["장비"] 개수에 포함된 채 다른 캐릭터가 쓸 수 없다
# (equipment_system/shop_system 장착중_개수가 숙소도 센다). 추방하면 캐릭터만
# 지워지고, 끼고 있던 장비는 소지품에 남아 다시 쓸 수 있게 된다.
#
# 파티 쪽 추가/제거는 party_system을 쓴다. 캐릭터 생성/골드 처리는 호출하는
# 쪽(gameflow)이 한다.

from game.system import party_system

숙소_최대인원 = 20
파티_최소인원 = 1


def _있는가(목록, 캐릭터):
    return any(c is 캐릭터 for c in 목록)


def _빼기(목록, 캐릭터):
    for i, c in enumerate(목록):
        if c is 캐릭터:
            del 목록[i]
            return
    raise ValueError(f"'{캐릭터.get('캐릭터명')}'은(는) 숙소에 없다.")


def 영입_자리(파티, 숙소):
    """새 동료가 들어갈 곳 - "파티"(빈자리 있음) / "숙소" / None(둘 다 꽉 참)."""
    if len(파티["파티원"]) < party_system.파티_최대인원:
        return "파티"
    if len(숙소) < 숙소_최대인원:
        return "숙소"
    return None


def 영입(파티, 숙소, 캐릭터):
    """파티에 빈자리가 있으면 파티로, 없으면 숙소로. 들어간 곳을 반환한다.
    둘 다 꽉 차면 ValueError."""
    자리 = 영입_자리(파티, 숙소)
    if 자리 == "파티":
        party_system.파티원_추가(파티, 캐릭터)
    elif 자리 == "숙소":
        숙소.append(캐릭터)
    else:
        raise ValueError(f"모험단 숙소가 가득 찼다(최대 {숙소_최대인원}명).")
    return 자리


def 대기(파티, 숙소, 캐릭터):
    """파티원을 숙소로 보낸다. 파티에는 최소 1명이 남아야 한다."""
    if not _있는가(파티["파티원"], 캐릭터):
        raise ValueError(f"'{캐릭터.get('캐릭터명')}'은(는) 파티에 없다.")
    if len(파티["파티원"]) <= 파티_최소인원:
        raise ValueError("파티에는 최소 1명이 남아야 한다.")
    if len(숙소) >= 숙소_최대인원:
        raise ValueError(f"모험단 숙소가 가득 찼다(최대 {숙소_최대인원}명).")
    party_system.파티원_제거(파티, 캐릭터)
    숙소.append(캐릭터)


def 합류(파티, 숙소, 캐릭터):
    """숙소 동료를 파티로 데려온다. 파티가 꽉 차 있으면 ValueError."""
    if not _있는가(숙소, 캐릭터):
        raise ValueError(f"'{캐릭터.get('캐릭터명')}'은(는) 숙소에 없다.")
    if len(파티["파티원"]) >= party_system.파티_최대인원:
        raise ValueError(f"파티가 가득 찼다(최대 {party_system.파티_최대인원}명).")
    _빼기(숙소, 캐릭터)
    party_system.파티원_추가(파티, 캐릭터)


def 추방(파티, 숙소, 캐릭터):
    """파티원 또는 숙소 동료를 지운다(파티에는 최소 1명이 남아야 한다).
    끼고 있던 장비는 소지품 개수에 그대로 남아 다시 쓸 수 있다."""
    if _있는가(파티["파티원"], 캐릭터):
        if len(파티["파티원"]) <= 파티_최소인원:
            raise ValueError("파티에는 최소 1명이 남아야 한다.")
        party_system.파티원_제거(파티, 캐릭터)
    else:
        _빼기(숙소, 캐릭터)
