# 장비 시스템
# =====================
# 캐릭터의 "장착장비"(character_format.py 참고: 슬롯 이름 -> 아이템 "이름")를
# 갈아 끼우는 처리와, 지금 장착 중인 장비들이 주는 보너스를 합산하는 처리를
# 담당한다.
#
# 다른 시스템 파일들과 같은 이유로, 이 파일도 "아이템 이름 -> 실제 데이터"
# 연결을 스스로 찾아가지 않는다. 캐릭터에는 장착한 아이템의 "이름"만
# 저장되고(character_data_system.py "장착장비"), 보너스 계산처럼 실제 수치가
# 필요한 함수는 호출하는 쪽이 eq_XX_XX.py에서 찾은 아이템 데이터 자체를
# 넘겨준다고 가정한다. 세트 정의(eq_02_armor_set.py 등)도 마찬가지로
# 호출하는 쪽이 넘겨준다.

# 방어구 슬롯 목록 (character_format.py "장착장비" 기준).
방어구_슬롯 = ["상의", "하의", "어깨", "벨트", "신발"]

# 장비 슬롯 -> 그 슬롯에 들어가는 아이템의 "분류" 값.
# eq_02_armor_XX.py / eq_03_accessory_XX.py / eq_04_special_XX.py의
# "분류"가 여기 대응한다. 무기는 "분류"가 직업마다 다르므로(예:
# "귀검사 무기") 여기서 고정값으로 검사하지 않는다.
슬롯별_분류 = {
    "무기": None,
    "상의": "상의",
    "하의": "하의",
    "어깨": "어깨",
    "벨트": "벨트",
    "신발": "신발",
    "목걸이": "목걸이",
    "반지": "반지",
    "팔찌": "팔찌",
    "보조장비": "보조장비",
    "마법석": "마법석",
    "귀걸이": "귀걸이",
}

_보너스_키 = ["AC보너스", "데미지보너스", "명중률보너스", "속도보너스"]


# =====================================================
# 장착 / 해제
# =====================================================


def 장착_가능여부(캐릭터, 슬롯, 아이템데이터):
    """해당 슬롯에 이 아이템을 장착할 수 있는지 (가능여부, 사유) 튜플로
    반환한다. 사유는 불가능할 때만 문자열로 채워진다.

    - 무기는 "타입"(소검/도/둔기/대검/광검 등)이 캐릭터의 "가용무기"
      목록에 있어야 한다.
    - 상의/하의/어깨/벨트/신발은 "재질"(천갑/가죽/경갑/중갑/판금)이
      캐릭터의 "가용방어구" 목록에 있어야 한다.
    - 목걸이/반지/팔찌/보조장비/마법석/귀걸이는 슬롯과 "분류"만
      일치하면 된다 (착용 제한 없음).
    """
    if 슬롯 not in 캐릭터["장착장비"]:
        return False, f"존재하지 않는 슬롯: {슬롯}"

    기대분류 = 슬롯별_분류.get(슬롯)
    if 기대분류 is not None and 아이템데이터.get("분류") != 기대분류:
        return False, f"'{아이템데이터.get('이름')}'은(는) {슬롯} 슬롯에 맞지 않는다."

    if 슬롯 == "무기":
        if 아이템데이터.get("타입") not in 캐릭터["가용무기"]:
            return False, (
                f"'{아이템데이터.get('이름')}'"
                f"({아이템데이터.get('타입')}) 종류의 무기는 "
                f"아직 사용할 수 없다."
            )
    elif 슬롯 in 방어구_슬롯:
        if 아이템데이터.get("재질") not in 캐릭터["가용방어구"]:
            return False, (
                f"'{아이템데이터.get('이름')}'"
                f"({아이템데이터.get('재질')}) 재질은 "
                f"아직 착용할 수 없다."
            )

    return True, None


def 장비_장착(캐릭터, 슬롯, 아이템데이터):
    """장착 가능하면 "장착장비"[슬롯]에 아이템 이름을 기록한다.
    불가능하면 ValueError를 낸다."""
    가능, 사유 = 장착_가능여부(캐릭터, 슬롯, 아이템데이터)
    if not 가능:
        raise ValueError(사유)
    캐릭터["장착장비"][슬롯] = 아이템데이터["이름"]


def 장비_해제(캐릭터, 슬롯):
    """해당 슬롯을 비운다. 이미 비어 있어도 에러 없이 넘어간다."""
    if 슬롯 not in 캐릭터["장착장비"]:
        raise ValueError(f"존재하지 않는 슬롯: {슬롯}")
    캐릭터["장착장비"][슬롯] = None


# =====================================================
# 세트효과
# =====================================================
# 세트목록 : eq_02_armor_set.py "방어구세트목록"처럼 {세트명: 세트정의}
# 딕셔너리. 세트정의의 "구성품"(아이템 이름 리스트)에 적힌 아이템을
# 전부 장착하고 있으면 그 세트가 활성화된다. 여러 세트 목록을
# 함께 검사하려면 호출하는 쪽이 딕셔너리를 합쳐서 넘긴다.


def 세트효과_목록(장착아이템데이터, 세트목록):
    """활성화된 세트정의들을 리스트로 반환한다. 세트목록이 없으면 빈 리스트.

    세트가 활성화되는 조건은 두 가지 형식 중 하나다.
    - "구성품"(아이템 이름 리스트)이 있으면: 그 아이템을 전부 장착했을 때.
      "구성품"이 비어 있으면 활성화되지 않는다.
    - "구성품"이 없는 방어구세트("분류": "방어구세트", "타입": 재질): 방어구 5부위
      (방어구_슬롯)를 전부 그 재질로 입었을 때 - eq_02_armor_set.py 머리말의
      "재질 5부위를 전부 갖추면 발동" 규칙."""
    if not 세트목록:
        return []
    장착이름들 = {
        아이템데이터.get("이름")
        for 아이템데이터 in 장착아이템데이터.values()
        if 아이템데이터 is not None
    }
    return [
        세트정의
        for 세트정의 in 세트목록.values()
        if _세트_충족(세트정의, 장착아이템데이터, 장착이름들)
    ]


def _세트_충족(세트정의, 장착아이템데이터, 장착이름들):
    if "구성품" in 세트정의:
        구성품 = 세트정의.get("구성품") or []
        return bool(구성품) and all(이름 in 장착이름들 for 이름 in 구성품)
    재질 = 세트정의.get("타입")
    if 세트정의.get("분류") != "방어구세트" or not 재질:
        return False
    return all(
        (장착아이템데이터.get(슬롯) or {}).get("재질") == 재질 for 슬롯 in 방어구_슬롯
    )


# =====================================================
# 장착 중인 장비의 보너스 합산
# =====================================================
# 아래 함수들은 캐릭터["장착장비"]에 적힌 "이름"이 아니라, 그 이름에
# 해당하는 실제 아이템 데이터 자체를 인자로 받는다.
#
# 장착아이템데이터 : {슬롯: 아이템데이터 또는 None, ...} 형태.
# 빈 슬롯은 값이 None이거나 아예 키가 없어도 된다. (이름 -> 데이터
# 조회는 장비 데이터 전체를 아는 호출하는 쪽의 몫이다.)


def _보너스_더하기(합계, 원천):
    for 키 in _보너스_키:
        값 = 원천.get(키, 0)
        if isinstance(값, (int, float)):
            합계[키] += 값
    for 스탯이름, 증가폭 in (원천.get("스탯보너스") or {}).items():
        if isinstance(증가폭, (int, float)):
            합계["스탯보너스"][스탯이름] = 합계["스탯보너스"].get(스탯이름, 0) + 증가폭


def 장비_보너스_합산(장착아이템데이터, 세트목록=None):
    """장착 중인 모든 아이템의 AC보너스/데미지보너스/명중률보너스/
    속도보너스/스탯보너스를 전부 더한 딕셔너리를 반환한다. 아이템에
    해당 키가 없으면 0(스탯보너스는 미기재 스탯 0)으로 취급한다.
    세트목록을 주면 활성화된 세트(세트효과_목록)의 "효과"도 같은 키로
    더한다."""
    합계 = {
        "AC보너스": 0,
        "데미지보너스": 0,
        "명중률보너스": 0,
        "속도보너스": 0,
        "스탯보너스": {
            "근력": 0,
            "민첩": 0,
            "건강": 0,
            "지능": 0,
            "지혜": 0,
            "매력": 0,
        },
    }

    for 아이템데이터 in 장착아이템데이터.values():
        if 아이템데이터 is None:
            continue
        _보너스_더하기(합계, 아이템데이터)

    for 세트정의 in 세트효과_목록(장착아이템데이터, 세트목록):
        _보너스_더하기(합계, 세트정의.get("효과") or {})

    return 합계


def 민첩상한_계산(캐릭터, 장착아이템데이터):
    """장착 중인 방어구들의 "민첩상한"(eq_02_armor_format.py 기준) 중
    가장 낮은 값을 최종 상한으로 쓴다. None은 "제한 없음"이라 비교에서
    제외한다. 방어구를 하나도 안 입었거나 전부 제한이 없으면
    None(제한 없음)을 반환한다.

    "경갑숙련" 같은 특성으로 "민첩상한해제"를 받은 재질(캐릭터
    "민첩상한해제" 목록, effect_engine.py가 채워준다)의 방어구는 그
    아이템의 "민첩상한"을 아예 집계에서 제외한다 - 그 슬롯만큼은
    상한이 없는 것으로 취급한다는 뜻이다."""
    민첩상한해제된_재질 = 캐릭터.get("민첩상한해제", [])
    상한값들 = [
        아이템데이터.get("민첩상한")
        for 아이템데이터 in 장착아이템데이터.values()
        if 아이템데이터 is not None
        and "민첩상한" in 아이템데이터
        and 아이템데이터.get("재질") not in 민첩상한해제된_재질
    ]
    상한값들 = [값 for 값 in 상한값들 if 값 is not None]

    if not 상한값들:
        return None
    return min(상한값들)


def 최종AC_계산(캐릭터, 장착아이템데이터, 세트목록=None, 추가민첩=0):
    """eq_02_armor_format.py 공식 그대로 계산한다.
    최종 AC = 기본AC + AC보너스(장비+세트) + min(민첩수정치, 민첩상한)
    (민첩상한이 없으면 민첩수정치를 제한 없이 전부 더한다.)

    민첩수정치는 캐릭터 원래 민첩에 장비(+세트) "스탯보너스"의 민첩과
    추가민첩(전투 중 버프/디버프로 늘거나 준 민첩 - combat.stats.최종AC가
    계산해 넘긴다)을 더한 값으로 계산한다. 전투 밖에서
    부를 때는 추가민첩을 생략하면 된다."""
    보너스 = 장비_보너스_합산(장착아이템데이터, 세트목록)
    민첩상한 = 민첩상한_계산(캐릭터, 장착아이템데이터)
    민첩값 = 캐릭터["민첩"] + 보너스["스탯보너스"].get("민첩", 0) + 추가민첩
    민첩수정치 = (민첩값 - 10) // 2

    if 민첩상한 is not None:
        민첩수정치 = min(민첩수정치, 민첩상한)

    return 캐릭터["기본AC"] + 보너스["AC보너스"] + 민첩수정치


# =====================================================
# 장비 반영 능력치 / 최대HP / 최대MP (전투 밖 공용)
# =====================================================
# 캐릭터에 저장된 능력치/"기본최대HP"/"기본최대MP"는 장비를 뺀 값이다.
# 아래 함수들은 장비(+세트) "스탯보너스"를 더한 값을 그때그때 계산한다 -
# 캐릭터 데이터 자체는 바꾸지 않으므로 장비를 바꿔도 되돌릴 필요가 없다.

능력치_이름목록 = ("근력", "민첩", "건강", "지능", "지혜", "매력")


def _보정치(값):
    return (값 - 10) // 2


def 장비반영_능력치(캐릭터, 장착아이템데이터, 세트목록=None):
    """{능력치이름: 원래값 + 장비 스탯보너스} 딕셔너리."""
    보너스 = 장비_보너스_합산(장착아이템데이터, 세트목록)["스탯보너스"]
    return {이름: 캐릭터[이름] + 보너스.get(이름, 0) for 이름 in 능력치_이름목록}


def 장비반영_최대HP(캐릭터, 장착아이템데이터, 세트목록=None):
    """기본최대HP는 레벨마다 건강보정치를 1번씩 더한 값(레벨 1 포함,
    character_data_system.기본최대HP_계산)이므로, 장비로 바뀐
    건강보정치의 차이 × 레벨만큼 더한다."""
    능력치 = 장비반영_능력치(캐릭터, 장착아이템데이터, 세트목록)
    차이 = _보정치(능력치["건강"]) - _보정치(캐릭터["건강"])
    return max(1, 캐릭터["기본최대HP"] + 차이 * 캐릭터.get("레벨", 1))


def 장비반영_최대MP(캐릭터, 장착아이템데이터, 세트목록=None):
    """최대MP = 50 + 10×주문시전보정치이므로, 장비로 바뀐 주문시전
    능력치 보정치의 차이 × 10만큼 더한다(주문시전능력치가 없으면 그대로)."""
    스탯 = 캐릭터.get("주문시전능력치")
    if 스탯 is None:
        return 캐릭터["기본최대MP"]
    능력치 = 장비반영_능력치(캐릭터, 장착아이템데이터, 세트목록)
    차이 = _보정치(능력치[스탯]) - _보정치(캐릭터[스탯])
    return max(0, 캐릭터["기본최대MP"] + 10 * 차이)


# =====================================================
# 소지품 연동 - 장비 교체
# =====================================================
# 소지품["장비"]는 "아이템이름 -> 개수"이고, 장착 중인 아이템도 그 개수에
# 포함되어 있다(장착품_소지품_동기화 참고). 그래서 교체 후보는 "소지품
# 개수 - 파티 전체가 장착 중인 개수"가 1개 이상인 아이템이고, 교체 자체는
# 소지품 개수를 바꾸지 않고 캐릭터의 장착 슬롯 이름만 바꾼다.


def 장착중_개수(플레이어, 이름):
    """파티원 전체가 이 이름의 아이템을 장착하고 있는 개수 합계."""
    개수 = 0
    for 캐릭터 in 플레이어.get("파티", {}).get("파티원", []):
        for 장착이름 in 캐릭터.get("장착장비", {}).values():
            if 장착이름 == 이름:
                개수 += 1
    return 개수


def 장착품_소지품_동기화(플레이어):
    """장착 중인 아이템이 소지품["장비"] 개수에 포함되도록 맞춘다.
    개수가 모자란 아이템만 부족분을 더한다(시작 장비처럼 캐릭터 생성 때
    소지품 없이 바로 장착된 아이템 대비). 게임을 시작/불러올 때 한 번
    부른다."""
    장비칸 = 플레이어.setdefault("소지품", {}).setdefault("장비", {})
    장착집계 = {}
    for 캐릭터 in 플레이어.get("파티", {}).get("파티원", []):
        for 이름 in 캐릭터.get("장착장비", {}).values():
            if 이름:
                장착집계[이름] = 장착집계.get(이름, 0) + 1
    for 이름, 장착수 in 장착집계.items():
        부족 = 장착수 - 장비칸.get(이름, 0)
        if 부족 > 0:
            장비칸[이름] = 장비칸.get(이름, 0) + 부족


def 교체_후보목록(플레이어, 캐릭터, 슬롯, 슬롯아이템들):
    """[(아이템데이터, 교체가능수량, 착용가능, 사유), ...].
    슬롯아이템들은 이 슬롯에 들어가는 아이템 데이터 {이름: 데이터}
    (예: 상점 카탈로그["장비"][슬롯]). 소지품에 있어도 그 부위 아이템이
    아니면 나오지 않고, 장착 중인 것(누가 끼고 있든)은 뺀 개수만 센다.
    착용할 수 없는 아이템도 나오며 착용가능=False, 사유에 이유가 담긴다."""
    장비칸 = 플레이어.get("소지품", {}).get("장비", {})
    결과 = []
    for 이름, 개수 in 장비칸.items():
        아이템 = 슬롯아이템들.get(이름)
        if 아이템 is None:
            continue
        가능수량 = 개수 - 장착중_개수(플레이어, 이름)
        if 가능수량 <= 0:
            continue
        착용가능, 사유 = 장착_가능여부(캐릭터, 슬롯, 아이템)
        결과.append((아이템, 가능수량, 착용가능, 사유))
    return 결과


def 장비_교체(플레이어, 캐릭터, 슬롯, 아이템데이터):
    """소지품에서 남는 아이템으로 슬롯 장비를 교체한다. 소지품에 없거나
    다 다른 곳에 장착 중이거나 착용할 수 없으면 아무것도 바꾸지 않고
    ValueError를 낸다. 원래 끼던 장비는 소지품 개수에 그대로 남아 있으므로
    자동으로 교체 후보가 된다."""
    이름 = 아이템데이터["이름"]
    보유 = 플레이어.get("소지품", {}).get("장비", {}).get(이름, 0)
    if 보유 - 장착중_개수(플레이어, 이름) <= 0:
        raise ValueError(f"'{이름}'은(는) 소지품에 남은 것이 없다.")
    장비_장착(캐릭터, 슬롯, 아이템데이터)
