# =====================
# 세이브 시스템
# =====================
# 진행 상황을 파일로 저장/불러온다. 슬롯 3개 지원(최대세이브슬롯 상수로
# 조정 가능). 슬롯 하나에 "플레이어"(레벨/파티/소지품)와 "진행도"를 함께
# 저장한다. 아직 없는 시스템(퀘스트 등)의 데이터는 저장 대상에 없다 -
# 생기면 여기도 같이 추가해야 한다.
#
# 모험단 프로필(SD 초상화)은 두 가지가 서로 별개다.
# 1) 캐릭터별 "직업 기반 초상화" - 캐릭터 딕셔너리마다 "성별" 키로
#    붙어 있고(gameflow.py 초상화_코드() 참고), "파티"["파티원"]
#    리스트를 그대로 저장하는 아래 로직만으로 자동 저장/복원된다 -
#    이 파일을 따로 손댈 필요가 없다.
# 2) 던전 지도용 "플레이어 초상화" - 직업과 무관하게 65장 그리드에서
#    직접 고르는 값이라 캐릭터 딕셔너리에 없고 게임상태 최상위
#    "선택된초상화" 키에 있다(gameflow.초상화_설정() 참고) - 아래
#    "플레이어" 저장 블록에 별도로 담아야 한다.
#
# 저장 형식은 JSON(한국어 키 그대로 저장 가능). 진행도의
# "클리어한던전"(문자열 set)과 "클리어한오브젝트"((던전파일명,(x,y))
# 튜플 set)는 JSON이 못 담는 타입이라 저장/불러오기 시 리스트로
# 변환한다.
#
# 세이브 파일은 game/saves/slot_N.json에 저장되며 폴더가 없으면 자동
# 생성한다.

import json
import os
from datetime import datetime

from game.system import player_system

최대세이브슬롯 = 3


def _세이브_폴더():
    """이 파일 기준으로 game/saves/ 경로를 계산한다(cwd 무관)."""
    game_루트 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    return os.path.join(game_루트, "saves")


def _세이브_경로(슬롯번호):
    return os.path.join(_세이브_폴더(), f"slot_{슬롯번호}.json")


def 세이브_존재(슬롯번호):
    return os.path.isfile(_세이브_경로(슬롯번호))


def 게임_저장(슬롯번호, 플레이어, 진행도):
    """플레이어와 진행도를 슬롯번호 파일에 저장한다(기존 저장 있으면 덮어씀)."""
    os.makedirs(_세이브_폴더(), exist_ok=True)

    저장할_진행도 = dict(진행도)
    저장할_진행도["클리어한던전"] = sorted(진행도.get("클리어한던전", set()))
    저장할_진행도["클리어한오브젝트"] = sorted(
        [던전파일명, list(좌표)]
        for 던전파일명, 좌표 in 진행도.get("클리어한오브젝트", set())
    )

    저장데이터 = {
        "플레이어": {
            "레벨": 플레이어.get("레벨", 1),
            "파티": {"파티원": 플레이어["파티"]["파티원"]},
            "숙소": 플레이어.get("숙소", []),
            "소지품": 플레이어.get("소지품", player_system.빈_소지품()),
            "선택된초상화": 플레이어.get("선택된초상화", "001m"),
        },
        "진행도": 저장할_진행도,
        "저장시각": datetime.now().isoformat(timespec="seconds"),
    }
    with open(_세이브_경로(슬롯번호), "w", encoding="utf-8") as f:
        json.dump(저장데이터, f, ensure_ascii=False, indent=2)


def 게임_불러오기(슬롯번호):
    """(플레이어, 진행도)를 반환한다. 슬롯이 비어 있으면
    FileNotFoundError. 구버전 세이브(플레이어 키 없음)는 "파티" 키를
    새 구조로 감싸 호환한다("골드"는 소지품["골드"]로 옮긴다)."""
    경로 = _세이브_경로(슬롯번호)
    if not os.path.isfile(경로):
        raise FileNotFoundError(f"{슬롯번호}번 슬롯에는 저장된 게임이 없다.")

    with open(경로, "r", encoding="utf-8") as f:
        저장데이터 = json.load(f)

    if "플레이어" in 저장데이터:
        플레이어 = 저장데이터["플레이어"]
        플레이어.setdefault("레벨", 1)
        플레이어.setdefault("소지품", player_system.빈_소지품())
        플레이어.setdefault("선택된초상화", "001m")  # 구버전 세이브 호환
        플레이어.setdefault("숙소", [])  # 모험단 숙소 도입 전 세이브 호환
    else:
        구파티 = 저장데이터.get("파티", {})
        플레이어 = player_system.빈_플레이어()
        플레이어["파티"]["파티원"] = 구파티.get("파티원", [])
        플레이어["소지품"]["골드"] = 구파티.get("골드", 0)
        플레이어["선택된초상화"] = "001m"
        플레이어["숙소"] = []

    진행도 = dict(저장데이터["진행도"])
    진행도["클리어한던전"] = set(진행도.get("클리어한던전", []))
    진행도["클리어한오브젝트"] = {
        (항목[0], tuple(항목[1])) for 항목 in 진행도.get("클리어한오브젝트", [])
    }
    return 플레이어, 진행도


def 세이브_삭제(슬롯번호):
    """슬롯을 비운다. 이미 비어 있으면 아무 일도 하지 않는다."""
    경로 = _세이브_경로(슬롯번호)
    if os.path.isfile(경로):
        os.remove(경로)


def 세이브_요약(슬롯번호):
    """슬롯 선택 화면용 요약. 비어 있으면 None, 있으면 {"슬롯번호",
    "저장시각", "현재마을", "대표캐릭터명", "파티인원수"}."""
    경로 = _세이브_경로(슬롯번호)
    if not os.path.isfile(경로):
        return None

    with open(경로, "r", encoding="utf-8") as f:
        저장데이터 = json.load(f)

    파티원 = (
        저장데이터.get("플레이어", {}).get("파티", {}).get("파티원", [])
        or 저장데이터.get("파티", {}).get("파티원", [])  # 예전 세이브 호환
    )
    진행도 = 저장데이터.get("진행도", {})

    return {
        "슬롯번호": 슬롯번호,
        "저장시각": 저장데이터.get("저장시각"),
        "현재마을": 진행도.get("현재마을"),
        "대표캐릭터명": 파티원[0]["캐릭터명"] if 파티원 else "-",
        "파티인원수": len(파티원),
    }


def 전체_세이브_요약():
    """전체 슬롯의 세이브_요약() 리스트. 빈 슬롯은 {"슬롯번호": n,
    "비어있음": True}로 채운다."""
    결과 = []
    for 슬롯번호 in range(1, 최대세이브슬롯 + 1):
        요약 = 세이브_요약(슬롯번호)
        결과.append(요약 or {"슬롯번호": 슬롯번호, "비어있음": True})
    return 결과
