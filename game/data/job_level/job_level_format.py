# =====================
# 공용 정의 / 레벨업 테이블 양식
# =====================
# job_level_XX 파일들의 공통 구조(차수 구분, 5단계 고정 패턴, "획득" 타입별
# 하위 양식)를 모아둔 참고용 파일이다. 실제 데이터는 없다.

# =====================
# 차수 구분
# =====================
# 1차수 비전직  : 레벨 1~5   (분류번호 X-0)
# 2차수 1차전직 : 레벨 6~10  (분류번호 X-1)
# 3차수 각성    : 레벨 11~15 (서브클래스별 분류번호)
# 4차수 2차각성 : 레벨 16~20 (3차수 서브클래스에 종속)
# (분류번호 앞자리는 1차 계열 번호, 뒷자리는 그 계열 안의 전직 순번)

# =====================
# 파일 구조
# =====================
# 각 파일은 "레벨업테이블" 딕셔너리 하나만 담는다. 키는 레벨(정수),
# 값은 <레벨 항목 하위 양식>이다.
#
# 1차수(레벨 1~5):
#   레벨 1 : "특성획득"
#   레벨 2 : "스타일선택" - 전투 스타일(강타/급소/연타/정밀/수호) 하나. 정의와
#            2차수 직업유형(밀리/캐스터/하이브리드)은 job_level_000x_style.py
#   레벨 3 : "특성획득" - 직업별 방어 스킬/특성(귀검사 가드, 격투가 분신, 거너
#            건가드, 마법사 오라 실드+위상 변화, 프리스트 치유의 기도+큐어)
#   레벨 4 : "퍽획득"
#   레벨 5 : "스탯성장" - 약점스탯 뺀 서로 다른 능력치 2개에 1점씩 (추가공격 없음)
# 2차수 이후는 아래 5단계가 이 순서로 반복된다.
#   1단계 (시작레벨)   : "타입" = "특성획득"
#   2단계 (시작레벨+1) : "타입" = "스탯획득"
#   3단계 (시작레벨+2) : "타입" = "미정"  (스킬은 파티 화면 [스킬습득]으로 배운다)
#   4단계 (시작레벨+3) : "타입" = "퍽획득"
#   5단계 (시작레벨+4) : "타입" = "행동획득"

# =====================
# <레벨 항목 하위 양식> - 공통 키
# =====================
# "분류"           : "레벨진행" (고정값)
# "타입"           : 위 5단계 중 하나 (순서 고정)
# "클래스"         : 문자열 (해당 파일의 클래스 이름)
# "획득"           : <획득 하위 양식> (아래 참고)
# "주문시전능력치" : 문자열 (선택. 주문 클래스의 "특성획득" 레벨에만 명시,
#                    기본값 "지능". 전직으로 바뀌면 2차수 이상에 새로 명시.
#                    예) 프리스트 "지능" → 크루세이더 "지혜")
# "레벨당체력증가" : 정수 (선택. 레벨 1 "특성획득" 항목에만. 레벨 1을
#                    포함해 레벨마다 오르는 고정 체력치, 건강보정치는 별도
#                    가산. 전직 레벨에는 새로 적지 않고 1차 계열 값을 따른다.
#                    최종 기본최대HP = 레벨 x (레벨당체력증가 + 건강보정치))
# "기본가용무기"   : 문자열 리스트 (선택. 레벨 1에만. eq_weapon_XX.py의
#                    무기 종류와 일치. 특성으로 별도 해금하는 무기는 제외)
# "시작장비"       : 문자열 (선택. 레벨 1에만. eq_weapon_XX.py 커먼 등급과 일치)

# =====================
# <타입 종류>
# =====================
# "특성획득" - 차수 시작 레벨. 해당 차수 특성 획득. ("획득"."타입"="특성")
# "스탯획득" - 능력치 배분. ("획득"."타입"="능력치배분")
# "스탯성장" - 약점스탯 뺀 서로 다른 능력치에 1점씩. ("획득"."타입"="능력치성장")
# "스타일선택" - 전투 스타일 하나 선택. ("획득"."타입"="스타일")
# "미정"     - 아직 정하지 않은 레벨. 레벨만 오른다. ("획득" = {"설명": "미정"})
# "퍽획득"   - 공용/클래스 퍽 목록에서 하나 선택. ("획득"."타입"="퍽선택")
# "행동획득" - 추가공격 횟수 +1. ("획득"."타입"="추가공격")

# =====================
# <획득 하위 양식> - "획득" 키의 값, "타입"으로 형태 구분
# =====================
# 1) "특성" ("특성획득" 전용)
#    {"타입": "특성", "습득방법": "레벨진행", "획득특성": 이름 또는 리스트,
#     "획득스킬": 리스트(선택. 1차수 레벨 3), "설명": 문자열}
#    (job_ability_XX.py "특성목록" 키와 일치해야 함. 전용 파일 없는
#    서브클래스 특성은 상위 계열 job_ability_XX.py에 넣고 그대로 참조)
#
# 2) "능력치배분" ("스탯획득" 전용, 모든 차수/클래스 동일)
#    {"타입": "능력치배분", "배분점수": 2, "설명": "능력치 2점을 원하는
#     스탯에 배분한다. 1점씩 나눠서 두 스탯에 배분할 수도 있다."}
#
# 3) (예전 "스킬획득" 자리 - 지금은 "미정")
#
# 4) "퍽선택" ("퍽획득" 전용, 모든 차수/클래스 동일)
#    {"타입": "퍽선택", "설명": "공용 퍽 또는 클래스 퍽 목록에서 하나를 선택한다."}
#
# 5) "추가공격" ("행동획득" 전용, 모든 차수/클래스 동일)
#    {"타입": "추가공격", "추가횟수": 1, "누적공격횟수": 정수(1차수에는 없음,
#     2차수 끝=2, ...), "설명": 문자열}
#
# 6) "능력치성장" ("스탯성장" 전용)
#    {"타입": "능력치성장", "배분점수": 2, "스탯당최대": 1, "설명": 문자열}
#    약점스탯에는 ("약점제거"가 있어도) 넣을 수 없다.
#
# 7) "스타일" ("스타일선택" 전용)
#    {"타입": "스타일", "선택지": list(전투스타일), "설명": 문자열}
#    고른 값은 캐릭터["스타일"]에 기록하고, 같은 이름의 특성으로 부여한다.
