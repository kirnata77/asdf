# =====================
# 마을 데이터 양식
# =====================
# 마을(배경 일러스트 + 선택지 형식 화면) 하나의 구조를 정의하는 참고용 파일이다.
# 실제 마을 데이터는 들어있지 않다.
#
# 마을 화면 좌측의 NPC/상점/파티구성/창고/휴식 메뉴는 마을마다 다른 게 아니라
# 모든 마을에 고정으로 뜨는 공용 메뉴이고, 실제 데이터(NPC 목록, 상점 재고 등)도
# 마을 파일이 아니라 각각의 공용 시스템(shop_system.py 등)에서 관리한다.
# 따라서 이 양식에는 포함하지 않는다.
#
# 화면 하단의 파티 상태 표시도 마을 전용이 아니라 전투 화면과 공유하는 UI라
# ui_system.py 쪽 공용 코드를 그대로 불러와 쓰고, 여기서는 다루지 않는다.
#
# 각 파일은 "마을정보" 딕셔너리 하나만 담는다.

# =====================================================
# <마을정보 항목 양식>
# =====================================================
#
# "마을명"     : 문자열                   예) "엘븐가드"
#
# "상세지역"   : 문자열의 리스트           (이 마을이 속한 상위 지역들을, 큰 것부터 작은 순서로)
#                                        예) ["아라드", "벨마이어 공국 북부"]
#
# "배경이미지" : 문자열                   (마을 화면 가운데에 띄울 배경 그림의 파일명.
#                                        game/assets/town/ 안의 파일명만 적는다.
#                                        예) "asset_town_elvengard.webp"
#                                        "미정"이거나 파일이 없으면 그림 없이 표시한다.
#                                        screens_town.py 마을화면 참고)
#
# "던전목록"   : [던전 맵 파일명, ...]     (이 마을에서 [던전이동]으로 갈 수 있는 소형지도 목록.
#                                        map_01A_DXX 형식의 파일명과 일치해야 함)
#
# "개방조건"   : <개방조건 항목> 또는 None (이 마을이 [마을이동] 목록에 뜨기 위한 조건.
#                                        시작 마을처럼 조건이 없으면 None)

# =====================================================
# <개방조건 항목 양식>
# =====================================================
#
# {
#     "타입" : "던전클리어" | 기타 문자열,
#     "대상" : 문자열,                     (예: 던전 맵 파일명. "타입"에 따라 의미가 달라짐)
# }