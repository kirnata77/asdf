# - 방 구역 안의 낱개 "X"들은 숲의 자연스러운 장애물 텍스처 느낌으로
#   임의 배치한 것이다 - 마음에 드는 배치가 아니면 얼마든지 바꿔도 된다.
# - "입장좌표"를 (1,3)으로 지정했다 - 엘븐가드의 [던전 이동] 목록에서
#   곧바로 들어올 때(연결지역을 거치지 않는 경우) 이 좌표에서 시작한다.
#   지정하지 않으면 그리드를 훑어 처음 만나는 칸(여기선 (1,1))에서
#   시작해 버려서, 서쪽 문(0,3) 바로 안쪽인 (1,3)으로 명시했다
