# =====================
# 맵 공용 함수
# =====================
# 특정 맵에 종속되지 않고, 여러 맵 파일이 공통으로 쓰는 함수를 모아둔다.


def 통행가능화(맵정보, 좌표):
    """
    map_format.py의 오브젝트 항목 양식 중 "클리어시": "통행가능화" 효과를 실제로 적용한다.
    전투 승리 등으로 오브젝트가 클리어됐을 때 호출하면,
    "지도"에서 해당 좌표를 "@"에서 "O"로 바꿔준다.

    맵정보 : map_format.py 양식을 따르는 "맵정보" 딕셔너리
    좌표   : (x, y) 튜플, "오브젝트" 딕셔너리의 키와 같은 좌표
    """
    x, y = 좌표
    행 = list(맵정보["지도"][y])
    행[x] = "O"
    맵정보["지도"][y] = "".join(행)
