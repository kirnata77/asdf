#   통행을 막을 필요는 없지만 클리어 기록을 남기려고 다른 던전과 동일하게
#   "클리어시":"통행가능화"를 적용했다.
# - 입구였던 첫 번째 방의 "아랫줄"(5행) 가운데(3,5)에 "숏컷" 이벤트칸을
#   뒀다. 처음엔 "@"라 그 아래(3,6) 연결지역(포이즌 선더랜드)으로 갈 수
#   없고, 이 던전 자신의 전투이벤트(25,3)를 한 번이라도 클리어하면
#   "O"로 열린다 - 같은 던전 안의 좌표를 가리키므로 "필요던전파일명"은
#   생략했다(map_format.py <해금조건 항목 양식> 참고).
# - 같은 방의 "윗줄"(1행) 가운데(3,1)에도 "숏컷" 이벤트칸을 하나 더
#   뒀다. 이번엔 그 위(3,0) 연결지역("어둠의 선더랜드")으로 가는 길을
#   막고 있는데, 조건이 이 던전이 아니라 다른 던전
#   ("불타는 그락카락" - map_01A_D09_blazing_grakquarak)의 전투이벤트라
#   "해금조건"에 "필요던전파일명"을 명시했다(머크우드의 (3,5)와 같은
#   방식 - map_01A_D03_mirkwood.py 참고).
# - 나무(X) 배치는 랜덤 텍스처이며 의미는 없다.
# - "입장좌표"를 (1,3)으로 지정했다 - 헨돈마이어의 [던전 이동] 목록에서
#   곧바로 들어올 때(연결지역을 거치지 않는 경우) 이 좌표에서 시작한다.
#   서쪽 문(0,3) 바로 안쪽이다(map_system.던전_시작() 참고).
#
