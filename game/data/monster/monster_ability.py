# =====================
# 몬스터 종족 특성 / 개별 특성
# =====================
# monster_tier_01.py 등 몬스터 데이터의 "특성" 리스트(예: ["종족:고블린"])가
# 이 "특성목록"의 키를 가리킨다. 전투에서는 gameflow.py가 이 목록과 공용
# 특성(job_ability_0000.py - "종족:루가루"/"종족:인간" 등)을 합쳐
# combat.flow.전투_시작()의 "특성정의모음"으로 넘긴다.
#
# 양식은 job_ability_format.py를 따르되, "분류"는 캐릭터용 분류 대신
# 아래 두 가지를 쓴다.
#   "종족특성"   - 한 종족 전체가 공통으로 갖는 특성 (예: 종족:고블린)
#   "몬스터특성" - 몬스터 개체 하나만 갖는 개별 특성 (예: 빙결의 마녀)
#
# =====================
# "효과" 형태별 엔진 처리 (combat 패키지)
# =====================
# 1) 상시 효과 - "효과"가 {"변동대상", "변동값"} 딕셔너리의 리스트
#    특성_수치()가 합산해 전투 수치에 바로 반영한다. 쓸 수 있는 변동대상:
#    AC / 최대HP / 데미지보너스 / 명중보너스 / 속도("속도보너스"도 같은 뜻) /
#    방어력 / 보호률 / 치명타범위 / 행동보너스.
#    "변동값"은 숫자 또는 "레벨×건강보정치" 같은 수식 문자열(몬스터의
#    레벨/차수/능력치로 평가).
#    "저항"/"취약"은 변동값에 속성 이름(짧은 표기: "암", "명" 등)을 적는다 -
#    피해 배율(저항 0.5배 / 취약 2배)로 반영된다.
#    예) 종족:고블린, 종족:타우, 종족:좀비, 체력증가
#
# 2) 조건부효과 - 상시 효과와 별도로 조건이 맞을 때만 더해지는 효과
#    "조건부효과": {"발동조건": ..., "조건값": ..., "효과": [상시 효과와 같은 리스트]}
#    지금 엔진이 판정하는 "발동조건"은 "적상태"(상대 진영 생존자 중
#    "조건값" 이름의 상태이상을 가진 자가 있음) 하나뿐이다.
#    예) 종족:좀비 - '출혈' 상태인 적이 있으면 속도보너스 +7, 명중보너스 +1
#
# 3) 트리거형 효과 - "효과"가 "종류"를 가진 딕셔너리 하나
#    (job_skill_format.py <효과 하위 양식>을 몬스터 특성에 재사용한 형태)
#    "발동조건"에 따라 아래 시점에 발동한다.
#    - "공격명중시"   : 이 몬스터의 공격이 명중할 때마다(피격_처리).
#                       "종류":"상태이상"만 처리. 예) 화염의 마녀, 빙결의 마녀
#    - "턴종료시"     : 이 몬스터의 턴이 끝날 때. "종류":"데미지",
#                       "타겟":"적전체"만 처리. 예) 냉기방출
#    - ["OO 해제시"]  : 이 몬스터에게서 상태이상 OO가 사라질 때 - 지속턴
#                       만료, 또는 스킬의 "상태이상해제"로 지워질 때.
#                       "종류":"데미지+상태이상", "타겟":"적전체"만 처리.
#                       예) 기상 충격파
#    - "전투시작시"   : 전투 시작 때 한 번(combat.traits.전투시작_특성).
#                       "종류":"임시생명력", "타겟":"자신"만 처리.
#                       "수치"의 "OO수"는 "집계조건"으로 센 값으로 바꿔
#                       평가한다. 예) 겁쟁이
#    "발동조건_주체"/"발동조건_상황"은 사람이 보는 설명용이다(엔진은 읽지 않는다).
#
