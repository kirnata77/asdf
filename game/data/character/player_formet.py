# =====================
# 플레이어 양식
# =====================
# 파티(4인 캐릭터 모음) 전체가 공유하는 값을 담는 참고용 파일이다.
# 실제 플레이어 데이터는 들어있지 않다.
#
# 캐릭터 개개인의 스테이터스는 character_formet.py가, "누가 파티에
# 속해 있는지"/생존자·어그로 등 파티 단위 조회는 party_system.py가
# 그대로 담당한다. 이 파일은 그 위에서 "파티 전체가 하나만 갖는 값"
# (레벨, 소지품)만 다룬다.

# =====================================================
# <플레이어 항목 양식>
# =====================================================
#
# "레벨"   : 정수                (파티 전체가 공유하는 대표 레벨.
#            캐릭터 개별 "레벨"(character_formet.py)과 항상 같은 값으로
#            맞춘다 - 레벨업 진행 자체(특성/스탯/스킬/퍽/
#            행동 획득)는 여전히 캐릭터 4명이 각자 job_level_XX.py
#            테이블에 따라 개별로 받는다. 이 값은 그 결과 4명의
#            "레벨"이 항상 일치한다는 전제 하의 대표 표시값이다 - 실제로
#            그 동기화를 강제/검증하는 코드는 아직 없다(레벨업을 실제로
#            트리거하는 UI/흐름 자체가 아직 없어서다). 확인 필요할 수 있음.)
#
# "파티"   : party_system.py 파티 딕셔너리 ({"파티원": [...]})
#
# "소지품" : {
#                "골드"        : 정수,
#                "장비"        : {아이템이름: 개수, ...},
#                "소모품"      : {아이템이름: 개수, ...},
#                "포션"        : {아이템이름: 개수, ...},
#                "재료"        : {아이템이름: 개수, ...},
#                "퀘스트아이템" : {아이템이름: 개수, ...},
#            }
#            (골드/장비/소모품/포션/재료/퀘스트아이템이
#            전부 파티가 아니라 이 플레이어 하나에 귀속된다. 장비를
#            포함한 모든 카테고리를 "아이템이름 -> 개수" 형태로
#            통일했다 - 이 프로젝트의 다른 곳(캐릭터 "장착장비", 몬스터
#            "전투몬스터" 등)도 전부 아이템/개체를 "이름"으로만
#            참조하는 방식이라 그 관례를 따랐다. 장비가 인챈트 등 개체별
#            고유값을 가져야 하게 되면 이 형태로는 부족할 수 있다 -
#            확인 필요할 수 있음.)
