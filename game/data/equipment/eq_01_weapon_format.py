# =====================
# 공용 정의 / 무기 양식
# =====================
# 직업별 무기 아이템(eq_01_weapon_010 / 020 / 030 / 040 / 050)의 공용 양식을
# 모아둔 참고용 파일이다. 실제 무기 데이터는 들어있지 않다.
# 각 eq_01_weapon_XX.py 파일의 최상위 딕셔너리(예: 귀검사무기목록)가
# 이 양식을 따른다.
#
# 파일명과 직업 대응 (job_skill_XX 번호 체계와 동일):
#   eq_01_weapon_010 - 귀검사
#   eq_01_weapon_020 - 격투가
#   eq_01_weapon_030 - 거너
#   eq_01_weapon_040 - 마법사
#   eq_01_weapon_050 - 프리스트

# -----------------------------------------------------
# <레어도 배수> (가격 계산에 쓴다)
# -----------------------------------------------------
# 커먼 1 / 언커먼 2 / 레어 3 / 유니크 4 / 레전더리 5 / 에픽 6 / 치트 0
#
# <가격 공식> (장비 전체 공용 - 방어구/악세서리/특수장비 파일에도 적용)
#   무기                      : 5 x 티어 x 레어도배수 x 10
#   방어구/악세서리/특수장비  : 티어 x 레어도배수 x 10
# 레어도 "치트"는 배수가 0이라 가격이 0골드가 된다(테스트용 아이템).

# -----------------------------------------------------
# <무기 항목 양식>
# -----------------------------------------------------
# {
#     "이름"         : 문자열,                      예) "녹슨 소검"
#     "분류"         : 문자열,   (파일 하나 안에서는 고정값)
#                      예) "귀검사 무기" | "격투가 무기" | "거너 무기"
#                          | "마법사 무기" | "프리스트 무기"
#     "타입"         : 문자열,   (무기 세부 종류)
#                      예) "소검" (귀검사 무기의 한 종류)
#     "무기속성"     : "참격" | "타격" | "관통" | "역장"
#     "무기능력치"   : 리스트,   (해당 타입이 쓸 수 있는 스탯 목록.
#                      이 중 가장 높은 스탯으로 명중률/데미지보너스를 계산한다)
#                      예) ["근력"], ["근력", "민첩"]
#     "레어도"       : "커먼" | "언커먼" | "레어" | "유니크" | "레전더리" | "에픽" | "치트"
#                      (새 등급이 필요해지면 여기 추가)
#     "티어"         : 정수,     (차수와 대응)
#                      1 = 1차수(비전직) | 2 = 2차수(1차전직)
#                      3 = 3차수(각성)   | 4 = 4차수(2차각성)
#                      (치트용 아이템은 99)
#     "무기공격력"   : 주사위 문자열,                예) "1d6"
#                      (무기 주사위만. 스탯 보정 없음)
#     "스탯보너스"   : 딕셔너리 (기본값 {}),         예) {"지혜": 1}
#     "AC보너스"     : 정수 (기본값 0),
#     "데미지보너스" : 정수 (기본값 0),
#     "명중률보너스" : 정수 (기본값 0),
#     "속도보너스"   : 정수 (기본값 0),
#     "가격"         : 정수,     (골드. 위 <가격 공식> 참고)
# }
