# =====================
# 방어구 재질별 AC 기준
# =====================
# 방어구 부위는 상의, 하의, 어깨, 벨트, 신발 5개.
# 재질은 천갑 / 가죽 / 경갑 / 중갑 / 판금 5단계.
#
# 하의, 어깨, 벨트, 신발은 마법 부여가 없는 한 아무 능력치도 없다.
#
# 캐릭터 기본AC는 10이고, 방어구 착용으로 얻는 값은 전부 "AC보너스"로 붙는다.
# 최종 AC = 10 + AC보너스 + min(민첩수정치, 민첩상한)
# 민첩상한이 None이면 민첩수정치를 제한 없이 전부 더한다.
# 민첩상한이 0이면 민첩수정치를 아예 더할 수 없다.
#
# 천갑 : AC보너스 0, 민첩 제한 없음
# 가죽 : AC보너스 1, 민첩 제한 없음
# 경갑 : AC보너스 2, 민첩수정치는 +2까지만
# 중갑 : AC보너스 4, 민첩수정치 적용 불가
# 판금 : AC보너스 6, 민첩수정치 적용 불가, 속도보너스 -2
#
# 방어구 항목에는 "가격"(골드)이 들어간다.
# 가격 = 티어 x 레어도배수 x 10 (레어도배수는 eq_01_weapon_format.py 참고)

상의_재질별_AC보너스 = {
    "천갑": {"AC보너스": 0, "민첩상한": None},
    "가죽": {"AC보너스": 1, "민첩상한": None},
    "경갑": {"AC보너스": 2, "민첩상한": 2},
    "중갑": {"AC보너스": 4, "민첩상한": 0},
    "판금": {"AC보너스": 6, "민첩상한": 0, "속도보너스": -2},
}
