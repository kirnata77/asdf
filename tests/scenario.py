"""풀 시나리오 도우미 (docs/scenarios.md, .claude/rules/scenarios.md).

tests/support.py와 달리 전투를 **실제로 굴린다**(`강제_승리` 없음). 전부 gameflow(화면이 부르는
API)를 통해서만 진행하므로, 화면의 버튼 하나가 하는 일과 같은 호출만 쓴다.
"""

import gameflow as gf

import support

_방향_순서 = ("오른쪽", "왼쪽", "아래", "위")


def 실전(상태, 최대반복=300):
    """[자동전투] 버튼과 같은 호출(gf.자동전투_한_턴)로 전투가 끝날 때까지 진행한다.
    조종할 수 없는 아군(만취)의 차례는 화면처럼 턴_넘기기가 대신 진행한다."""
    support.반응_처리(상태)
    for _ in range(최대반복):
        if gf.전투_종료됨(상태):
            return 상태["전투상태"]["종료"]
        if gf.아군_차례인가(상태):
            gf.자동전투_한_턴(상태)
        else:
            gf.턴_넘기기(상태)
    raise AssertionError("전투가 끝나지 않았다")


def 인카운트까지_걷기(상태, 최대걸음=400):
    """던전에서 막히면 방향을 바꿔 가며 걷다가 무작위 인카운트가 뜨면 멈춘다.
    인카운트로 시작된 전투의 적 이름 목록을 돌려준다."""
    방향 = 0
    for _ in range(최대걸음):
        결과 = gf.던전_이동(상태, _방향_순서[방향])
        if 결과["결과"] == "전투시작":
            return [e["이름"] for e in gf.적_목록(상태)]
        if 결과["결과"] != "이동":
            방향 = (방향 + 1) % len(_방향_순서)
    raise AssertionError(f"{최대걸음}걸음 안에 인카운트가 없었다")


def 보상_수령(상태):
    """전투 보상 3칸 중 첫 아이템을 받는다(전부 비었으면 포기 골드). 받은 것을 돌려준다."""
    칸 = gf.전투_보상_칸(상태)
    for 번호, 이름 in enumerate(칸):
        if 이름 is not None:
            return ("아이템", gf.전투_보상_받기(상태, 번호))
    return ("골드", gf.전투_보상_포기(상태))


def 소지품_장비수(상태):
    return dict(상태["소지품"]["장비"])


def 소지품_아이템수(상태):
    """장비/소모품/포션/재료 칸을 합친 {이름: 개수} - 전리품에는 잡템(재료)과 투척 아이템(소모품)도 섞인다."""
    결과 = {}
    for 칸 in ("장비", "소모품", "포션", "재료"):
        for 이름, 개수 in 상태["소지품"].get(칸, {}).items():
            결과[이름] = 결과.get(이름, 0) + 개수
    return 결과


def 파티_HP(상태):
    return {c["캐릭터명"]: c["현재HP"] for c in 상태["파티"]["파티원"]}


def 전투중_아군_HP(상태):
    """전투 참가자 쪽 HP - 결과 정리 전에는 캐릭터 원본에 아직 안 돌아와 있다."""
    return {p["이름"]: p["현재HP"] for p in gf.아군_목록(상태)}


# ------------------------------------------------------------ 스킬 우선 전투 정책

# 쓰는 차례: 해제 -> 회복 -> 버프 -> 자원 -> 소환 -> 공격. 같은 분류 안에서는 보유스킬 순서.
_스킬_차례 = ("해제스킬", "회복스킬", "버프스킬", "자원스킬", "소환스킬", "공격스킬")
# 정책이 다루지 않는 타겟 방식(대상을 하나씩 따로 고르는 팝업이 필요한 스킬)
_정책_제외_타겟 = ("적반복지정",)


def _살아있는_적(상태):
    """지정할 수 있는 적을 HP가 낮은 순으로 준다. 정책은 맨 앞 적을 노리므로 파티 전원이 한 적을
    쓰러질 때까지 집중공격한다(사람이 하는 대로). 적_목록 순서는 전투 중에 바뀌어 그대로 쓰면 피해가 흩어진다."""
    적들 = [
        e for e in gf.적_목록(상태) if e["생존"] and not gf.지정불가_상태인가(상태, e)
    ]
    return sorted(적들, key=lambda e: (e["현재HP"], e["이름"]))


def _스킬_인수(상태, 시전자, 이름):
    """스킬을 낼 대상 인수를 만든다. 쓸 수 없으면 None."""
    데이터 = 상태["스킬데이터모음"][이름]
    타겟 = gf.스킬_실제_타겟(상태, 데이터)
    if 타겟 in _정책_제외_타겟:
        return None
    if 타겟 and 타겟.startswith("적"):
        적들 = _살아있는_적(상태)
        return {"중심대상": 적들[0]} if 적들 else None
    if 타겟 == "아군단일":
        부상 = [
            a
            for a in gf.아군_목록(상태)
            if a["생존"] and a["현재HP"] * 2 <= gf.캐릭터_최대HP(상태, a["원본"])
        ]
        return {"중심대상": min(부상, key=lambda a: a["현재HP"])} if 부상 else None
    return {}


def _쓸_가치가_있나(상태, 시전자, 이름, 사용기록):
    """버프/해제/회복/자원/소환은 효과가 있을 때만 쓴다(같은 버프를 계속 갱신하지 않는다)."""
    데이터 = 상태["스킬데이터모음"][이름]
    분류 = 데이터.get("분류")
    라운드 = 상태["전투상태"]["라운드"]
    if 분류 == "버프스킬":
        지속 = 데이터.get("지속턴")
        직전 = [
            r["라운드"]
            for r in 사용기록
            if r["스킬"] == 이름 and r["시전자"] == 시전자["이름"]
        ]
        if 지속 is None and 데이터.get("버프획득"):
            # 버프 정의의 지속(예: 카잔버프 "전투종료")을 따른다 - 한 전투에 한 번
            return not 직전
        지속 = 지속 if isinstance(지속, int) else 3  # 수식이면 짧게 본다
        return not 직전 or 라운드 >= max(직전) + 지속
    if 분류 == "해제스킬":
        return any(
            a["상태이상"] or a["디버프"] for a in gf.아군_목록(상태) if a["생존"]
        )
    if 분류 == "자원스킬":
        return not 시전자.get("보유자원")
    if 분류 == "소환스킬":
        return not 시전자.get("소환수")
    return True


def 스킬_고르기(상태, 시전자, 사용기록):
    """지금 쓸 스킬 하나와 인수 (이름, 인수). 쓸 게 없으면 None."""
    보유 = 시전자["원본"]["보유스킬"]
    for 분류 in _스킬_차례:
        for 이름 in 보유:
            데이터 = 상태["스킬데이터모음"][이름]
            if 데이터.get("분류") != 분류:
                continue
            if not gf.스킬_사용_가능여부(상태, 시전자, 이름)[0]:
                continue
            if not _쓸_가치가_있나(상태, 시전자, 이름, 사용기록):
                continue
            인수 = _스킬_인수(상태, 시전자, 이름)
            if 인수 is not None:
                return 이름, 인수
    return None


def 스킬_우선_턴(상태, 사용기록):
    """아군 한 차례: 쓸 수 있는 스킬을 차례대로 쓰고, 남은 일반행동은 일반공격에 쓴 뒤 턴을 넘긴다.
    스킬을 쓸 때마다 사용기록에 {스킬, 분류, MP소모, 행동소비, ...}를 더한다."""
    시전자 = gf.현재_턴_참가자(상태)
    전투상태 = 상태["전투상태"]
    for _ in range(20):  # 무한 반복 방지(행동이 안 줄어드는 버그가 있어도 멈춘다)
        if 전투상태["종료"] is not None or not 시전자["생존"]:
            break
        선택 = 스킬_고르기(상태, 시전자, 사용기록)
        if 선택 is None:
            break
        이름, 인수 = 선택
        MP전, 자원전 = 시전자["현재MP"], dict(시전자["행동자원"])
        효과전 = 효과_스냅샷(상태)
        적HP전 = sum(e["현재HP"] for e in gf.적_목록(상태))
        아군HP전 = {a["이름"]: a["현재HP"] for a in gf.아군_목록(상태)}
        gf.아군_스킬사용(상태, 이름, **인수)
        사용기록.append(
            {
                "시전자": 시전자["이름"],
                "라운드": 전투상태["라운드"],
                "스킬": 이름,
                "분류": 상태["스킬데이터모음"][이름]["분류"],
                "MP소모": MP전 - 시전자["현재MP"],
                "행동소비": {
                    k: 자원전[k] - v
                    for k, v in 시전자["행동자원"].items()
                    if k in 자원전 and 자원전[k] != v
                },
                "효과전": 효과전,
                "효과후": 효과_스냅샷(상태),
                "적HP변화": sum(e["현재HP"] for e in gf.적_목록(상태)) - 적HP전,
                "아군HP변화": {
                    a["이름"]: a["현재HP"] - 아군HP전.get(a["이름"], a["현재HP"])
                    for a in gf.아군_목록(상태)
                },
            }
        )
    else:
        raise AssertionError("한 차례에 스킬을 20번 넘게 썼다 - 행동이 줄지 않는다")
    if 전투상태["종료"] is not None:
        return
    적들 = _살아있는_적(상태)
    while 시전자["행동자원"].get("일반행동", 0) > 0 and 적들 and 시전자["생존"]:
        gf.아군_일반공격(상태, 적들[0])
        if 전투상태["종료"] is not None:
            return
        적들 = _살아있는_적(상태)
    gf.턴_넘기기(상태)


def 효과_스냅샷(상태):
    """모든 참가자의 버프/디버프/상태이상을 {참가자: {"버프": {이름: 지속턴}, ...}}로 얻는다."""
    return {
        p["이름"]: {
            "버프": {b["이름"]: b.get("지속턴") for b in p["버프"]},
            "디버프": {b["이름"]: b.get("지속턴") for b in p["디버프"]},
            "상태이상": sorted(x["이름"] for x in p["상태이상"]),
        }
        for p in 상태["전투상태"]["참가자"]
        if p["생존"]
    }


def 스킬_실전(상태, 사용기록, 효과기록=None, 최대반복=300):
    """전투가 끝날 때까지 아군은 스킬 우선 정책으로, 몬스터는 gameflow가 알아서 진행한다.
    효과기록 리스트를 주면 아군 차례가 시작될 때마다 {라운드, 시전자, 효과: 효과_스냅샷}을 더한다."""
    support.반응_처리(상태)
    for _ in range(최대반복):
        if gf.전투_종료됨(상태):
            return 상태["전투상태"]["종료"]
        참가자 = gf.현재_턴_참가자(상태)
        if 참가자["진영"] == "아군" and 참가자["생존"]:
            if 효과기록 is not None:
                효과기록.append(
                    {
                        "라운드": 상태["전투상태"]["라운드"],
                        "시전자": 참가자["이름"],
                        "효과": 효과_스냅샷(상태),
                    }
                )
            스킬_우선_턴(상태, 사용기록)
        else:
            gf.턴_넘기기(상태)
    raise AssertionError("전투가 끝나지 않았다")


# ------------------------------------------------------------ 밸런스 측정 조건 (사용자 지정 2026-10-13)
# 수치를 재는 전투 시뮬레이션은 앞으로 이 조건을 쓴다(.memory/roadmap/game-rules.md "밸런스 측정 조건").
# - 스킬: 골드를 내고 배우는 스킬([스킬습득], 모두 50골드)은 배우지 않는다 - 레벨업으로 얻는 스킬만.
# - 장비: 레벨별로 파티 순서대로 앞의 N명이 지금 무기와 같은 종류의 언커먼 무기를 낀다.
# - 포션: 전투마다 초보자용 HP 포션 1개. 조종하는 아군이 자기 차례에 HP가 절반 이하면 먼저 마신다.

언커먼무기_인원 = {1: 0, 2: 1, 3: 2, 4: 3, 5: 4}
측정_포션 = "초보자용 HP 포션"


def 측정_파티_준비(상태, 레벨):
    """밸런스 측정 조건으로 파티를 레벨까지 키우고(골드 스킬 없이) 언커먼 무기를 끼운 뒤 휴식한다."""
    파티 = 상태["파티"]["파티원"]
    for 캐릭터 in 파티:
        support.성장(상태, 캐릭터, 레벨)
    무기들 = 상태["상점카탈로그"]["장비"]["무기"]
    for 캐릭터 in 파티[: 언커먼무기_인원.get(레벨, len(파티))]:
        종류 = gf.캐릭터_장착아이템(상태, 캐릭터, "무기")["타입"]
        이름 = sorted(
            n
            for n, i in 무기들.items()
            if i.get("레어도") == "언커먼" and i["타입"] == 종류 and "치트" not in n
        )[0]
        상태["소지품"]["골드"] = 상태["소지품"].get("골드", 0) + 무기들[이름]["가격"]
        gf.상점_구매(상태, "장비", "무기", 이름, 1)
        gf.장비_교체(상태, 캐릭터, "무기", 이름)
    gf.휴식(상태)


def 측정_실전(상태, 사용기록=None, 최대반복=300):
    """밸런스 측정 조건의 전투 - 스킬 우선 정책 + 전투당 초보자용 HP 포션 1개. 종료 결과를 돌려준다."""
    사용기록 = [] if 사용기록 is None else 사용기록
    상태["소지품"].setdefault("포션", {})[측정_포션] = 1
    마심 = False
    support.반응_처리(상태)
    for _ in range(최대반복):
        if gf.전투_종료됨(상태):
            return 상태["전투상태"]["종료"]
        참가자 = gf.현재_턴_참가자(상태)
        if 참가자["진영"] != "아군" or not 참가자["생존"]:
            gf.턴_넘기기(상태)
            continue
        if (
            not 마심
            and 참가자["현재HP"] * 2 <= gf.캐릭터_최대HP(상태, 참가자["원본"])
            and 참가자["행동자원"].get("보조행동", 0) > 0
        ):
            gf.아군_포션사용(상태, 측정_포션)
            마심 = True
        스킬_우선_턴(상태, 사용기록)
    raise AssertionError("전투가 끝나지 않았다")
