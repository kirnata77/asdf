    소지품 = {"포션": {"a": 2}}
    포션시스템.소지품_차감(소지품, "a")
    포션시스템.소지품_차감(소지품, "a")
    assert 소지품["포션"] == {}
    with pytest.raises(ValueError):
        포션시스템.소지품_차감(소지품, "a")
