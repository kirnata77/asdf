def test_구매_성공과_오류(카탈로그):
    p = _플레이어(골드=35)
    assert 상점.구매_처리(p, 카탈로그, "소모품", "포션", "초보자용 HP 포션", 3) == 30
    assert p["소지품"]["골드"] == 5 and p["소지품"]["포션"] == {"초보자용 HP 포션": 3}
    assert 상점.구매_처리(p, 카탈로그, "소모품", "투척 아이템", "돌맹이", 5) == 5
