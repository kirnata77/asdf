"""마법으로 봉인된 장비의 봉인해제/봉인변환과 "마법의 ~" 장비(2026-10-15 사용자 결정).

규칙은 .memory/roadmap/game-rules.md "마법으로 봉인된 장비".
"""

import pytest

import gameflow as gf
from game.data.equipment.eq_00_magic_seal import 마봉능력
from game.system import collection_system, loot_system, magic_seal_system
from tests import support


def _무기(상태, 이름):
    return 상태["상점카탈로그"]["장비"]["무기"][이름]


def _준비(골드=1000, 소울=5, 봉인="마법으로 봉인된 소검"):
    상태 = support.새게임([("", "귀검사")])
    상태["소지품"]["골드"] = 골드
    상태["소지품"]["재료"]["레어 소울"] = 소울
    상태["소지품"]["장비"][봉인] = 1
    return 상태


# ------------------------------------------------------------------ 카탈로그


def test_마법의_장비는_봉인_장비와_그_부위의_마봉능력마다_카탈로그에_있다():
    상태 = support.새게임()
    장비 = 상태["상점카탈로그"]["장비"]
    강타 = 장비["무기"]["마법의 강타 소검"]
    봉인 = 장비["무기"]["마법으로 봉인된 소검"]
    assert 강타["봉인원본"] == "마법으로 봉인된 소검" and 강타["마봉능력"] == "강타"
    assert 강타["레어도"] == "레어" and 강타["타입"] == "소검"
    assert 강타["명중률보너스"] == 봉인["명중률보너스"]
    assert "마법의 근력 천갑 상의" in 장비["상의"]
    assert "마법의 강타 천갑 상의" not in 장비["상의"]  # 강타는 무기에만
    assert "마법의 근력 소검" not in 장비["무기"]  # 능력치는 방어구에만
    for 탭, 아이템들 in 장비.items():
        for 이름, 아이템 in 아이템들.items():
            if "마봉능력" in 아이템:
                assert 탭 in 마봉능력[아이템["마봉능력"]]["부위"], 이름


def test_장비_칸으로_되는_마봉능력은_마법의_장비_수치에_더해진다():
    상태 = support.새게임()
    장비 = 상태["상점카탈로그"]["장비"]
    봉인 = 장비["무기"]["마법으로 봉인된 소검"]
    assert 장비["무기"]["마법의 집중 소검"]["명중률보너스"] == 봉인["명중률보너스"] + 1
    assert 장비["무기"]["마법의 일격 소검"]["데미지보너스"] == 봉인["데미지보너스"] + 2
    assert 장비["무기"]["마법의 맹속 소검"]["속도보너스"] == 봉인["속도보너스"] + 1
    assert 장비["무기"]["마법의 맹타 소검"]["집요함"] == 1
    assert 장비["상의"]["마법의 회피 천갑 상의"]["AC보너스"] == (
        장비["상의"]["마법으로 봉인된 천갑 상의"]["AC보너스"] + 1
    )
    assert 장비["상의"]["마법의 근력 천갑 상의"]["스탯보너스"]["근력"] == 1
    # 대상타입이 붙은 데미지보너스(사냥꾼)는 그냥 더하지 않는다 - 마봉효과로 남는다
    사냥꾼 = 장비["무기"]["마법의 사냥꾼 소검"]
    assert 사냥꾼["데미지보너스"] == 봉인["데미지보너스"]
    assert 사냥꾼["마봉효과"] == 마봉능력["사냥꾼"]["효과"]


def test_마법의_장비는_도감_드랍_레어_항아리_목록에_안_나온다():
    상태 = support.새게임()
    장비 = 상태["상점카탈로그"]["장비"]
    assert not any("마봉능력" in a for a in collection_system.장비_목록(장비, "무기"))
    for _ in range(50):
        이름 = loot_system.레어도_장비_뽑기(장비, "레어")
        assert not 이름.startswith("마법의 "), 이름


# ------------------------------------------------------------------ 봉인해제 / 봉인변환


def test_봉인해제는_100골드와_레어_소울로_그_부위의_능력_하나를_붙인다():
    상태 = _준비()
    [항목] = [h for h in gf.전문직업_봉인목록(상태, "봉인해제") if h["캐릭터"] is None]
    assert 항목["이름"] == "마법으로 봉인된 소검" and 항목["수량"] == 1
    새이름 = gf.전문직업_봉인해제(상태, 항목)
    능력 = _무기(상태, 새이름)["마봉능력"]
    assert 새이름 == f"마법의 {능력} 소검" and "무기" in 마봉능력[능력]["부위"]
    assert 상태["소지품"]["장비"].get("마법으로 봉인된 소검", 0) == 0
    assert 상태["소지품"]["장비"][새이름] == 1
    assert 상태["소지품"]["골드"] == 900
    assert 상태["소지품"]["재료"]["레어 소울"] == 4


@pytest.mark.parametrize("골드, 소울", [(99, 5), (1000, 0)])
def test_골드나_레어_소울이_모자라면_아무것도_안_바뀐다(골드, 소울):
    상태 = _준비(골드=골드, 소울=소울)
    [항목] = gf.전문직업_봉인목록(상태, "봉인해제")
    with pytest.raises(ValueError):
        gf.전문직업_봉인해제(상태, 항목)
    assert 상태["소지품"]["장비"]["마법으로 봉인된 소검"] == 1
    assert 상태["소지품"]["골드"] == 골드


def test_장착_중인_봉인_장비도_풀면_장착한_채로_바뀐다():
    상태 = _준비()
    귀검사 = 상태["파티"]["파티원"][0]
    gf.장비_교체(상태, 귀검사, "무기", "마법으로 봉인된 소검")
    [항목] = gf.전문직업_봉인목록(상태, "봉인해제")
    assert 항목["캐릭터"] is 귀검사 and 항목["슬롯"] == "무기"
    새이름 = gf.전문직업_봉인해제(상태, 항목)
    assert 귀검사["장착장비"]["무기"] == 새이름
    assert gf.캐릭터_장착아이템(상태, 귀검사, "무기")["이름"] == 새이름


def test_봉인변환은_지금_능력을_뺀_다른_능력으로_바꾼다():
    상태 = _준비(봉인="마법의 강타 소검")
    assert gf.전문직업_봉인목록(상태, "봉인해제") == []
    for _ in range(20):
        [항목] = gf.전문직업_봉인목록(상태, "봉인변환")
        전 = 항목["이름"]
        새이름 = gf.전문직업_봉인변환(상태, 항목)
        assert 새이름 != 전 and 새이름.endswith(" 소검")
        assert "무기" in 마봉능력[_무기(상태, 새이름)["마봉능력"]]["부위"]
        상태["소지품"]["골드"] = 1000
        상태["소지품"]["재료"]["레어 소울"] = 5


def test_봉인해제_뒤에도_세이브_왕복으로_장비가_남는다(임시_세이브폴더):
    상태 = _준비()
    [항목] = gf.전문직업_봉인목록(상태, "봉인해제")
