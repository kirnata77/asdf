_방향 = {(0, -1): "위", (0, 1): "아래", (-1, 0): "왼쪽", (1, 0): "오른쪽"}


def 경로(그리드, 시작, 목표):
    """이동 가능한 칸(O/#)만 밟아 시작 -> 목표로 가는 방향 목록(BFS, 최단).
    목표 칸 자체는 무엇이든 된다(오브젝트 "@" 앞까지 가서 말걸기용)."""
    이전 = {시작: None}
    큐 = deque([시작])
    while 큐:
        x, y = 큐.popleft()
        if (x, y) == 목표:
            break
        for dx, dy in _방향:
            n = (x + dx, y + dy)
            if n in 이전:
                continue
            문자 = (
                그리드[n[1]][n[0]]
                if 0 <= n[1] < len(그리드) and 0 <= n[0] < len(그리드[n[1]])
                else None
            )
            if n == 목표 or 문자 in ("O",):
                이전[n] = (x, y)
                큐.append(n)
    if 목표 not in 이전:
        return None
    결과 = []
    칸 = 목표
    while 이전[칸] is not None:
        p = 이전[칸]
        결과.append(_방향[(칸[0] - p[0], 칸[1] - p[1])])
        칸 = p
    return 결과[::-1]


def 걸어가기(상태, 목표, 기록=None, 전투처리=강제_승리):
    """던전_이동으로 목표 칸까지 걷는다. 인카운트가 뜨면 전투처리 후 정리하고
    같은 방향으로 다시 걷는다. 마지막 이동 결과를 돌려준다."""
    기록 = 기록 if 기록 is not None else []
    while True:
        던전 = 상태["던전상태"]
        if 던전["위치"] == 목표:
            return None
        방향들 = 경로(던전["그리드"], 던전["위치"], 목표)
        assert 방향들, f"{던전['던전파일명']}: {던전['위치']} -> {목표} 경로 없음"
        결과 = gf.던전_이동(상태, 방향들[0])
        if 결과["결과"] == "전투시작":
            기록.append(
                (
                    "인카운트",
                    던전["던전파일명"],
                    결과["위치"],
                    [e["이름"] for e in gf.적_목록(상태)],
                )
            )
            전투처리(상태)
            gf.전투_결과_정리(상태)
            continue
        if 결과["결과"] != "이동" or 결과["위치"] == 목표:
            return 결과


def 보스_처치(상태, 기록=None, 전투처리=강제_승리):
    """현재 던전의 보스 오브젝트 앞까지 걸어가 말을 걸고 이긴다."""
    던전 = 상태["던전상태"]
    위치, 오브젝트 = next(
        (p, o)
        for p, o in 던전["맵정보"]["오브젝트"].items()
        if o.get("타입") == "보스전투"
    )
    x, y = 위치
    앞칸 = next(
        p
        for p in ((x - 1, y), (x, y - 1), (x, y + 1), (x + 1, y))
        if 경로(던전["그리드"], 던전["위치"], p) is not None
        and 던전["그리드"][p[1]][p[0]] == "O"
    )
    걸어가기(상태, 앞칸, 기록, 전투처리)
    assert gf.오브젝트_상호작용(상태, 위치, 오브젝트) == {"결과": "전투시작"}
    전투처리(상태)
    return gf.전투_결과_정리(상태), 위치


def 연결로_나가기(상태, 연결맵, 기록=None):
    """현재 던전에서 연결맵으로 가는 "#" 칸까지 걸어가 연결지역_처리를 한다."""
    던전 = 상태["던전상태"]
    좌표 = next(
        p for p, c in 던전["맵정보"]["연결지역"].items() if c.get("연결맵") == 연결맵
    )
    결과 = 걸어가기(상태, 좌표, 기록)
    assert 결과["결과"] == "이동" and 결과["연결지역"]["연결맵"] == 연결맵
    return gf.연결지역_처리(상태, 결과["연결지역"])


