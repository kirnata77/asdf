def _던전(n):
    return {1: "map_01A_D01_Lorien", 2: "map_01A_D02_Hollow_Lorien", 3: "map_01A_D03_mirkwood",
            4: "map_01A_D04_Hollow_mirkwood", 5: "map_01A_D05_thunderland",
            6: "map_01A_D06_poison_thunderland", 7: "map_01A_D07_frost_mirkwood",
            8: "map_01A_D08_grakquarak", 9: "map_01A_D09_blazing_grakquarak",
            10: "map_01A_D10_shadow_thunderland"}[n]


def _보스(상태, 기록):
    결과, 위치 = 보스_처치(상태, 기록)
    던전 = 상태["던전상태"]
    기록.append(("보스", 던전["던전파일명"], 결과, 상태["진행도"]["플레이어레벨"]))
    assert 던전["그리드"][위치[1]][위치[0]] == "O"  # 통행가능화
    return 결과


