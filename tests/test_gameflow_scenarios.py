def test_인카운트_전투는_던전_이동에서_시작된다(golden):
    random.seed(3)
    상태 = 새게임()
    gf.던전_진입(상태, _던전(1))
    기록 = []
    for _ in range(200):
        결과 = gf.던전_이동(상태, "오른쪽")
        if 결과["결과"] == "전투시작":
            기록.append([e["이름"] for e in gf.적_목록(상태)])
            break
        if 결과["결과"] != "이동":
            gf.던전_이동(상태, "왼쪽")
    assert 기록, "200걸음 안에 인카운트가 없었다"
    assert gf.전투_종료됨(상태) is False
    결과 = support.자동_전투(상태)
    기록.append(결과)
    기록.append(gf.전투_결과_정리(상태))
    기록.append({c["캐릭터명"]: c["현재HP"] for c in 상태["파티"]["파티원"]})
    assert 상태["전투상태"] is None and not gf.전투_종료됨(상태)
    golden("scenario_encounter_seed3", 기록)


