def test_패배하면_기록없이_HP0으로_돌아오고_휴식으로_회복():
    상태 = 새게임()
    gf.던전_진입(상태, _던전(1))
    위치, 오브젝트 = next(iter(상태["던전상태"]["맵정보"]["오브젝트"].items()))
    gf.오브젝트_상호작용(상태, 위치, 오브젝트)
    support.강제_패배(상태)
    assert gf.전투_결과_정리(상태) == "적승리"
