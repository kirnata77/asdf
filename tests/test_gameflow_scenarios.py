def test_주점_영입_대기_합류_추방(임시_세이브폴더):
    """주점: 영입(100골드, 레벨 1, 파티가 차면 모험단 숙소), 대기(파티 최소 1명),
    합류, 추방(장비는 소지품에 남는다). 숙소는 최대 20명, 세이브에 남는다."""
    상태 = 새게임([("철수", "귀검사"), ("", "거너")])
    파티 = 상태["파티"]["파티원"]
    with pytest.raises(ValueError, match="골드가 모자란다"):
        gf.파티원_영입(상태, "", "프리스트")

    상태["소지품"]["골드"] = 10_000
    c, 자리 = gf.파티원_영입(상태, "", "거너")  # 이미 "거너"가 있다 -> 거너A
    assert (c["캐릭터명"], c["레벨"], 자리) == ("거너A", 1, "파티")
    assert 상태["소지품"]["골드"] == 9_900 and c["현재HP"] == gf.캐릭터_최대HP(상태, c)
    assert 상태["소지품"]["장비"][c["장착장비"]["무기"]] >= 1  # 시작 장비도 소지품에
    with pytest.raises(ValueError, match="겹칩니다"):
        gf.파티원_영입(상태, "철수", "마법사")
    assert 상태["소지품"]["골드"] == 9_900  # 실패하면 골드도 그대로

    gf.파티원_영입(상태, "영희", "마법사")
    넷째, 자리 = gf.파티원_영입(상태, "민수", "격투가")
    assert 자리 == "숙소" and len(파티) == 4 and gf.숙소_목록(상태) == [넷째]

    # 대기 - 파티에는 최소 1명
    for p in list(파티)[1:]:
        gf.파티원_대기(상태, p)
    assert [p["캐릭터명"] for p in 파티] == ["철수"]
    with pytest.raises(ValueError, match="최소 1명"):
        gf.파티원_대기(상태, 파티[0])
    with pytest.raises(ValueError, match="최소 1명"):
        gf.파티원_추방(상태, 파티[0])
    assert len(gf.숙소_목록(상태)) == 4

    # 합류 - 파티가 차면 불가
    for p in list(gf.숙소_목록(상태))[:3]:
        gf.파티원_합류(상태, p)
    with pytest.raises(ValueError, match="파티가 가득"):
        gf.파티원_합류(상태, gf.숙소_목록(상태)[0])

    # 숙소 동료의 장비는 다른 캐릭터가 쓰거나 팔 수 없다 -> 추방하면 풀린다
    민수 = gf.숙소_목록(상태)[0]
    무기 = 민수["장착장비"]["무기"]
