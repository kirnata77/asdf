def test_중갑_판금을_입으면_패널티_그_숙련이_있으면_없다():
    from game.system import equipment_system as 장비
    from game.system import skill_system as ss

    상태 = 새게임([("", "귀검사")])
    c = 상태["파티"]["파티원"][0]
    카탈로그 = 상태["상점카탈로그"]["장비"]
    중갑 = 카탈로그["상의"]["녹슨 중갑 상의"]
    판금 = next(i for i in 카탈로그["상의"].values() if i.get("재질") == "판금")
    경갑 = 카탈로그["상의"]["허름한 경갑 상의"]
    기본 = 장비.캐릭터_장비_보너스(c, {"상의": 경갑})
    assert 기본["MP소모배율"] == 1 and 장비.중갑_패널티_재질(c, {"상의": 경갑}) == []

    for 갑옷, 재질 in ((중갑, "중갑"), (판금, "판금")):
        보너스 = 장비.캐릭터_장비_보너스(c, {"상의": 갑옷})
        assert 장비.중갑_패널티_재질(c, {"상의": 갑옷}) == [재질]
        assert 보너스["MP소모배율"] == 2
        assert 보너스["명중률보너스"] == 갑옷.get("명중률보너스", 0) - 1
        assert 보너스["속도보너스"] == 갑옷.get("속도보너스", 0) - 5
    c["보유특성"].append("중갑숙련")  # 중갑만 숙련 - 판금은 여전히 패널티
    assert 장비.캐릭터_장비_보너스(c, {"상의": 중갑})["MP소모배율"] == 1
    assert 장비.중갑_패널티_재질(c, {"상의": 중갑, "하의": 판금}) == ["판금"]

    # 전투에서 MP 소모 2배 (중갑숙련을 빼고 중갑 상의를 입힌다)
    c["보유특성"].remove("중갑숙련")
    상태["소지품"]["장비"]["녹슨 중갑 상의"] = 1
    gf.장비_교체(상태, c, "상의", "녹슨 중갑 상의")
    gf._전투_시작(상태, ["고블린"], 레벨=1, 차수=1)
    p = next(x for x in gf.아군_목록(상태))
    assert stats.MP소모_배율(p) == 2
    while not gf.아군_차례인가(상태):
        gf.턴_넘기기(상태)
    p = gf.현재_턴_참가자(상태)
    전 = p["현재MP"]
    ss.자원_소비_처리(상태["전투상태"], p, {"MP소모": 5, "행동": []})
    assert p["현재MP"] == 전 - 10
