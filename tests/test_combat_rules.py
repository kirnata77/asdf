def _스킬(**kw):
    기본 = {"_이름": "시험", "분류": "공격스킬", "행동": "일반행동", "MP소모": 0}
    기본.update(kw)
    return 기본


def test_사용가능여부_각_사유(전장):
    _, 전투상태, _, 아군 = 전장
