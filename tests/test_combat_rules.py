def test_자원_소비_처리(전장):
    _, 전투상태, _, 아군 = 전장
    p = 아군[0]
    cs._턴_시작_처리(전투상태, p)
    p["보유자원"]["탄약"] = 3
    mp = p["현재MP"]
    ss.자원_소비_처리(전투상태, p, _스킬(행동=["일반행동", "보조행동"], MP소모=5, 자원소모={"탄약": 2},
                                    휴식당횟수=3))
    assert (p["행동자원"]["일반행동"], p["행동자원"]["보조행동"], p["현재MP"]) == (0, 0, mp - 5)
    assert p["보유자원"]["탄약"] == 1
    assert p["이번턴_스킬사용횟수"]["시험"] == 1 and p["전투당_스킬사용횟수"]["시험"] == 1
    assert p["원본"]["횟수제한스킬"]["휴식제한스킬"]["시험"] == 2
    assert cs.자원_소모(전투상태, p, "탄약", 5) == (True, 1)
    assert cs.자원_소모(전투상태, p, "탄약", 1) == (False, 0)
    assert cs.자원_소모(전투상태, p, "류심자세", 1) == (False, 0)  # 기술효과형인데 버프가 없음
    ss.이름있는효과_부여(전투상태, p, "류심자세", 2)
    assert cs.자원_보유량(전투상태, p, "류심자세") == 1  # 최대값 1로 잘린다
    assert cs.자원_소모(전투상태, p, "류심자세", 1) == (True, 1)
    assert cs.자원_보유량(전투상태, p, "류심자세") == 0 and p["버프"] == []
    ss.이름있는효과_부여(전투상태, p, "장전 : 은탄", 5)  # 최대값 1+2차수 = 3
    assert cs.자원_소모(전투상태, p, "장전 : 은탄", 5) == (True, 3)


