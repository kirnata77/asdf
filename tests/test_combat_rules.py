def test_속성_배율(전장):
    _, 전투상태, 적, _ = 전장
    대상 = 적[0]
    대상["원본"] = dict(
        대상["원본"], 저항=["화속성", "수속성"], 취약=["수속성", "명속성"]
    )
    assert (
        damage.속성_정식명("암") == "암속성"
        and damage.속성_정식명("무속성") == "무속성"
    )
    assert damage._피해_속성배율(전투상태, 대상, "화속성") == 0.5
    assert damage._피해_속성배율(전투상태, 대상, "명속성") == 2
    assert damage._피해_속성배율(전투상태, 대상, "수속성") == 1  # 저항+취약 상쇄
    assert damage._피해_속성배율(전투상태, 대상, "화") == 0.5  # 줄임말도 정식명으로
    assert (
        damage._피해_속성배율(전투상태, 대상, ["화속성", "명속성"]) == 2
    )  # 리스트면 가장 큰 배율
    assert damage._피해_속성배율(전투상태, 대상, None) == 1
    assert damage._피해_속성배율(전투상태, 대상, []) == 1


