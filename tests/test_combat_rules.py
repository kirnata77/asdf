def test_수식_평가_문법(monkeypatch):
    _주사위고정(monkeypatch, 3)
    ctx = {"차수": 2, "보정치": 4, "주문시전보정치": 1, "추가공격": 1, "레벨": 5,
           "무기공격력": "1d6", "능력치": {"민첩": 14, "건강": "?"}}
    assert cs.수식_평가(7, ctx) == 7
    assert cs.수식_평가("2차수+보정치", ctx) == 8           # 숫자 뒤 키워드는 곱셈
    assert cs.수식_평가("(차수)d8+주문시전보정치", ctx) == 3 * 2 + 1
    assert cs.수식_평가("민첩보정치+건강보정치", ctx) == 2 + 0  # 숫자 아닌 능력치는 10 취급
    assert cs.수식_평가("보정공격력x2", ctx) == (3 + 4) * 2
    assert cs.수식_평가("무기공격력+추가공격+레벨", ctx) == 3 + 1 + 5
    assert cs.수식_평가("(차수+1)d6÷2", ctx) == 3 * 3 / 2
    assert cs.수식_평가("1d6", ctx, 치명타=True) == 6      # 치명타: 주사위 1개 추가
    assert cs.수식_평가("(0)d6+1", ctx) == 1               # 개수 0이면 0
    with pytest.raises(ValueError, match="처리할 수 없는"):
        cs.수식_평가("귀신보유수", ctx)


