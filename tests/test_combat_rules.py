def test_타겟_확장(전장):
    _, 전투상태, 적, 아군 = 전장
    시전자 = 아군[0]
    assert ss.타겟_확장(전투상태, 시전자, "자신") == [시전자]
    assert ss.타겟_확장(전투상태, 시전자, "아군전체") == [p for p in 전투상태["참가자"] if p["진영"] == "아군"]
    assert ss.타겟_확장(전투상태, 시전자, "적전체") == [p for p in 전투상태["참가자"] if p["진영"] == "적"]
    assert ss.타겟_확장(전투상태, 시전자, "적3체", 적[1]) == 적       # 가운데면 3체
    assert ss.타겟_확장(전투상태, 시전자, "적3체", 적[0]) == 적[:2]   # 구석이면 2체
    적[1]["생존"] = False
    assert ss.타겟_확장(전투상태, 시전자, "적3체", 적[0]) == [적[0]]  # 죽은 칸은 당겨지지 않는다
    assert ss.타겟_확장(전투상태, 시전자, "적3체", 아군[1]) == [아군[1]]
    assert ss.타겟_확장(전투상태, 시전자, "적랜덤")[0] in (적[0], 적[2])
    assert ss.타겟_확장(전투상태, 시전자, "적랜덤반복") == [p for p in 전투상태["참가자"]
                                                    if p["진영"] == "적" and p["생존"]]
    for 종류 in ("아군단일", "적단일", "적3체"):
        with pytest.raises(ValueError, match="지정"):
            ss.타겟_확장(전투상태, 시전자, 종류)
    with pytest.raises(ValueError, match="알 수 없는"):
        ss.타겟_확장(전투상태, 시전자, "하늘")
    ss._상태이상_부여(전투상태, 적[0], "은신", 2, None)
    ss._상태이상_부여(전투상태, 아군[1], "은신", 2, None)
    with pytest.raises(ValueError, match="지정 불가"):
        ss.타겟_확장(전투상태, 시전자, "적단일", 적[0])
    with pytest.raises(ValueError, match="지정 불가"):
        ss.타겟_확장(전투상태, 시전자, "아군단일", 아군[1])
    for p in 적:
        p["생존"] = False
    assert ss.타겟_확장(전투상태, 시전자, "적랜덤") == []


