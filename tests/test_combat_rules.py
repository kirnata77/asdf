def test_효과_범위분배(전장):
    _, 전투상태, 적, 아군 = 전장
    hp = [p["현재HP"] for p in 적]
    로그 = ss.효과_적용(전투상태, 아군[0], 적[1], [{"종류": "범위분배", "대상": "양옆1체씩", "피해량": "주대상피해÷2"}],
                     주대상피해=4)
    assert len(로그) == 2 and 적[0]["현재HP"] == hp[0] - 2 and 적[2]["현재HP"] == hp[2] - 2
    적[2]["생존"] = False
    로그 = ss.효과_적용(전투상태, 아군[0], 적[1], [{"종류": "범위분배", "대상": "양옆1체씩", "피해량": 0.5}],
                     주대상피해=2)
    assert len(로그) == 1  # 죽은 이웃은 건너뛴다
    assert ss.효과_적용(전투상태, 아군[0], 적[0], [{"종류": "범위분배", "대상": "양옆1체씩", "피해량": None}]) == \
        [f"{적[1]['이름']}에게 범위분배 피해 0"]
    assert "지원하지 않는다" in ss.효과_적용(전투상태, 아군[0], 적[0], [{"종류": "범위분배", "대상": "전체"}])[0]


