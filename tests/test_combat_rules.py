def test_속성_면역_강화_내성(전장):
    """면역 0, 속성강화/속성내성 1당 ±10%를 방어력 뒤 최종피해에 곱하고 저항/취약과 곱연산."""
    _, 전투상태, 적, 아군 = 전장
    p, e = 아군[0], 적[0]
    e["원본"] = dict(e["원본"], 면역=["암속성"], 저항=["수속성"], 취약=["명속성"])
    방어력 = stats.유효_방어력(전투상태, e)
    assert damage._피해_속성배율(전투상태, e, "암속성") == 0

    def 피해(속성, 원래=40):
        e["현재HP"] = 999
        return damage.피해_적용(전투상태, e, 원래, 속성=속성, 공격측=p)

    assert 피해("암속성") == 0  # 면역
    기본 = 40 - 방어력
    assert 피해("화속성") == 기본
    p["버프"].append({"이름": "엘레멘탈 번", "중첩": 2})  # 모든 속성강화 +2
    assert 피해("화속성") == round(기본 * 1.2)
    assert 피해("수속성") == round(최종피해(20, 방어력) * 1.2)  # 저항과 곱연산
    assert 피해("명속성") == round(최종피해(80, 방어력) * 1.2)  # 취약과 곱연산
    assert 피해("암속성") == 0  # 면역은 강화와 상관없이 0
    # 속성내성: 대상 쪽, 속성별 - 특정 속성 버프를 데이터 없이 정의에 넣어 확인
    전투상태["버프정의"]["화내성"] = {
        "효과": [{"변동대상": "속성내성", "속성": "화속성", "변동값": 1}]
    }
    e["버프"].append({"이름": "화내성", "중첩": 3})
    assert 피해("화속성") == round(기본 * 1.2 * 0.7)
    assert 피해("무속성") == round(기본 * 1.2)  # 다른 속성은 그대로
    e["버프"][-1]["중첩"] = 15  # 내성 150% -> 0 아래로 안 내려감
    assert 피해("화속성") == 0
    assert damage.피해_적용(전투상태, e, 40, 속성=None) == 기본  # 속성 없음(지속피해)


