def 전투_결과_정리(게임상태):
    """전투가 끝난 뒤, 참가자 인스턴스에만 반영돼 있던 HP/MP를 캐릭터
    원본 데이터로 되돌려 쓴다. combat_system.py/skill_system.py는 이
    동기화를 하지 않는다 - 참가자 인스턴스는 전투 동안만 쓰는 사본이라,
    다음 전투/던전 진행에 반영하려면 호출하는 쪽이 직접 챙겨야 한다.

    승리 시, 이 전투가 던전 오브젝트(보스 등) 클리어로 시작됐다면
    map_system.오브젝트_클리어_처리()(타일 상태 변경)와 함께
    town_system.오브젝트_클리어_기록()(진행도에 영구 기록 - 세이브에
    반영되고, map_format.py "숏컷" 해금 조건에도 쓰인다)도 같이
    호출한다."""
    전투상태 = 게임상태["전투상태"]
    종료결과 = 전투상태["종료"]

    for 참가자 in 아군_목록(게임상태):
        캐릭터 = 참가자["원본"]
        캐릭터["현재HP"] = 참가자["현재HP"]
        캐릭터["현재MP"] = 참가자["현재MP"]

    if 종료결과 == "아군승리":
        클리어위치 = 게임상태.get("전투_클리어위치")
        if 클리어위치 is not None:
            던전상태 = 게임상태["던전상태"]
            던전파일명 = 던전상태["던전파일명"]
            처음클리어 = not town_system.오브젝트_클리어됨(
                게임상태["진행도"], 던전파일명, 클리어위치,
            )
            map_system.오브젝트_클리어_처리(던전상태, 클리어위치)
            town_system.오브젝트_클리어_기록(
                게임상태["진행도"], 던전파일명, 클리어위치,
            )
            # 던전의 보스전투 오브젝트 클리어 = 그 던전 클리어로 기록한다
            # - 헨돈마이어 "개방조건"(로리엔 안쪽 클리어)이 이
            # 기록을 읽는다(town_system.개방조건만족).
            town_system.던전_클리어_처리(게임상태["진행도"], 던전파일명)

            # 보스를 "처음" 클리어했을 때만 플레이어 레벨을 올린다(재도전은
            # 해당 안 됨 - _플레이어레벨업_트리거 참고). 캐릭터 개별 레벨은
            # 파티관리 화면에서 [레벨업]으로 직접 올려야 한다.
            목표레벨 = _플레이어레벨업_트리거.get((던전파일명, 클리어위치))
            if 처음클리어 and 목표레벨 is not None:
                게임상태["진행도"]["플레이어레벨"] = max(
                    게임상태["진행도"]["플레이어레벨"], 목표레벨,
                )

    게임상태["전투상태"] = None
    게임상태["전투_클리어위치"] = None
    게임상태["전투_로그커서"] = 0
    return 종료결과


