# 파일명의 계열 번호(01 귀검사/02 격투가/03 거너/04 마법사/05 프리스트)를
# 그대로 쓰고, 비전직은 끝자리 0을 붙인다(예: 격투가 비전직 = "020").
# 아래 표는 비전직 5개이고, 전직한 캐릭터는 전직_레지스트리의 "분류번호"를
