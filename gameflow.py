def _캐릭터_생성(캐릭터명, 직업):
    정보 = 직업_레지스트리[직업]
    레벨업테이블 = 정보["레벨업테이블"]
    레벨1_항목 = 레벨업테이블[1]

    획득특성이름들 = 레벨1_항목["획득"]["획득특성"]
    if isinstance(획득특성이름들, str):
        획득특성이름들 = [획득특성이름들]
    특성정의모음 = {이름: 정보["특성목록"][이름] for 이름 in 획득특성이름들}

    시작무기데이터 = 정보["무기목록"][레벨1_항목["시작장비"]]
    주문시전능력치 = 레벨1_항목.get("주문시전능력치")

    캐릭터 = 캐릭터생성.캐릭터_생성(
        캐릭터명, 직업, 레벨1_항목, 특성정의모음, 시작무기데이터,
        주문시전능력치=주문시전능력치,
    )

    # 레벨 1 그대로 시작한다.
    캐릭터["현재HP"] = 캐릭터["기본최대HP"]
    캐릭터["현재MP"] = 캐릭터["기본최대MP"]

    # 모험단 프로필(SD 초상화)의 성별 - 기본값 "m", 모험단 화면에서
    # 캐릭터별로 "m"/"f" 토글 가능. 이 값은 캐릭터 딕셔너리에 그대로 붙어
    # 파티원 목록과 함께 세이브된다.
    캐릭터["성별"] = "m"
    # 전직 전에는 None. 새 캐릭터와 불러온 캐릭터가 같은 모양이 되게 처음부터 넣는다
    # (게임_불러오기의 setdefault는 이 키가 없던 구버전 세이브용으로 남겨 둔다).
    캐릭터["전직"] = None

    return 캐릭터


def _장비데이터모음_생성(파티, 상점카탈로그):
    """캐릭터별 장비 데이터({캐릭터명: {슬롯: 아이템데이터}}). 캐릭터
    "장착장비"의 이름을 상점 카탈로그(무기는 5직업 무기 합본)에서 찾아
    실제 데이터로 바꾼다. 방어구/악세서리/특수장비도 들어가므로 전투의
    최종AC 계산 등에 장비 보너스가 반영된다. 빈 슬롯이나 데이터가 없는
    이름은 뺀다."""
    장비카탈로그 = 상점카탈로그["장비"]
    결과 = {}
    for 캐릭터 in 파티["파티원"]:
        슬롯데이터 = {}
        for 슬롯, 이름 in 캐릭터["장착장비"].items():
            if not 이름:
                continue
            아이템 = 장비카탈로그.get(슬롯, {}).get(이름)
            if 아이템 is not None:
                슬롯데이터[슬롯] = 아이템
        결과[캐릭터["캐릭터명"]] = 슬롯데이터
    return 결과


