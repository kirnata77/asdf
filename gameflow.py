def _몬스터목록_합치기(파일목록):
    """종족별 몬스터목록을 하나로 합친다. 같은 이름이 두 파일에 있으면
    어느 파일끼리 겹치는지 적어 오류를 낸다(게임 시작 시 멈춤 - 한쪽이
    조용히 덮어써지는 것을 막는다)."""
    합친목록, 출처, 겹침 = {}, {}, []
    for 파일명, 목록 in 파일목록:
        for 이름, 데이터 in 목록.items():
            if 이름 in 합친목록:
                겹침.append(f"'{이름}' ({출처[이름]} / {파일명})")
            합친목록[이름] = 데이터
            출처[이름] = 파일명
    if 겹침:
        raise ValueError("몬스터 이름이 겹친다: " + ", ".join(겹침))
    return 합친목록


몬스터목록 = _몬스터목록_합치기(_몬스터파일목록)


