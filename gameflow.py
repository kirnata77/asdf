# 파티관리(캐릭터별 레벨업)
# =====================================================
# 몬스터 처치 경험치로는 캐릭터 레벨이 오르지 않는다. 대신 위 전투_결과_정리()가
# 던전 보스 첫 클리어 시 "플레이어 레벨"을 올리고, 캐릭터별 레벨은 이
# 플레이어 레벨 한도 안에서 파티관리 화면의 [레벨업] 버튼을 하나씩 눌러야
# 오른다. [레벨업] 실제 반영은 character_levelup_system.캐릭터_레벨업()에
# 위임한다 - 타입(특성/스탯/스킬/퍽/행동획득)별 처리는 그 함수의 몫이다.

def _선행조건_만족(캐릭터, 선행조건):
    """퍽 선행조건 판정. None=항상 만족,
    문자열=해당 특성 보유, dict={"특성보유"|"스킬보유"|"최소능력치": ...}."""
    if 선행조건 is None:
        return True
    if isinstance(선행조건, str):
        return 선행조건 in 캐릭터["보유특성"]
    if isinstance(선행조건, dict):
        if "특성보유" in 선행조건:
            return 선행조건["특성보유"] in 캐릭터["보유특성"]
        if "스킬보유" in 선행조건:
            return 선행조건["스킬보유"] in 캐릭터.get("보유스킬", [])
        if "최소능력치" in 선행조건:
            return all(
                캐릭터.get(스탯, 0) >= 값
                for 스탯, 값 in 선행조건["최소능력치"].items()
            )
    return True


def _퍽_선택가능(캐릭터, 퍽정의):
    분류 = 퍽정의.get("분류")
    if 분류 == "일반퍽":
        return False
    if not _선행조건_만족(캐릭터, 퍽정의.get("선행조건")):
        return False
    if "획득특성" in 퍽정의:
        return 퍽정의["획득특성"] not in 캐릭터["보유특성"]
    if 분류 == "스킬획득":
        획득스킬 = 퍽정의.get("획득스킬")
        if 획득스킬 is None:
            return False  # "훔쳐배우기"류 - 아직 미지원
        return 획득스킬 not in 캐릭터["보유스킬"]
    return True


def 선택가능_퍽목록(캐릭터):
    """이 캐릭터가 지금 고를 수 있는 (퍽이름, 퍽정의) 목록. 공용퍽
    (perks_class_0000) + 그 직업 퍽목록 중 "일반퍽" 분류·선행조건
    미충족·이미 보유한 것은 뺀다."""
    직업퍽 = 직업_레지스트리[캐릭터["직업"]]["퍽목록"]
    전체 = list(_공용퍽.items()) + list(직업퍽.items())
    return [(이름, 정의) for 이름, 정의 in 전체 if _퍽_선택가능(캐릭터, 정의)]


def 퍽_특성정의_찾기(캐릭터, 퍽정의):
    """퍽정의["획득특성"]의 실제 특성 정의를 그 직업의 특성목록에서
    먼저 찾고, 없으면 공용특성(job_ability_0000)에서 찾는다. "획득특성"이
    없는 퍽이면 None."""
    특성이름 = 퍽정의.get("획득특성")
    if 특성이름 is None:
        return None
    직업특성목록 = 직업_레지스트리[캐릭터["직업"]]["특성목록"]
    return 직업특성목록.get(특성이름) or _공용특성.get(특성이름)


def 캐릭터_직업표시(캐릭터):
    """화면 표시용 직업 이름 - 전직했으면 전직명, 아니면 1차 계열 직업명."""
    return 캐릭터.get("전직") or 캐릭터["직업"]


def _전직_레벨업테이블(캐릭터, 전직명=None):
    전직명 = 전직명 or 캐릭터.get("전직")
    정보 = 전직_레지스트리.get(캐릭터["직업"], {}).get(전직명)
    return 정보["레벨업테이블"] if 정보 else None


def 선택가능_전직목록(캐릭터):
    """[(전직명, 설명, 구현여부)] - 그 직업의 1차 전직 목록(데이터 순서).
    구현된 전직의 설명은 레벨 6 항목의 "획득" 설명(얻는 특성), 미구현은
    "미구현"."""
    결과 = []
    for 전직명, 정보 in 전직_레지스트리.get(캐릭터["직업"], {}).items():
        if 정보["구현"]:
            항목 = 정보["레벨업테이블"].get(_전직_시작레벨, {})
            결과.append((전직명, 항목.get("획득", {}).get("설명", ""), True))
        else:
            결과.append((전직명, "미구현", False))
    return 결과


def 캐릭터_전직_필요(캐릭터):
    """다음 레벨업이 전직(레벨 5 → 6)이라 전직 선택창을 띄워야 하는가
    (구현된 전직이 하나라도 있어야 한다)."""
    return (캐릭터["레벨"] + 1 == _전직_시작레벨 and not 캐릭터.get("전직")
            and any(정보["구현"] for 정보 in 전직_레지스트리.get(캐릭터["직업"], {}).values()))


def 캐릭터_다음_레벨업_항목(캐릭터, 전직명=None):
    """이 캐릭터가 다음에 배울 레벨업테이블(job_level_XX.py) 항목(다음
    레벨의 항목)을 반환한다. 레벨 5까지는 1차 계열 표, 레벨 6부터는
    전직 표를 쓴다(아직 전직 전이면 전직명을 넘겨야 레벨 6 항목이 나온다).
    그 레벨 데이터가 없으면 None."""
    다음레벨 = 캐릭터["레벨"] + 1
    if 다음레벨 >= _전직_시작레벨:
        표 = _전직_레벨업테이블(캐릭터, 전직명)
        return 표.get(다음레벨) if 표 else None
    레벨업테이블 = 직업_레지스트리[캐릭터["직업"]]["레벨업테이블"]
    return 레벨업테이블.get(다음레벨)


def 캐릭터_레벨업_가능(게임상태, 캐릭터):
    """캐릭터 레벨이 플레이어 레벨보다 낮고, 다음 레벨의 레벨업테이블
    항목이 있거나 전직 선택이 가능해야 [레벨업]을 시도할 수 있다."""
    if 캐릭터["레벨"] >= 게임상태["진행도"]["플레이어레벨"]:
        return False
    if 캐릭터_전직_필요(캐릭터):
        return True
    return 캐릭터_다음_레벨업_항목(캐릭터) is not None


def 캐릭터_레벨업_적용(캐릭터, **선택):
    """[레벨업] 확정 시 호출한다. 타입별로 필요한 선택 인자는
    character_levelup_system.캐릭터_레벨업()의 문서를 그대로 따라
    호출하는 쪽이 채워 넘긴다("스탯획득"=배분=.., "퍽획득"=퍽이름=..
    퍽정의=.. 등). 다만 "특성획득" 타입만은 특성정의모음(그 직업의
    전체 특성목록 - 캐릭터 생성 때와 동일)을 이 함수가 직접 채운다."""
    전직명 = 선택.pop("전직", None)
    if 캐릭터_전직_필요(캐릭터):
        # 레벨 5 → 6: 전직 선택. 고른 전직의 레벨 6 항목으로
        # 레벨업하고, 전직 표에 "주문시전능력치"가 있으면 바꾼 뒤 기본최대MP
        # (50 + 10×주문시전보정치)를 다시 계산한다.
        정보 = 전직_레지스트리[캐릭터["직업"]].get(전직명)
        if not 정보:
            raise ValueError("전직을 선택해야 한다.")
        if not 정보["구현"]:
            raise ValueError(f"'{전직명}'은(는) 아직 구현되지 않은 전직이다.")
        레벨업항목 = 캐릭터_다음_레벨업_항목(캐릭터, 전직명)
        캐릭터["전직"] = 전직명
        새스탯 = 레벨업항목.get("주문시전능력치")
        if 새스탯:
            캐릭터["주문시전능력치"] = 새스탯
            보정치 = (캐릭터[새스탯] - 10) // 2
            캐릭터["기본최대MP"] = 50 + 10 * 보정치
            캐릭터["현재MP"] = min(캐릭터["현재MP"], 캐릭터["기본최대MP"])
    else:
        레벨업항목 = 캐릭터_다음_레벨업_항목(캐릭터)
    if 레벨업항목 is None:
        raise ValueError("더 이상 배울 레벨업 항목이 없다.")

    레벨1_항목 = 직업_레지스트리[캐릭터["직업"]]["레벨업테이블"][1]
    기본체력 = 레벨1_항목["기본체력"]
    레벨당체력증가 = 레벨1_항목["레벨당체력증가"]

    if 레벨업항목["타입"] == "특성획득":
        선택.setdefault("특성정의모음", 직업_레지스트리[캐릭터["직업"]]["특성목록"])

    # 고른 퍽 이름을 기록한다(파티원 화면 퍽 탭). 기록이 없던 캐릭터는
    # 먼저 지금까지의 퍽을 추정해 채운다(_보유퍽_추정).
    캐릭터_보유퍽(캐릭터)
    결과 = 캐릭터레벨업.캐릭터_레벨업(
        캐릭터, 레벨업항목, 기본체력, 레벨당체력증가, **선택,
    )
    if 레벨업항목["타입"] == "퍽획득" and 선택.get("퍽이름"):
        캐릭터["보유퍽"].append(선택["퍽이름"])
    return 결과


# =====================================================
# 파티원 화면용 조회
# =====================================================
# screens_party.파티원화면이 쓴다. 전부 읽기 전용이다(캐릭터를 바꾸지 않는다 -
# 캐릭터_보유퍽만 "보유퍽" 키가 없을 때 추정값으로 채운다).

def _캐릭터_전체퍽(캐릭터):
    return {**_공용퍽, **직업_레지스트리[캐릭터["직업"]]["퍽목록"]}


def _보유퍽_추정(캐릭터):
    """"보유퍽" 기록이 생기기 전 캐릭터용 - 퍽이 주는 특성/스킬을 이미 가진
    퍽을 고른 것으로 본다. 능력치향상처럼 흔적이 남지 않는 퍽은 알 수 없다."""
    결과 = []
    for 이름, 정의 in _캐릭터_전체퍽(캐릭터).items():
        if 정의.get("분류") == "일반퍽":
            continue
        획득특성 = 정의.get("획득특성")
        획득스킬 = 정의.get("획득스킬")
        if (획득특성 and 획득특성 in 캐릭터["보유특성"]) or \
                (획득스킬 and 획득스킬 in 캐릭터["보유스킬"]):
            결과.append(이름)
    return 결과


def 캐릭터_보유퍽(캐릭터):
    if "보유퍽" not in 캐릭터:
        캐릭터["보유퍽"] = _보유퍽_추정(캐릭터)
    return 캐릭터["보유퍽"]


def 캐릭터_퍽목록(캐릭터):
    """[(퍽이름, 설명)]"""
    전체 = _캐릭터_전체퍽(캐릭터)
    return [(이름, (전체.get(이름) or {}).get("설명", "")) for 이름 in 캐릭터_보유퍽(캐릭터)]


def 캐릭터_특성목록(캐릭터):
    """[(특성이름, 설명)] - 보유특성 순서 그대로."""
    return [(이름, (_전투용_캐릭터특성정의.get(이름) or {}).get("설명", "(설명 없음)"))
            for 이름 in 캐릭터["보유특성"]]


def 캐릭터_스킬목록(게임상태, 캐릭터):
    """[(스킬이름, 요약, 설명)] - 요약은 "행동 · MP · 휴식당 횟수"."""
    모음 = 게임상태.get("스킬데이터모음") or {}
    결과 = []
    for 이름 in 캐릭터["보유스킬"]:
        데이터 = 모음.get(이름) or {}
        조각 = []
        행동 = 데이터.get("행동")
        if 행동:
            조각.append("/".join(행동) if isinstance(행동, list) else str(행동))
        if 데이터.get("MP소모"):
            조각.append(f"MP {데이터['MP소모']}")
        if 데이터.get("휴식당횟수") is not None:
            남은 = (캐릭터.get("횟수제한스킬", {}).get("휴식제한스킬", {}) or {}).get(이름)
            조각.append(f"휴식당 {데이터['휴식당횟수']}회" + (f" (남은 {남은})" if 남은 is not None else ""))
        결과.append((이름, " · ".join(조각), 데이터.get("설명", "")))
    return 결과


def _상세용_참가자(게임상태, 캐릭터):
    """전투 밖에서 전투 공식(특성/장비/세트 반영)을 그대로 쓰기 위한 임시
    전투상태와 참가자. 캐릭터 사본을 써서 원본은 바꾸지 않는다. 라운드는
    0으로 둬서 첫턴 전용 보너스는 빠진다."""
    import copy
    전투상태 = {
        "참가자": [], "현재턴": 0, "라운드": 0, "로그": [], "종료": None,
        "버프정의": 버프목록, "디버프정의": 디버프목록, "상태이상정의": 상태이상목록,
        "특성정의": _전투용_몬스터특성정의, "캐릭터특성정의": _전투용_캐릭터특성정의,
        "칭호정의": 칭호목록, "세트정의": 방어구세트목록,
    }
    참가자 = combat_system._아군_참가자_생성(copy.deepcopy(캐릭터), 캐릭터_장비데이터(게임상태, 캐릭터))
    참가자["장비보너스"] = equipment_system.장비_보너스_합산(참가자["장비데이터"], 방어구세트목록)
    전투상태["참가자"].append(참가자)
    return 전투상태, 참가자


def _부호(값):
    return f"{값:+d}" if isinstance(값, int) else f"{값:+g}"


def 캐릭터_상세정보(게임상태, 캐릭터):
    """스탯 상세보기 창 내용 - [(제목, [줄, ...]), ...]."""
    cs = combat_system
    전투상태, 참가자 = _상세용_참가자(게임상태, 캐릭터)
    장비 = 참가자["장비보너스"]
    유효 = 캐릭터_유효능력치(게임상태, 캐릭터)

    기본 = [
        f"이름: {캐릭터['캐릭터명']}",
        f"직업: {캐릭터['직업']}" + (f" → {캐릭터['전직']}" if 캐릭터.get("전직") else ""),
        f"레벨: {캐릭터['레벨']}   차수: {cs.차수(참가자)}",
        f"HP: {캐릭터['현재HP']}/{캐릭터_최대HP(게임상태, 캐릭터)}   "
        f"MP: {캐릭터['현재MP']}/{캐릭터_최대MP(게임상태, 캐릭터)}",
    ]

    능력치줄 = []
    for 이름 in ("근력", "민첩", "건강", "지능", "지혜", "매력"):
        원래 = 캐릭터[이름]
        차이 = 유효[이름] - 원래
        보정 = (유효[이름] - 10) // 2
        능력치줄.append(f"{이름}: {유효[이름]}" + (f" (기본 {원래} {_부호(차이)})" if 차이 else "")
                     + f"   보정치 {_부호(보정)}")

    치명 = cs.유효_치명타범위(전투상태, 참가자)
    명중_평타 = (cs.평타_능력치_보정치(전투상태, 참가자) + cs.장비_수치(참가자, "명중률보너스")
              + cs.특성_수치(전투상태, 참가자, "명중보너스", 명중률종류="보정명중률"))
    데미지 = (cs.장비_수치(참가자, "데미지보너스")
            + cs.특성_수치(전투상태, 참가자, "데미지보너스", 명중률종류="보정명중률"))
    속도 = (캐릭터.get("기본속도", 0) + 장비.get("속도보너스", 0)
          + cs.특성_수치(전투상태, 참가자, "속도"))
    전투 = [
        f"AC: {cs.최종AC(전투상태, 참가자)}",
        f"명중 보정(보정명중률): {_부호(명중_평타)}  (평타 능력치: {'/'.join(캐릭터.get('평타스탯') or [])})",
        f"데미지보너스: {_부호(데미지)}",
        f"속도: {_부호(속도)}",
        f"방어력: {cs.유효_방어력(전투상태, 참가자)}   보호률: {cs.유효_보호률(전투상태, 참가자)}",
        f"치명타범위: {치명}~20" if 치명 < 20 else "치명타범위: 20",
    ]
    주문스탯 = 캐릭터.get("주문시전능력치")
    if 주문스탯:
        주문보정 = cs.주문시전_보정치(전투상태, 참가자)
        주문명중 = (주문보정 + cs.장비_수치(참가자, "명중률보너스")
                + cs.특성_수치(전투상태, 참가자, "명중보너스", 명중률종류="주문시전명중률"))
        주문데미지 = (cs.장비_수치(참가자, "데미지보너스")
                  + cs.특성_수치(전투상태, 참가자, "데미지보너스", 명중률종류="주문시전명중률"))
        전투 += [
            f"주문시전능력치: {주문스탯} (보정치 {_부호(주문보정)})",
            f"주문 명중 보정: {_부호(주문명중)}   주문 데미지보너스: {_부호(주문데미지)}",
        ]
    else:
        전투.append("주문시전능력치: 없음")

    행동 = []
    for 종류, 키 in (("일반행동", "기본일반행동"), ("보조행동", "기본보조행동"), ("반응행동", "기본반응행동")):
        보너스 = cs.특성_수치(전투상태, 참가자, "행동보너스", 행동종류=종류)
        행동.append(f"{종류}: {캐릭터.get(키, 0) + 보너스}")
    행동.append(f"추가공격: {캐릭터.get('추가공격', 0)}회")

    장비줄 = [
        f"AC {_부호(장비.get('AC보너스', 0))}   명중 {_부호(장비.get('명중률보너스', 0))}   "
        f"데미지 {_부호(장비.get('데미지보너스', 0))}   속도 {_부호(장비.get('속도보너스', 0))}",
    ]
    스탯보너스 = {k: v for k, v in (장비.get("스탯보너스") or {}).items() if v}
    if 스탯보너스:
        장비줄.append("능력치 " + "  ".join(f"{k} {_부호(v)}" for k, v in 스탯보너스.items()))
    세트 = equipment_system.세트효과_목록(캐릭터_장비데이터(게임상태, 캐릭터), 방어구세트목록)
    if 세트:
        장비줄.append("세트효과: " + ", ".join(정의.get("세트명", "?") for 정의 in 세트))

    return [("기본", 기본), ("능력치", 능력치줄), ("전투", 전투), ("행동", 행동), ("장비 보너스 합계", 장비줄)]
