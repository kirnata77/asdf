def 초상화_코드(캐릭터):
    """캐릭터["직업"]과 캐릭터["성별"]로 SD 초상화 분류번호(예: "020f")를
    계산한다. 아직 분류번호를 모르는 직업(_직업_분류번호에 없음)은
    기본/공용 초상화 "001"+성별로 대체한다. 이 코드에 대응하는 실제 파일이
    없을 때 대신 보여줄 파일을 고르는 처리는 여기가 아니라
    screens_common._캐릭터이미지_경로()에서 한다."""
    분류번호 = _직업_분류번호.get(캐릭터["직업"], "001")
    전직정보 = 전직_레지스트리.get(캐릭터["직업"], {}).get(캐릭터.get("전직"))
    if 전직정보:
        분류번호 = 전직정보["분류번호"]
    성별 = 캐릭터.get("성별", "m")
    return f"{분류번호}{성별}"


