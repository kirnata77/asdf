def 턴_넘기기(게임상태):
    """현재 참가자의 턴을 끝낸다. 다음이 몬스터면 자동으로 행동시키고
    계속 넘겨서, 다시 아군 차례가 되거나 전투가 끝나면 멈춘다(화면 갱신
    타이밍 없이 한 번에 끝까지 진행한다)."""
    전투상태 = 게임상태["전투상태"]

    while True:
        참가자 = skill_system.다음_턴(전투상태)
        if 전투상태["종료"] is not None:
            return
        if 참가자["진영"] == "아군":
            return
        combat_system.몬스터_턴_실행(전투상태, 참가자)
        if 전투상태["종료"] is not None:
            return


