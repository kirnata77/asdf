def 게임_불러오기(슬롯번호):
    플레이어, 진행도 = save_system.게임_불러오기(슬롯번호)
    # "플레이어레벨" 도입 전에 저장된 세이브 호환 처리 - 없으면 세이브에
    # 담긴 캐릭터(플레이어) 레벨을 대신 쓴다.
    진행도.setdefault("플레이어레벨", 플레이어.get("레벨", 1))
    게임상태 = _새_게임상태(플레이어["파티"], 진행도)
    게임상태["소지품"] = 플레이어.get("소지품", player_system.빈_소지품())
    # 구버전 세이브(선택된초상화가 없던 시절) 호환 - _새_게임상태의
    # 기본값(001m)을 그대로 둔다.
    게임상태["선택된초상화"] = 플레이어.get("선택된초상화", "001m")
    # 구버전 세이브(캐릭터에 "성별"이 없던 시절)를 불러올 때 기본값을
