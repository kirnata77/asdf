# 1차 전직 레지스트리: {1차 계열 직업: {전직명: 정보}}.
# 데이터는 각 1차 계열 job_level_XX.py 하단 "전직목록"({전직명: {"분류번호",
# "레벨업테이블파일"}})이다. "레벨업테이블파일"이 있으면 그 파일(레벨 6~10)과
# 이름이 대응하는 job_skill 파일(job_level_ → job_skill_)을 불러와 "구현":True,
# None이면 "구현":False(선택창에 미구현으로 보이고 고를 수 없음). 레벨 5
# 캐릭터가 [레벨업]을 누르면 구현된 것 중 하나를 골라 레벨 6이 된다.

def _전직정보_생성(항목):
    파일명 = 항목.get("레벨업테이블파일")
    정보 = {"분류번호": str(항목.get("분류번호") or "")[:3], "구현": False,
          "레벨업테이블": {}, "스킬목록": {}}
    if not 파일명:
        return 정보
    정보["레벨업테이블"] = importlib.import_module(
        f"game.data.job_level.{파일명}").레벨업테이블
    try:
        정보["스킬목록"] = importlib.import_module(
            f"game.data.job_skill.{파일명.replace('job_level_', 'job_skill_', 1)}").스킬목록
    except ImportError:
        정보["스킬목록"] = {}
    정보["구현"] = True
    return 정보


